"""Build parts/15_js_mp_data.js (window.MP) from the recorded runs in ../runs/. Run from anywhere: python3 -B gen_data.py
Fails if the recorded registry does not match the promotion gate replayed here."""
import json, os

H = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(H, "..", "runs")
lab = json.load(open(os.path.join(R, "mp_lab.json")))
xp = json.load(open(os.path.join(R, "xplat.json")))
rest = json.load(open(os.path.join(R, "rest_alias_champion.json")))

ORDER = ["start", "train", "evaluate", "register", "end"]
runs = []
for r in lab["runs"]:
    t, m = r["tags"], r["metrics"]
    runs.append(dict(id=r["id"][:8], mf=t["metaflow.run"].split("/")[1], status=r["status"],
                     lr=float(r["params"]["lr"]), steps=int(r["params"]["steps"]), seed=int(r["params"]["seed"]),
                     split=float(r["params"]["split"]), code=(t["code_sha"] or "")[:12], data=(t["data_sha"] or "")[:12],
                     train=(t["train_sha"] or "")[:12], val=(t["val_sha"] or "")[:12], ckpt=(t.get("ckpt_sha") or "")[:12],
                     val_loss=m.get("val_loss"), train_loss=m.get("train_loss"), train_secs=m.get("train_secs"),
                     platform=t["platform"], torch=t["torch"], user=t["mlflow.user"],
                     start=r["start"], end=r["end"], curve=r["curve"]))
vers = []
for v in lab["versions"]:
    vers.append(dict(v=int(v["version"]), run=v["run"][:8], model=v["source"].split("/")[-1][:10],
                     val_loss=float(v["tags"]["val_loss"]), mf=v["tags"]["metaflow_run"].split("/")[1],
                     code=v["tags"]["code_sha"][:12], ckpt=v["tags"]["ckpt_sha"][:12], created=v["created"]))
# replay the gate: alias moves only on strictly lower held-out loss
champ, hist = None, []
for v in vers:
    prev = champ
    promoted = champ is None or v["val_loss"] < [x for x in vers if x["v"] == champ][0]["val_loss"]
    if promoted:
        champ = v["v"]
    hist.append(dict(v=v["v"], promoted=promoted, prev=prev, champion=champ))
assert str(champ) == lab["aliases"]["champion"], (champ, lab["aliases"])
mf = []
for run in lab["metaflow"]:
    tasks = sorted(run["steps"], key=lambda s: ORDER.index(s["step"]))
    origin = next((s["origin_run"] for s in tasks if s["origin_run"] not in (None, "None")), None)
    mf.append(dict(id=run["id"], ok=run["ok"], origin=origin, created=run["created"],
                   tasks=[dict(step=s["step"], task=s["task"], ok=s["ok"],
                               dur=None if s["end"] is None else round((s["end"] - s["start"]) / 1000, 2),
                               cloned=s["origin_run"] not in (None, "None") and s["step"] in ("start", "train", "evaluate"),
                               arts=[[a["name"], a["sha"], a["bytes"]] for a in s["artifacts"]]) for s in tasks]))
out = dict(note=lab["note"], runs=runs, versions=vers, alias_hist=hist, champion=champ, metaflow=mf,
           storage=lab["storage"], mlmodel=lab["mlmodel"], model_files=lab["model_files"],
           repro_v1=lab["repro_v1_check"], repro=lab["repro_champion"],
           xplat=dict(logged=xp["logged"], every=xp["every_step"], native=xp["native"], container=xp["container"],
                      cmd=xp["cmd"], nck=xp["native_ckpt_sha"], cck=xp["container_ckpt_sha"], cval=xp["container_val_loss"]),
           rest=rest)

# a real excerpt of flow.py (the skeleton lines) and of one run's log
keys = ("class ", "Parameter(", "@step", "@timeout", "def ", "self.next", "cmd = [", "\"--master-addr\"", "subprocess.run(", "self.ckpt = ",
        "self.val_loss, _, ", "registered_model_name", "self.promoted = ", "set_registered_model_alias", "assert self.data_sha", "info = C.split_text", "info = mlflow.pytorch.log_model", "input_example=", "pip_requirements=", "if self.promoted:")
fl, last = [], -2
src = open(os.path.join(H, "..", "lab", "flow.py")).read().splitlines()
start = next(i for i, l in enumerate(src) if l.startswith("class TinyGPTFlow"))
for i, l in enumerate(src[start:], start):
    if l.startswith("if __name__"):
        break
    if any(k in l for k in keys):
        if i != last + 1 and fl:
            fl.append("        ...")
        fl.append(l.rstrip()); last = i
runlog = [l for l in open(os.path.join(R, "run_r2.txt")).read().splitlines()
          if "View run" not in l and "View experiment" not in l and not l.startswith(("real", "user", "sys"))]
out["flow_excerpt"] = fl
out["runlog"] = runlog
out["load_champion"] = json.load(open(os.path.join(R, "load_champion.json")))
out["wall"] = json.load(open(os.path.join(R, "wall_secs.json")))
js = "// generated by src/scripts/gen_data.py from src/runs/ (do not edit)\nwindow.MP=" + json.dumps(out, separators=(",", ":")) + ";\n"
p = os.path.join(H, "..", "parts", "15_js_mp_data.js")
open(p, "w").write(js)
print("wrote", p, len(js), "bytes; champion", champ, [h["promoted"] for h in hist])
