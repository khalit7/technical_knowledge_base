#!/usr/bin/env python3
"""Timings for Fig. 3 (the stuck-rank hang as a 3D stage), from the scrubbed run already in runs/.

Reads runs/hang/stuck_OFF/out.txt (the ranks' JSON lines) and events.txt (launch, py-spy and exit wall-clock stamps),
and writes parts/27_js_ld_scdata.js with window.LD_SC. Every time is in seconds since the first rank finished
init_process_group, the clock the rest of section 8 uses. No new run; usage: python3 scripts/ld_scene_data.py (from src/).
"""
import json, os

SRC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(SRC, "runs", "hang", "stuck_OFF")

recs = []
for line in open(os.path.join(D, "out.txt"), errors="replace"):
    for part in line.strip().replace("}{", "}\n{").split("\n"):
        if part.startswith("{"):
            try:
                recs.append(json.loads(part))
            except ValueError:
                pass
ev = {}
for line in open(os.path.join(D, "events.txt")):
    k, *_, v = line.split()
    ev[" ".join(line.split()[:-1])] = float(v)

t0 = min(r["ts"] for r in recs if r["ev"] == "init")
rel = lambda ts: round(ts - t0, 3)
steps = {}
for r in recs:
    if r["ev"] == "step":
        steps.setdefault(r["rank"], []).append([r["step"], rel(r["ts"])])
bug = [r for r in recs if r["ev"] == "bug"][0]
wd = {r["rank"]: [rel(r["ts"]), r["idle_s"]] for r in recs if r["ev"] == "watchdog_dump"}
err = {}
for r in recs:
    if r["ev"] == "error" and r["rank"] not in err:
        err[r["rank"]] = rel(r["ts"])
exit_key = [k for k in ev if k.startswith("exit")][0]
out = {"stuck": {
    "steps": steps, "bug": {"rank": bug["rank"], "t": rel(bug["ts"])}, "watchdog": wd, "errors": err,
    "pyspy": rel(ev["pyspy"]), "pyspy_since_launch": round(ev["pyspy"] - ev["start"], 1),
    "exit": rel(ev[exit_key]), "exit_code": int(exit_key.split()[1]), "launch_to_init": round(t0 - ev["start"], 2)}}
with open(os.path.join(SRC, "parts", "27_js_ld_scdata.js"), "w") as f:
    f.write("// ---- Generated by scripts/ld_scene_data.py from runs/hang/stuck_OFF: timings for Fig. 3 (seconds since init_process_group) ----\n")
    f.write("window.LD_SC=" + json.dumps(out, separators=(",", ":")) + ";\n")
print(json.dumps(out)[:600])
