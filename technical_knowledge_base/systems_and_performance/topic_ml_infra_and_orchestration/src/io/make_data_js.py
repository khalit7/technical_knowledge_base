#!/usr/bin/env python3
"""Storage lab: write parts/34_js_io_0data.js (window.IO_D) from out/io_data.json. Run after summarise.py."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
D = json.load(open(os.path.join(here, "out", "io_data.json")))
D["anatomy"].pop("entry_names_sample", None)
js = ("// ---- Storage lab: recorded measurements (generated by src/io/make_data_js.py from src/io/out/io_data.json; do not edit) ----\n"
      "window.IO_D=" + json.dumps(D, separators=(",", ":")) + ";\n")
open(os.path.join(here, "..", "parts", "34_js_io_0data.js"), "w").write(js)
print(len(js), "bytes")
