"""out/co_data.json -> ../parts/35_js_co_0data.js (the page embeds exactly this)."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(H, 'out/co_data.json')))
d.pop('azure_raw', None)
s = json.dumps(d, separators=(',', ':'), ensure_ascii=False)
open(os.path.join(H, '../parts/35_js_co_0data.js'), 'w').write('// Cost lab data: generated by src/cost/make_data_js.py from src/cost/out/co_data.json\nwindow.CO_DATA=' + s + ';\n')
print(len(s), 'bytes')
