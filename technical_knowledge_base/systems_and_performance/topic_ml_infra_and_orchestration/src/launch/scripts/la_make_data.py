#!/usr/bin/env python3
"""Launch lab: build parts/32_js_la_0data.js (window.LA) from the recorded outputs in src/launch/out/.

usage: python3 la_make_data.py            (run from anywhere; paths are relative to this file)
Inputs (all in src/launch/out/, scrubbed): launch_times.json, env.json, rz.json, hangs.json, tools.json, pull.json,
dns.json; texts.py (prose that carries numbers, built here from the same JSON so prose and data cannot disagree).
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "out")
PARTS = os.path.join(HERE, "..", "..", "parts")
sys.path.insert(0, HERE)
from la_envdoc import ENVDOC, RAY_OVERRIDES  # noqa: E402
import la_texts  # noqa: E402


def load(name, default=None):
    p = os.path.join(OUT, name)
    if not os.path.exists(p):
        return default
    with open(p) as f:
        return json.load(f)


def slim_times(t):
    """Keep what the page draws: stages per run, per-node and per-rank timestamps relative to submit."""
    res = {}
    for s, v in t["systems"].items():
        runs = []
        for r in v["runs"]:
            o = {"run": r["run"], "stages": r["stages"], "total_s": r["total_s"], "t_submit": 0.0}
            T0 = r["t_submit"]
            if "nodes" in r:
                o["nodes"] = [{k: (round(x - T0, 3) if isinstance(x, float) else x) for k, x in n.items()} for n in r["nodes"]]
                o["ranks"] = [{k: (round(x - T0, 3) if isinstance(x, float) and k not in ("rank",) else x) for k, x in n.items()} for n in r["ranks"]]
            if "workers" in r:
                o["workers"] = [{k: (round(x - T0, 3) if isinstance(x, float) else x) for k, x in w.items()} for w in r["workers"]]
            if "api_1s" in r:
                o["api_1s"] = r["api_1s"]
            runs.append(o)
        res[s] = {"runs": runs, "summary": v["summary"]}
    return res


def main():
    times = load("launch_times.json")
    env = load("env.json", {})
    envdoc = {k: list(v) for k, v in ENVDOC.items()}
    # Ray's values come from Ray Train, not torchrun: the explorer reads per-system docs
    envdoc_ray = dict(envdoc)
    envdoc_ray.update({k: list(v) for k, v in RAY_OVERRIDES.items()})
    D = {
        "times": slim_times(times),
        "env": env,
        "envdoc": envdoc,
        "envdoc_ray": envdoc_ray,
        "rz": load("rz.json"),
        "hangs": load("hangs.json", []),
        "rankpic": load("rankpic.json"),
        "code": load("code.json"),
    }
    D.update(la_texts.texts(D, load))
    js = "// generated by src/launch/scripts/la_make_data.py from src/launch/out/*.json; do not edit by hand\nwindow.LA=" + \
        json.dumps(D, separators=(",", ":"), ensure_ascii=False) + ";\n"
    p = os.path.join(PARTS, "32_js_la_0data.js")
    with open(p, "w") as f:
        f.write(js)
    print("wrote", p, len(js), "bytes")


if __name__ == "__main__":
    main()
