"""Build ../parts/22_js_ss_data.js (window.SS) from ../out/*.json: the only data the page embeds.

    python3 -I -B ss_data.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(HERE)
OUT = os.path.join(SRC, "out")
ROOT_SRC = os.path.join(os.path.dirname(os.path.dirname(SRC)), "src")


def J(name, root=False):
    with open(os.path.join(ROOT_SRC, "tpu", "out", name) if root else os.path.join(OUT, name)) as f:
        return json.load(f)


def prop():
    d = J("prop.json")
    src = {}
    cases = []
    for c in d["cases"]:
        rec = {k: c[k] for k in ("id", "mesh", "axes", "x_spec", "constraint", "note", "n_ops_compared", "n_ops_differ")}
        for part in ("shardy", "gspmd"):
            r = c[part]
            rows = []
            for x in r["rows"]:
                src[x["line"]] = x["src"]
                rows.append([x["line"], x["op"], x["phase"], x["shape"], x["spec"]])
            agg = {}
            for cl in r["collectives"]:
                k = (cl["kind"], cl["line"] or 0, cl["phase"])
                a = agg.setdefault(k, [0, 0])
                a[0] += 1
                a[1] += cl["bytes"]
                if cl["line"] and cl["src"]:
                    src[cl["line"]] = cl["src"]
            rec[part] = {"rows": rows, "coll": [[k[0], k[1], k[2], v[0], v[1]] for k, v in sorted(agg.items())],
                         "temp": r["temp_bytes"], "err": r["max_abs_err_vs_one_device"]}
        cases.append(rec)
    full = {}
    for sid, v in d["full_step"].items():
        full[sid] = {p: [[r["kind"], r["where"], r["phase"], r["count"], r["bytes"]] for r in v[p]] for p in ("shardy", "gspmd")}
    return {"cases": cases, "src": {str(k): v for k, v in sorted(src.items())}, "full": full}


def cut(fname, start, stop=None):
    """Source lines of runs/<fname> from the line containing `start` up to (not including) the first line after it
    containing `stop` (or the next line with no indentation)."""
    lines = open(os.path.join(HERE, fname)).read().splitlines()
    i = next(k for k, ln in enumerate(lines) if start in ln)
    out = [lines[i]]
    for ln in lines[i + 1:]:
        if (stop and stop in ln) or (not stop and ln and not ln[0].isspace()):
            break
        out.append(ln)
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out)


def main():
    code = {"pipe": cut("ss_pipe.py", "    def stage_fn(layers, x):", "    # layer order on the stacked axis"),
            "ring": cut("ss_cp.py", "def ring_attn(q, k, v):"),
            "moe": cut("ss_moe.py", "def moe_hand(params, xg, k, cap):"),
            "multi": cut("ss_multi.py", "    rows = slice(pid * B // NPROC", "        if i == 0:"),
            "multi_init": cut("ss_multi.py", '    jax.config.update("jax_cpu_collectives_implementation", "gloo")', "    import numpy as np")}
    SS = {"code": code, "prop": prop(), "explicit": J("explicit.json"), "cp": J("cp.json"), "pipe": J("pipe.json"),
          "moe": J("moe.json"), "multi": J("multi.json"), "scale": J("scale.json"), "fcheck": J("formula_check.json"),
          "debug": J("debug.json"), "source": J("source.json"), "torus": J("torus.json", root=True), "specs": J("specs.json", root=True)}
    # trim: the debug devices map and the torus grids are large; the page needs only the summaries
    SS["debug"].pop("devices_indices_map", None)
    for s in SS["torus"]["slices"]:
        for m in s["meshes"]:
            m.pop("grid", None)
    for p in ("normal", "mismatch"):
        for r in SS["multi"][p]["processes"]:
            r.pop("devices", None)
    for r in SS["scale"]["configs"].values():
        for lay in r["layouts"]:
            lay.pop("summary", None)
    SS["specs"] = {"gens": [{k: g[k] for k in ("gen", "name", "bf16", "hbm", "hbm_txt", "bw", "ici", "ici_txt", "pod", "topo", "url", "sb")}
                            for g in SS["specs"]["gens"]], "sources": SS["specs"]["sources"]}
    txt = "window.SS=" + json.dumps(SS, separators=(",", ":")) + ";\n"
    with open(os.path.join(SRC, "parts", "22_js_ss_data.js"), "w") as f:
        f.write("// Generated by src/runs/ss_data.py from src/out/*.json and the root's src/tpu/out/{torus,specs}.json. Do not edit.\n")
        f.write(txt)
    print("bytes", len(txt))


if __name__ == "__main__":
    main()
