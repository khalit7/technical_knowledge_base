"""Gather out/*.json (this page's runs) and the few root numbers the page quotes into parts/22_js_pj_data.js
as window.PJ. Run by ../build.sh. Plain python3, no packages.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "src"))


def load(name):
    with open(os.path.join(OUT, name + ".json"), encoding="utf-8") as f:
        return json.load(f)


PJ = {}
for n in ("defaults", "hunt", "convert", "gpt2", "interop", "drills", "source", "dropout"):
    if os.path.exists(os.path.join(OUT, n + ".json")):
        PJ[n] = load(n)
lad = {}
for dt in ("float32", "float64"):
    p = os.path.join(OUT, "ladder_%s.json" % dt)
    if os.path.exists(p):
        lad.update(json.load(open(p)))
PJ["ladder"] = lad

# root numbers quoted on this page (read, never retyped)
tl = json.load(open(os.path.join(ROOT, "train", "out", "twin_long.json")))
last = tl["drift"][-1]
PJ["root"] = dict(
    twin_steps=tl["steps"], twin_val_at=tl["val_at"], twin_val={k: v for k, v in tl["val"].items()},
    twin_first_over=tl["first_step_loss_diff_over"], twin_max_abs=tl["max_abs_loss_diff"],
    twin_by_window=tl["max_abs_loss_diff_by_window"]["torch_vs_jax"],
    twin_drift_last=last, twin_step_time=tl["step_time_median_s"], twin_clip_active=tl["clip_active_steps"],
    twin_machine=tl["machine"], twin_date=tl["date"])
eq = json.load(open(os.path.join(ROOT, "data", "equiv.json")))
PJ["root"]["n_params"] = eq["n_params"]

def clean(o):
    if isinstance(o, float) and (o != o or o in (float("inf"), float("-inf"))):
        return None
    if isinstance(o, dict):
        return {k: clean(v) for k, v in o.items()}
    if isinstance(o, list):
        return [clean(v) for v in o]
    return o


PJ = clean(PJ)
js = "// generated by runs/make_data.py from runs/out/*.json and the root's src/train/out/twin_long.json; do not edit\n"
js += "window.PJ=" + json.dumps(PJ, separators=(",", ":"), ensure_ascii=False, allow_nan=False) + ";\n"
dst = os.path.join(HERE, "..", "parts", "22_js_pj_data.js")
with open(dst, "w", encoding="utf-8") as f:
    f.write(js)
print("wrote", os.path.relpath(dst, HERE), len(js), "bytes")
