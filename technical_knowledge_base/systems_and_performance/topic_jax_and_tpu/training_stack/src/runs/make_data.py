"""Build ../parts/22_js_ts_data.js (window.TS) from out/*.json. Plain python3, no dependencies.
Everything the page shows as a measured number comes from here; check_data.py verifies the page against out/."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")


def load(n):
    with open(os.path.join(OUT, n + ".json")) as f:
        return json.load(f)


def r(x, s=5):
    """round floats to s significant digits, recursively"""
    if isinstance(x, float):
        if x == 0 or x != x or x in (float("inf"), float("-inf")):
            return x
        return float(f"{x:.{s}g}")
    if isinstance(x, list):
        return [r(v, s) for v in x]
    if isinstance(x, dict):
        return {k: r(v, s) for k, v in x.items()}
    return x


TS = {}
nnx = load("nnx")
e1 = nnx["E1"]
TS["nnx"] = {
    "E1": {k: e1[k] for k in ("n_nodes", "n_attributes", "num_leaves", "node_types", "attr_kinds", "static_attr_values",
                              "graphdef_equal_other_seed", "graphdef_hash_equal_other_seed", "graphdef_repr_chars", "graphdef_repr_head", "n_params")},
    "leaves": [[l["path"], l["type"], l["shape"], l["size"], l["dtype"]] for l in e1["leaves"]],
    "E2": {v: {"extra": [[l["path"], l["type"], l["shape"], l["size"], l["dtype"]] for l in d["leaves"] if l["path"] not in {x["path"] for x in e1["leaves"]}],
               "groups": d["groups"]} for v, d in nnx["E2"].items()},
    "E2_split_error": nnx["E2_split_error"],
    "E3": nnx["E3"], "E4": nnx["E4"], "E5": nnx["E5"], "E6": r(nnx["E6"]), "E7": r(nnx["E7"], 4), "E9": nnx["E9"],
    "versions": nnx["versions"],
}
TS["shard"] = load("nnx_shard")
TS["lx"] = r(load("linen_eqx"))
opt = load("optax")
TS["opt"] = r({k: opt[k] for k in ("S1", "S2", "S3", "S4", "S5", "S6", "S7", "S9", "versions")}, 6)
s8 = opt["S8"]
TS["opt"]["S8"] = r({k: s8[k] for k in s8}, 4)
TS["ckpt"] = r(load("ckpt"), 7)
for n in ("ckpt_mesh", "full", "full_policy_only", "grain", "torch_loader", "mixed", "mesh_det"):
    p = os.path.join(OUT, n + ".json")
    if os.path.exists(p):
        TS[n] = r(load(n), 7)
src = open(os.path.join(HERE, "ts_full.py")).read()
a = src.index("def train(ckpt_dir"); b = src.index("# ---------------------------------------------------------------- driver")
TS["full_code"] = src[a:b].rstrip() + "\n"
TS["src"] = {k: {"p": v["path"], "l": v["line"], "u": v["url"], "t": v["text"]} for k, v in load("source").items()}

js = "// generated by src/runs/make_data.py from src/runs/out/*.json; do not edit\nwindow.TS=" + json.dumps(TS, separators=(",", ":")) + ";\n"
dst = os.path.join(HERE, "..", "parts", "22_js_ts_data.js")
with open(dst, "w") as f:
    f.write(js)
print("wrote", dst, len(js), "bytes")
