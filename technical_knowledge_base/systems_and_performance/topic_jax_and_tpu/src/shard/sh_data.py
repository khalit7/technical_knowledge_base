"""Build the Sharding lab's embedded data (parts/34_js_sh_0data.js) from out/*.json. Plain Python, no JAX.

    python3 sh_data.py
Everything the tab shows as a number comes from here; check_tab.py checks the built page against out/*.json.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
PART = os.path.join(os.path.dirname(HERE), "parts", "34_js_sh_0data.js")


def load(n):
    with open(os.path.join(OUT, n)) as f:
        return json.load(f)


def main():
    st, pg, co, ex = load("strategies.json"), load("playground.json"), load("collectives.json"), load("explicit.json")
    strategies = []
    gs = {g["id"]: g for g in st["gspmd"]}
    for r in st["strategies"]:
        g = gs.get(r["id"])
        strategies.append({
            "id": r["id"], "label": r["label"], "mesh": r["mesh"], "axes": r["axes"], "batch": r["batch_spec"],
            "resid": r["resid_constraint"], "specs": r["param_specs"],
            "grouped": r["grouped"],
            "sum": {k: [v["count"], v["bytes"], round(v["ring_bytes"])] for k, v in r["summary"].items()},
            "param_b": r["param_bytes_per_device"], "opt_b": r["opt_bytes_per_device"], "mem": r["memory"],
            "loss0": r["losses"][0], "lossN": r["losses"][-1], "losses": [round(x, 6) for x in r["losses"]],
            "dloss": r["max_abs_loss_diff_vs_single"], "dw": r["max_abs_weight_diff_vs_single"],
            "shards": r["shard_shapes"], "step_s": r["step_s_median"], "compile_s": r["compile_s"],
            "hlo_lines": r["hlo_lines"],
            "gspmd": None if g is None else {"sum": {k: [v["count"], v["bytes"], round(v["ring_bytes"])] for k, v in g["summary"].items()},
                                              "same": g["same_as_shardy"], "temp": g["memory"]["temp_size_in_bytes"],
                                              "grouped": g["grouped"]},
        })
    rows = [[r["x"], r["w"], r["out"], r["x_shard"], r["w_shard"], r["y_spec"], r["y_shard"],
             [[c[0], c[1], c[2] or 0] for c in r["coll"]], r["mem"]["temp_size_in_bytes"], r["max_err"]] for r in pg["rows"]]
    data = {
        "steps": st["steps"], "jax": st["jax"], "params_total": st["params_total"],
        "strategies": strategies,
        "pg": {"mesh": pg["mesh_devices"], "x_shape": pg["x_shape"], "w_shape": pg["w_shape"],
               "x_tiles": pg["x_tiles"], "w_tiles": pg["w_tiles"], "rows": rows},
        "co": {"input": co["input_per_device"], "cases": co["cases"], "ring": co["ring"],
               "mismatch_auto": co["mismatch_auto"], "mismatch_explicit": co["mismatch_explicit"],
               "ag_rep": co["all_gather_replicated_out_specs"], "pmap": co["pmap"],
               "make_mesh_default": co["make_mesh_default_axis_types"]},
        "viz": ex["visualize"]["P('model', None)"],
        "ex": {"make_mesh_default": ex["make_mesh_default"], "Mesh_default": ex["Mesh_default"],
               "matmul": ex["matmul"], "reshard": ex["reshard"]},
    }
    js = ("// ---- Sharding lab data: generated by src/shard/sh_data.py from src/shard/out/*.json (do not edit) ----\n"
          "window.SHD=" + json.dumps(data, separators=(",", ":")) + ";\n")
    with open(PART, "w") as f:
        f.write(js)
    print(PART, len(js), "bytes")


if __name__ == "__main__":
    main()


def reading_summary():
    """out/rd_collectives.json: the compact per-strategy table the Reading tab's TODO rd-todo-coll asks for."""
    st = load("strategies.json")
    rows = []
    for r in st["strategies"]:
        rows.append({"id": r["id"], "label": r["label"], "mesh": r["mesh"], "axes": r["axes"],
                     "collectives": {k: {"count": v["count"], "bytes": v["bytes"], "sent_per_device_ring": round(v["ring_bytes"])}
                                     for k, v in r["summary"].items()},
                     "param_bytes_per_device": r["param_bytes_per_device"], "opt_bytes_per_device": r["opt_bytes_per_device"],
                     "memory_analysis": r["memory"], "loss_step0": r["losses"][0], "loss_last": r["losses"][-1],
                     "max_abs_loss_diff_vs_single": r["max_abs_loss_diff_vs_single"]})
    with open(os.path.join(OUT, "rd_collectives.json"), "w") as f:
        json.dump({"what": st["what"], "steps": st["steps"], "rows": rows}, f, indent=1)
        f.write("\n")


reading_summary()
