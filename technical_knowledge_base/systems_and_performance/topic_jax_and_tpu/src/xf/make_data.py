"""Assemble the Transforms lab's embedded data (parts/31_js_xf_0data.js) from out/*.json.
Pure Python, no JAX needed: python3 make_data.py"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
PART = os.path.join(os.path.dirname(HERE), "parts", "31_js_xf_0data.js")


def load(n):
    with open(os.path.join(OUT, n + ".json"), encoding="utf-8") as f:
        return json.load(f)


tr, rc, ba, gr, vm, so, toy, p8 = (load(n) for n in ("trace", "recompile", "basics", "grad", "vmap", "source", "toy", "prng8"))
pick = lambda d, ks: {k: d[k] for k in ks}  # noqa: E731
D = {
    "versions": tr["versions"],
    "trace": {
        "attention": pick(tr["attention"], ["src", "src_start", "head", "eqns", "prims", "line", "inner", "foot"]),
        "mlp": pick(tr["mlp"], ["src", "src_start", "head", "eqns", "prims", "line", "inner", "foot"]),
        "tracers": tr["tracers"], "typeof": tr["typeof"], "loop_vs_scan": tr["loop_vs_scan"],
        "cf_errors": tr["cf_errors"], "cf_jaxprs": tr["cf_jaxprs"], "cf_values": tr["cf_values"],
        "loops": {k: {kk: v[kk] for kk in ("top", "total", "value", "grad")} for k, v in tr["loops"].items()},
        "forward_eqns": tr["forward_eqns"], "vg_eqns": tr["value_and_grad_eqns"],
    },
    "drills": rc["drills"],
    "basics": {k: ba[k] for k in ("side", "np_random_in_jit", "time_in_jit_same", "immut", "immut_torch", "oob", "prng",
                                    "leafdemo", "tree_map_mismatch", "footguns", "async", "param_bytes")},
    "pytree": pick(ba["pytree"], ["n_leaves", "n_params", "leaves", "n_torch_tensors", "nnx_n_leaves", "nnx_paths_first",
                                  "nnx_n_params", "torch_names_first"]),
    "prng8": p8,
    "grad": {"loss": gr["loss"], "summary": gr["summary"], "accumulate": gr["accumulate"], "has_aux": gr["has_aux"],
             "has_aux_missing": gr["has_aux_missing"], "higher": gr["higher"], "stop_gradient": gr["stop_gradient"],
             "argnums": gr["argnums"],
             "rows": [[r["name"], r["max_abs_diff"], r["max_abs_grad"]] for r in gr["rows"]]},
    "vmap": {"agree": vm["agree"], "time_s": {k: v for k, v in vm["time_s"].items() if k != "raw"},
             "norms": vm["per_example_norms"], "eqns": vm["eqns"], "batching": vm["batching"],
             "mlp_anim": vm["mlp_anim"], "grad_bytes": vm["grad_bytes"], "load": round(vm["load"], 1), "B": vm["B"], "T": vm["T"]},
    "source": so,
    "toy": pick(toy, ["toy_code", "f_code", "toy_out", "jax_out", "code_lines"]),
}
# JSON has no NaN: write the NaN gradients of the jnp.where footgun as the string Python printed
for k in ("where_nan_jax", "where_nan_torch"):
    v = D["basics"]["footguns"][k]
    if v != v:
        D["basics"]["footguns"][k] = "nan"
js = "// ---- Transforms lab (t-xf): data, generated by src/xf/make_data.py from src/xf/out/*.json. Do not edit by hand.\nwindow.XFD=" + \
     json.dumps(D, separators=(",", ":"), ensure_ascii=False, allow_nan=False) + ";\n"
with open(PART, "w", encoding="utf-8") as f:
    f.write(js)
print("wrote", os.path.relpath(PART, HERE), len(js.encode()), "bytes")
