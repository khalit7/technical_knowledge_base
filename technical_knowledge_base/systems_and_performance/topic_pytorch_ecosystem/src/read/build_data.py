"""Write ../parts/22_js_rd_data.js for the Reading tab from recorded inputs (plain Python 3, no torch).
Sources: read/inputs/measure.json (this tab), step/inputs (Inside one step), comp/inputs (Compile lab),
dist/inputs (Distributed lab, when present). Everything the Reading tab draws comes from here."""
import json, os, sys
sys.dont_write_bytecode = True
H = os.path.dirname(os.path.abspath(__file__)); S = os.path.dirname(H)
J = lambda *p: json.load(open(os.path.join(S, *p)))
m = J("read", "inputs", "measure.json")
tim = J("step", "inputs", "timing.json"); topt = J("step", "inputs", "timing_opt.json")
c_cpu = J("comp", "inputs", "time_step_cpu.json"); c_mps = J("comp", "inputs", "time_step_mps.json")
med = lambda d: round(d["median_ms"], 2)
rng = lambda d: [round(d["min_ms"], 2), round(d["max_ms"], 2)]
D = {
  "strides": m["strides"], "dispatch": m["dispatch"], "tiny": m["tiny_graph"], "tinyck": m["tiny_ckpt"], "customop": m["custom_op"],
  "phases": {"cpu": {k: med(tim["cpu"]["plain"][k]) for k in ("fwd", "bwd", "opt", "step")},
             "cpu_ck": {k: med(tim["cpu"]["checkpoint"][k]) for k in ("fwd", "bwd", "opt", "step")},
             "load": [round(x, 1) for x in tim["load_before"]]},
  "opt": {d: {k: med(v) for k, v in topt[d].items()} for d in ("cpu", "mps")},
  "comp": {"cpu": {k: med(v) for k, v in c_cpu["results"].items()}, "cpu_rng": {k: rng(v) for k, v in c_cpu["results"].items()},
           "mps": {k: med(v) for k, v in c_mps["results"].items()}, "mps_rng": {k: rng(v) for k, v in c_mps["results"].items()},
           "load_cpu": [round(x, 1) for x in c_cpu["load_before"]], "load_mps": [round(x, 1) for x in c_mps["load_before"]]},
}
# live bytes added by one forward, plain and checkpointed (Inside one step traces)
for k, f in (("plain", "step_cpu.json"), ("ckpt", "step_cpu_ckpt.json")):
    t = J("step", "inputs", f)
    D.setdefault("step", {})[k] = dict(fwd_added=t["live_after_fwd"] - t["base_live"], n_fwd=t["n_fwd"], n_bwd=t["n_bwd"], n_opt=t["n_opt"])
# distributed lab (section 7), only if its records exist
dist = os.path.join(S, "dist", "inputs")
if os.path.isdir(dist) and os.path.exists(os.path.join(H, "dist_extract.py")):
    import importlib.util
    sp = importlib.util.spec_from_file_location("dx", os.path.join(H, "dist_extract.py")); dx = importlib.util.module_from_spec(sp); sp.loader.exec_module(dx)
    D["dist"] = dx.extract(dist)
out = os.path.join(S, "parts", "22_js_rd_data.js")
open(out, "w").write("// generated by src/read/build_data.py from recorded inputs; do not edit\nwindow.RDD=" + json.dumps(D, separators=(",", ":")) + ";\n")
print(out, os.path.getsize(out))
