"""Turn the recorded runs in inputs/ into parts/22_ext_data.js (window.EXT), trimmed to what the page uses.
Run: python3 src/build_data.py (plain Python, no torch needed)."""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
I = os.path.join(HERE, "inputs")


def J(n):
    return json.load(open(os.path.join(I, n)))


co, fresh, trap, ex, gr, sub, real, hel, tim, qu = (J(n) for n in [
    "custom_ops.json", "custom_ops_cpp_fresh.json", "cache_trap.json", "op_extras.json", "graphs.json",
    "subclasses.json", "real_subclasses.json", "helion.json", "timing.json", "quotes.json"])


def first_line(s, n=230):
    if s is None:
        return None
    s = s.replace("\n  ", " ").split("\n")[0]
    return s[:n] + ("..." if len(s) > n else "")


def tidy(s, n=300):
    if s is None:
        return None
    s = re.sub(r"\s+", " ", s).strip()
    return s[:n] + ("..." if len(s) > n else "")


variants = dict(co["variants"])
variants["cpp_full"] = fresh["variants"]["cpp_full"]
V = {}
for k, v in variants.items():
    e, x, c = v["eager"], v["explain"], v["compile"]
    V[k] = {
        "loss": e["loss"], "eager_err": tidy(e["error"], 200), "warn": [tidy(w, 220) for w in e["warnings"]],
        "with_grad": e.get("n_with_grad"), "n_params": e.get("n_params"), "grad_diff": e["max_grad_diff"],
        "graphs": x.get("graphs"), "breaks": x.get("breaks"), "reason": first_line(x["reasons"][0]) if x.get("reasons") else None,
        "explain_err": tidy(x.get("error"), 260), "custom_nodes": x.get("custom_nodes"),
        "comp_ok": c["ok"], "comp_err": tidy(c.get("error"), 260), "comp_grad_diff": c.get("max_grad_diff"),
        "comp_loss": c.get("loss"),
        "opcheck": {t: {"ok": r["ok"], "msg": tidy(r["msg"], 260) if not r["ok"] else None} for t, r in v.get("opcheck", {}).items()},
        "schema": v.get("schema"),
    }
EXT = {"ref_loss": co["ref_loss"], "variants": V,
       "late_after_clear": {t: r["ok"] for t, r in co["cpp_late_after_cache_clear"].items()},
       "dispatch_cpp": fresh.get("dispatch_dump_cpp"),
       "trap": trap["runs"]}

EXT["schemas"] = ex["schemas"]
EXT["alias_error"] = tidy(ex["alias_error"], 260)
EXT["inductor"] = {k: {"calls": v["calls"], "n": v["n_generated_kernels"]} for k, v in ex["inductor"].items()}
EXT["dd"] = ex["data_dependent"]
EXT["mps"] = {k: v for k, v in ex["mps"].items() if k != "erf_error"}
EXT["mps"]["erf_error"] = tidy(ex["mps"].get("erf_error", ""), 120)
EXT["dup"] = ex["duplicate_torch_library"]

EXT["graphs"] = {k: {"graphs": [g["ops"] for g in v["graphs"]], "breaks": v["breaks"], "gc": v["graph_count"], "bc": v["break_count"],
                     "n0": len(v["graphs"][0]["ops"])}
                 for k, v in gr.items() if k not in ("export", "export_pybind")}
EXT["export"] = dict(gr["export"], pybind_error=gr["export_pybind"])

# subclass traces: compact events [level, phase, op, sub-arg indices]
L = {}
for k, v in sub["levels"].items():
    L[k] = {"ev": [[e["level"][0], e["phase"][0], e["op"], e["sub"]] for e in v["events"]],
            "ns": v["n_setup"], "nf": v["n_forward"], "nb": v["n_backward"], "n": v["n_events"], "loss": v["loss"],
            "loss_type": v["loss_type"], "grad_type": v["grad_type"], "hist": v["ops_hist"]}
EXT["levels"] = L
EXT["param_detach_error"] = tidy(sub.get("parameter_detach_error"), 260)
EXT["int8"] = {k: v for k, v in sub["int8"].items()}
EXT["sub_ref_loss"] = sub["ref_loss"]
R = []
for r in real["real"]:
    d = {k: r.get(k) for k in ("label", "class", "shape", "dtype", "inner", "inner_bytes", "keyset", "mixed_error",
                               "matmul_result_type", "matmul_result_placements", "dequant_max_err", "mm_on_cpu", "error")}
    d["ctx"] = tidy(r.get("ctx"), 160)
    if r.get("aten_calls"):
        d["aten_calls"] = [c.replace("aten.", "").replace(".default", "") for c in r["aten_calls"] if "randn" not in c]
    R.append(d)
EXT["real"] = R
EXT["modes"] = real["modes"]
EXT["helion"] = {"kernels": {k: {kk: vv for kk, vv in v.items() if kk != "stderr"} for k, v in hel["kernels"].items()},
                 "op": hel["as_custom_op"], "ref": hel["ref_mode_cpu"]}
EXT["timing"] = tim
EXT["quotes"] = {k: {"path": v["path"], "first": v["first"], "last": v["last"], "url": v["url"], "text": v["text"]} for k, v in qu.items()}

js = "// Recorded runs for Extending PyTorch (generated by src/build_data.py from src/inputs/*.json; do not edit)\nwindow.EXT=" + \
     json.dumps(EXT, separators=(",", ":"), ensure_ascii=True) + ";\n"
open(os.path.join(HERE, "parts", "22_ext_data.js"), "w").write(js)
print("wrote parts/22_ext_data.js", len(js), "bytes")
