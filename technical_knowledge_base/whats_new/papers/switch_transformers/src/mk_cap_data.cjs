// Data for the capacity stage (31_js_sc_cap.js): the toy Switch layer of the Train tab, trained with the sweep's base settings
// (16 experts, top-1, capacity factor 1.25, alpha 0.01, init 0.1, 1,500 steps, seed 1) and its top-2 twin (k = 2, otherwise the same),
// then one held-out batch of 512 tokens (the first routing group of the 2,048 held-out tokens) routed through each, with the expert
// buffers set by Eq. 3 at capacity factors 0.5, 1.0, 1.25 and 2.0. Also the drop rate over all 2,048 held-out tokens at each factor.
// usage: node mk_cap_data.cjs   (about 10 seconds; writes parts/20c_cap_data.js)
const SW = require('./parts/20_js_switch_core.js'); const fs = require('fs');
const BASE = JSON.parse(fs.readFileSync('parts/20b_sweep_data.js', 'utf8').replace(/^[^{]*/, '').replace(/;\s*$/, '')).base;
const CFS = [0.5, 1, 1.25, 2], out = { cfg: Object.assign({}, BASE, { seed: 1 }), steps: 1500, cfs: CFS, runs: {} };
for (const k of [1, 2]) {
  const st = SW.run(Object.assign({}, BASE, { k, seed: 1 })); SW.trainSteps(st, 1500);
  const d = st.cfg.d, T = st.cfg.T, N = st.cfg.N, te = st.test;
  const B = { X: te.X.subarray(0, T * d), Y: te.Y.subarray(0, T * d), T };
  const all = SW.pass(st.P, B, Object.assign({}, st.cfg, { cf: 100 }), null, null);   // no capacity limit: the demand
  const first = Array.from({ length: N }, () => 0); for (let t = 0; t < T; t++) first[all.first[t]]++;
  const demand = Array.from(all.fill), second = demand.map((v, e) => v - first[e]);
  const at = {};
  for (const cf of CFS) {
    const r = SW.pass(st.P, B, Object.assign({}, st.cfg, { cf }), null, null);
    const kept = Array.from(r.fill), lost = r.dropped + r.dropped2;
    let noExpert = 0; if (k === 1) noExpert = r.dropped; else { /* a token with no expert: its first choice dropped and its second too */ }
    at[cf] = { C: r.C, kept, dropped1: r.dropped, dropped2: r.dropped2, slots: N * r.C, pad: N * r.C - kept.reduce((a, b) => a + b, 0), mse: +r.mse.toFixed(5),
      heldout_drop: +SW.evaluate(st, cf).drop.toFixed(4) };
  }
  out.runs['k' + k] = { first, second, demand, at, mse_eval2: +SW.evaluate(st).mse.toFixed(5) };
  console.log('k', k, 'first', first.join(' '), 'second', second.join(' '));
  for (const cf of CFS) console.log('  cf', cf, JSON.stringify(at[cf]));
}
fs.writeFileSync('parts/20c_cap_data.js', '// Generated by mk_cap_data.cjs (the toy Switch layer, sweep base settings, seed 1, 1,500 steps; one held-out batch of 512 tokens).\nwindow.CAP=' + JSON.stringify(out) + ';\n');
