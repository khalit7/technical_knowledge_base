// node src/toy_sweep.mjs : every toy number on the page (inputs/toy.json, parts/_gen_toydata.js). About a minute.
import { createRequire } from 'node:module'; import fs from 'node:fs'; import path from 'node:path'; import url from 'node:url';
const here = path.dirname(url.fileURLToPath(import.meta.url));
const OPD = createRequire(import.meta.url)(path.join(here, 'parts', '22_js_toy.js'));
const W = OPD.world(1);
const LAMS = [-2, -1.5, -1, -0.5, 0, 0.5, 1, 1.5, 2], LRS = [0.02, 0.1], SEEDS = [42, 43, 44];
const r4 = x => Math.round(x * 1e4) / 1e4;
const init = OPD.evaluate(W, 'mlp', OPD.initTheta(W, 'mlp'), 1), initT = OPD.evaluate(W, 'table', OPD.initTheta(W, 'table'), 1), teach = OPD.teacherEval(W, 1);
const out = { world_seed: 1, lams: LAMS, lrs: LRS, seeds: SEEDS, init: { pass1: r4(init.pass1), pass10: r4(init.pass10), distinct10: r4(init.distinct10) }, init_table: { pass1: r4(initT.pass1), pass10: r4(initT.pass10), distinct10: r4(initT.distinct10) },
  teacher: { pass1: r4(teach.pass1), pass10: r4(teach.pass10), distinct10: r4(teach.distinct10) }, sweep: {} };
for (const model of ['mlp', 'table']) for (const clip of [1.0, 0]) for (const kind of ['f', 'r']) for (const lr of LRS) {
  if (model === 'table' && !clip) continue;
  const key = `${model} ${kind} ${lr} ${clip ? 'clip' : 'noclip'}`; out.sweep[key] = [];
  for (const lam of LAMS) {
    const runs = SEEDS.map(seed => { const res = OPD.train(W, { model, kind, lam, lr, seed, clip }); const e = OPD.evaluate(W, model, res.theta, 1); return [e.pass1, e.pass10, e.distinct10]; });
    const mean = j => runs.reduce((s, x) => s + x[j], 0) / runs.length;
    const sem = j => { const m = mean(j); return Math.sqrt(runs.reduce((s, x) => s + (x[j] - m) ** 2, 0) / (runs.length - 1) / runs.length); };
    out.sweep[key].push({ lam, pass1: r4(mean(0)), pass1_sem: r4(sem(0)), pass10: r4(mean(1)), distinct10: r4(mean(2)), runs: runs.map(x => x.map(r4)) });
  }
}
fs.writeFileSync(path.join(here, 'inputs', 'toy.json'), JSON.stringify(out));
fs.writeFileSync(path.join(here, 'parts', '_gen_toydata.js'), '// Generated by toy_sweep.mjs; do not edit by hand.\nwindow.TOYD=' + JSON.stringify(out) + ';\n');
console.log('init', out.init, 'teacher', out.teacher);
for (const [k, v] of Object.entries(out.sweep)) console.log(k.padEnd(16), 'p1', v.map(x => x.pass1.toFixed(2)).join(' '), '| p10', v.map(x => x.pass10.toFixed(2)).join(' '), '| dist', v.map(x => x.distinct10.toFixed(2)).join(' '));
