// The data of the method stage on The paper tab (Stage 2: the four steps of SA-MRPO on one batch of the toy).
// One training batch of the graded-length toy (Table 2 style), SA-MRPO with γ = 0.5, seed 1, at step 80, read through the
// engine's read-only onBatch hook (parts/22_js_toy.js), so it is exactly the batch that run trained on. Selection rule, fixed
// before looking at the advantages: the first group (in sampled order) of each of four kinds, by which objectives vary within
// the group: correctness only, both, length only, neither. GDPO's advantages (γ = 0) are computed on the same batch for comparison.
//   node stage_batch.mjs   -> inputs/stage.json and parts/_gen_stage.js   (well under a second)
import { createRequire } from 'module';
import fs from 'fs';
const require = createRequire(import.meta.url);
const here = new URL('.', import.meta.url).pathname;
const T = require(here + 'parts/22_js_toy.js');
const STEP = 80, SEED = 1, SETTING = 'graded', METHOD = 'sa50';
const r4 = v => Math.round(v * 1e4) / 1e4;
let B = null, first = null;
T.train({ setting: SETTING, method: METHOD, seed: SEED, steps: STEP, onBatch: (t, b) => { if (t === 1) first = b.ad; if (t === STEP) B = b } });
const { Rc, Rl, ad } = B, gd = T.advantages([Rc, Rl], T.METHODS.gdpo);
const sd = a => T.std(a), z = g => { const m = T.mean(g), s = T.std(g, m); return g.map(r => (r - m) / (s + 1e-6)) };
const kind = i => (sd(Rc[i]) > 0 ? 'c' : '') + (sd(Rl[i]) > 0 ? 'l' : '');
const KINDS = [['c', 'only correctness varies'], ['cl', 'both vary'], ['l', 'only length varies'], ['', 'neither varies']];
const groups = KINDS.map(([k, name]) => { const i = Rc.findIndex((_, j) => kind(j) === k);
  return { i, kind: k, name, rc: Rc[i], rl: Rl[i].map(r4), ac: z(Rc[i]).map(r4), al: z(Rl[i]).map(r4),
    sum: Rc[i].map((_, j) => r4(ad.wt[0] * z(Rc[i])[j] + ad.wt[1] * z(Rl[i])[j])), sa: ad.A[i].map(r4), gdpo: gd.A[i].map(r4) } });
const nVar = k => Rc.filter((_, i) => kind(i).includes(k)).length;
const out = { setting: SETTING, method: METHOD, gamma: 0.5, seed: SEED, step: STEP, B: Rc.length, G: Rc[0].length,
  s: ad.s.map(r4), w: ad.wt.map(r4), shareL: r4(ad.share[1]), shareL_gdpo: r4(gd.share[1]), varC: nVar('c'), varL: nVar('l'),
  s_step1: first.s.map(r4), w_step1: first.wt.map(r4), groups };
fs.writeFileSync(here + 'inputs/stage.json', JSON.stringify(out, null, 1) + '\n');
fs.writeFileSync(here + 'parts/_gen_stage.js', '// Generated by stage_batch.mjs: one batch of the toy for the method stage (graded setting, SA-MRPO γ = 0.5, seed 1, step 80).\nwindow.TOYSTAGE=' + JSON.stringify(out) + ';\n');
console.log(JSON.stringify({ s: out.s, w: out.w, shareL: out.shareL, shareL_gdpo: out.shareL_gdpo, varC: out.varC, varL: out.varL, s1: out.s_step1, w1: out.w_step1, groups: groups.map(g => [g.i, g.kind]) }));
groups.forEach(g => console.log(g.i, g.kind, 'rc', g.rc.join(''), 'rl', g.rl.join(' '), '\n  ac', g.ac.join(' '), '\n  al', g.al.join(' '), '\n  sa', g.sa.join(' '), '\n  gd', g.gdpo.join(' ')));
