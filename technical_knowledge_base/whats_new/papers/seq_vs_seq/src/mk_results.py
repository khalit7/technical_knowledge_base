"""Turn the toy suite's measurements (model/gen.json, cls.json, logs.json, report.json, check_forward.json,
overlap.json) into parts/_gen_results.js (window.TOY). usage: python3 mk_results.py (build.sh runs it)"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); MD = os.path.join(HERE, 'model')
rd = lambda f: json.load(open(os.path.join(MD, f))) if os.path.exists(os.path.join(MD, f)) else None
out = {'gen': rd('gen.json'), 'cls': rd('cls.json'), 'logs': rd('logs.json'), 'report': rd('report.json'), 'check': rd('check_forward.json'), 'overlap': rd('overlap.json'), 'cls_check': rd('cls_check.json')}
# the toy sizes, as train.py's SIZES (check_forward.py asserts they agree)
out['sizes'] = {'s': dict(d=32, L=2, h=4, I=48), 'm': dict(d=48, L=3, h=4, I=72), 'l': dict(d=64, L=4, h=4, I=96)}
open(os.path.join(HERE, 'parts', '_gen_results.js'), 'w').write('// Generated by mk_results.py from model/*.json.\nwindow.TOY=' + json.dumps(out, separators=(',', ':')) + ';\n')
print('mk_results: wrote parts/_gen_results.js')
