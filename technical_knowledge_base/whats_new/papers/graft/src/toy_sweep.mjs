// Every toy number quoted in the page's prose: the default run and three variants, five seeds each.
// node src/toy_sweep.mjs   (from the page folder or anywhere; about 5 s)  -> src/inputs/toy.json
import { createRequire } from 'node:module';
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const T = createRequire(import.meta.url)(path.join(HERE, 'parts/22_js_toy.js'));
const VARIANTS = {
  default: {},
  monitor_hack3: { monitor: 3 },          // the monitor sees only the least common hack
  recall_025: { recall: 0.25 },           // the monitor catches a quarter of hack-1 samples
  penalty_3: { penalty: 3 },
};
const SEEDS = [1, 2, 3, 4, 5];
const r3 = v => Math.round(v * 1000) / 1000;
const out = { _doc: 'Written by src/toy_sweep.mjs from parts/22_js_toy.js; final step, mean and range over seeds 1 to 5.', def: T.DEF, variants: {} };
for (const [name, cfg] of Object.entries(VARIANTS)) {
  const res = {};
  for (const m of T.METHODS) {
    const views = m === 'graft' || m === 'noroute' || m === 'noanchor' ? ['dep', 'pre', 'fo'] : ['dep'];
    for (const v of views) {
      const rows = SEEDS.map(seed => { const h = T.run(m, { ...cfg, seed }).hist; return h[h.length - 1][v]; });
      const agg = {};
      for (const k of ['hack', 'detected', 'undetected', 'clean', 'proxy']) {
        const xs = rows.map(r => r[k]);
        agg[k] = r3(xs.reduce((a, b) => a + b, 0) / xs.length); agg[k + '_min'] = r3(Math.min(...xs)); agg[k + '_max'] = r3(Math.max(...xs));
      }
      res[m + (v === 'dep' ? '' : '_' + v)] = agg;
    }
  }
  out.variants[name] = res;
}
const base = T.metrics([...T.DEF.start.map(Math.log), Math.log(T.DEF.q0 / T.DEF.qMax / (1 - T.DEF.q0 / T.DEF.qMax))], T.cfgOf({}));
out.base = { hack: r3(base.hack), detected: r3(base.detected), undetected: r3(base.undetected), clean: r3(base.clean), proxy: r3(base.proxy) };
// The two stages on The paper (Fig. 2 and Fig. 3) are driven by the default GRAFT run, seed 1: its adapters every 5 steps, and one
// group of 16 sampled from its pre-ablation policy at step 15 exactly as the engine samples (illustrative: the first sampler seed, counting
// from 1, whose group holds a right and a wrong real solution, every hack, and 6 to 10 flagged answers).
{
  const run = T.run('graft', { seed: 1 }), c = run.cfg, r2 = v => Math.round(v * 100) / 100;
  const traj = run.hist.map(h => ({ t: h.t, uR: h.uR.map(r3), uF: h.uF.map(r3), pre: h.pre.pi.map(r3), qpre: r3(h.pre.q), dep: h.dep.pi.map(r3), qdep: r3(h.dep.q) }));
  const at = run.hist.find(h => h.t === 15).pre;
  let group = null;
  for (let sd = 1; sd < 500 && !group; sd++) {
    const R = T.rng(sd), S = [];
    for (let j = 0; j < c.G; j++) { let t = 0, u = R(), acc = 0; for (t = 0; t < 3; t++) { acc += at.pi[t]; if (u < acc) break; }
      const ok = t === 0 ? (R() < at.q ? 1 : 0) : 1; S.push({ t, ok, r: t === 0 ? ok : c.rHack[t - 1], fl: t === c.monitor ? 1 : 0 }); }
    const n = k => S.filter(s => s.t === k).length, nf = S.filter(s => s.fl).length;
    if (S.some(s => s.t === 0 && s.ok) && S.some(s => s.t === 0 && !s.ok) && n(2) >= 2 && n(3) >= 1 && nf >= 6 && nf <= 10) {
      S.sort((a, b) => a.fl - b.fl || a.t - b.t || b.ok - a.ok);
      const all = T.advantages(S, s => s.r, 'all'), unf = T.advantages(S, s => s.r, 'unflagged');
      const mean = a => a.reduce((x, y) => x + y, 0) / a.length, U = S.filter(s => !s.fl);
      group = { sampler_seed: sd, step: 15, pi: at.pi.map(r3), q: r3(at.q), samples: S.map((s, i) => ({ t: s.t, ok: s.ok, r: s.r, fl: s.fl, a_all: r3(all[i]), a_graft: r3(unf[i]) })),
        mean_all: r3(mean(S.map(s => s.r))), mean_unflagged: r3(mean(U.map(s => s.r))),
        sum_unflagged_all: r2(S.reduce((x, s, i) => x + (s.fl ? 0 : all[i]), 0)), sum_unflagged_graft: r2(S.reduce((x, s, i) => x + (s.fl ? 0 : unf[i]), 0)) };
    }
  }
  out.stage = { _doc: 'Default GRAFT run, seed 1: adapters (logit shifts: real solution, hack 1, hack 2, hack 3, skill), pre-ablation and deployed answer mixes every 5 steps; one sampled group (illustrative).', traj, group };
}
fs.writeFileSync(path.join(HERE, 'inputs/toy.json'), JSON.stringify(out, null, 1));
fs.writeFileSync(path.join(HERE, 'parts/_gen_toydata.js'), '// Generated by src/toy_sweep.mjs; do not edit by hand.\nwindow.TOYREF=' + JSON.stringify(out) + ';\n');
for (const [n, res] of Object.entries(out.variants)) {
  console.log('==', n);
  for (const [m, a] of Object.entries(res)) console.log('  ' + m.padEnd(14), 'hack', a.hack, '(det', a.detected, 'undet', a.undetected + ', range', a.hack_min + '-' + a.hack_max + ') clean', a.clean, 'proxy', a.proxy);
}
