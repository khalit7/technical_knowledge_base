"""Labels src/ledger.json (drafted by html_utils/ledger.py init on 2026-10-25 from the page as committed before the light pass;
adapted from the Qwen3 labeller). For every unit not overridden below, the key is the first run of 8 (then 6, then 4) consecutive
words of its text that appears verbatim in the rebuilt page, and the label is depth when that key sits inside a closed <details>
block, core otherwise. Rerun after a rebuild; it prints any unit it cannot place."""
import json, re, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[4] / 'html_utils'))
import ledger  # visible() and norm(), so keys match what ledger.py check reads
PAGE = 'whats_new/papers/prime_agent'
H = 'agents_and_retrieval/topic_agentic_harnesses'
FAT = {1: 'old reading-time line, replaced by the measured subtitle', 35: 'old autoplay note, replaced by "never plays by itself"', 225: 'old autoplay note, replaced by "never plays by itself"'}
VOLATILE = {}
OWNED = {}
KEYS = {189: 'when it pays off'}
NEW = [
 ('core', '', 'Core sentence: the state hierarchy managed by the model; Opus 5 at 95.5% on the public set; nothing isolates the harness effect; models not trained to use it.', 'the idea in one sentence: treat a model'),
 ('core', '', "Hero: the paper's Figure 2 (CC BY 4.0), the state hierarchy with the model-context boundary.", 'everything below the red line is state the model manages with code'),
 ('core', '', 'Hero results: ARC-AGI-3 public-set RHAE bars (ARC harness 30.2, best of 3 95.5, median 95.24, human card 95.35, community 98.97 to 100), generated by mk_hero.py; the caption carries the key.', 'community cards are self-reported and unverified'),
 ('core', '', 'New terms: L0 to L3, rlm(), Continual Harness, agentic garbage collection, RHAE.', 'the model deciding which repl values and subagent sessions to keep'),
 ('core', '', "The paper's Figure 1 (system architecture) as a real figure in Method.", 'execution runs left to right, persistent state hangs below'),
 ('owned:' + H, '', 'What a harness is and its parts are taught on Topic: agentic-harnesses; Problem keeps the paper\'s framing and links it.', 'harness is everything except the model'),
 ('owned:agents_and_retrieval/topic_agentic_harnesses/context_engineering', '', 'Compaction and agent memory in general are on Context engineering; Method keeps what Prime Agent does with them (originals kept in L3) and links it.', 'replaces the conversation with a model-written summary'),
 ('owned:measurement/topic_benchmarks/knowledge_and_reasoning', '', 'ARC-AGI-3 and RHAE are owned by Knowledge and reasoning benchmarks; Result 1 keeps the one-sentence definition and links it.', 'action efficiency against people, squared and level-weighted'),
 ('owned:models_and_training/topic_llm_training_and_post_training/reward_hacking', '', 'Specification gaming in general is on Reward hacking; the Factorio finding stays here and links it.', 'raising the proxy without raising the gold'),
 ('volatile', '', 'As of 25 October 2026 arXiv still lists v1 and the repository is at release v0.10.1 (21 October): dated closed block.', 'latest release v0.10.1 on 21 october 2026'),
]
F = HERE / 'ledger.json'
u = json.loads(F.read_text())
raw = (HERE.parent / 'index.html').read_text()
vis = ledger.norm(ledger.visible(PAGE))
body = re.sub(r'<script.*?</script>|<style.*?</style>', ' ', raw, flags=re.S)
det = ' '.join(ledger.norm(d) for d in re.findall(r'<details.*?</details>', body, flags=re.S))
def find_key(text):
    w = ledger.norm(text).split(' ')
    for n in (8, 6, 4):
        for i in range(0, max(1, len(w) - n + 1)):
            k = ' '.join(w[i:i + n])
            if len(k) >= 18 and k in vis and not re.fullmatch(r'[\W\d ]+', k):
                return k
    return ''
bad = 0
for x in u:
    if x.get('added'):
        continue
    x.pop('note', None)
    if x['id'] in FAT:
        x['label'], x['key'], x['note'] = 'fat', '', FAT[x['id']]; continue
    if x['id'] in VOLATILE:
        x['label'], x['key'] = 'volatile', VOLATILE[x['id']]; x['note'] = 'dated closed block'; continue
    if x['id'] in OWNED:
        o, k = OWNED[x['id']]; x['label'], x['key'] = 'owned:' + o, k; continue
    k = KEYS.get(x['id']) or find_key(x['text'])
    if not k:
        print('UNPLACED', x['id'], x['tab'], x['text'][:110]); bad += 1; x['label'], x['key'] = '', ''; continue
    x['key'] = k; x['label'] = 'depth' if k in det else 'core'
have = {x['text'] for x in u if x.get('added')}
n = max(x['id'] for x in u)
for lab, where, text, key in NEW:
    if text in have:
        continue
    n += 1; u.append({'id': n, 'tab': 't-read', 'section': 'light pass 2026-10-25', 'text': text, 'label': lab, 'key': key, 'where': where, 'added': True})
F.write_text(json.dumps(u, indent=1, ensure_ascii=False) + '\n')
c = {}
for x in u: c[x['label'].split(':')[0]] = c.get(x['label'].split(':')[0], 0) + 1
print('units', len(u), c, 'unplaced', bad)
