"""Transcribe the paper's tables (and the code repository's per-pair table) into tables.json, printed precision kept.

  python3 mk_tables.py      (build.sh runs it)

Parsed from the extracts in inputs/ (never retyped): Table 2 (inputs/table_S7_T2.txt), Table 3 (table_S7_T3.txt),
the 25 matched seed-pairs (inputs/table2_pairs.md, results/TABLE2_PAIRS.md of the code repository). Table 1 is a
2 x 2 of sentences, so its cells are copied as text with the numbers the extract prints. The cost, transfer and
master-against-served numbers are prose in the paper (sections 7.4, 7.6, 7.7); each row names its anchor.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
I = lambda f: open(os.path.join(HERE, 'inputs', f), encoding='utf-8').read()


def cells(txt):
    return [c.strip() for c in txt.replace('\t', '\n').split('\n') if c.strip()]


def num(s):
    s = s.replace('−', '-').replace('+', '')
    m = re.match(r'(-?[0-9.]+)(?: ± ([0-9.]+))?$', s)
    return (float(m.group(1)), float(m.group(2)) if m.group(2) else None) if m else (None, None)


def table2():
    c = cells(I('table_S7_T2.txt'))
    i = c.index('Δ') + 1  # header ends with the Delta column
    rows = []
    while i + 5 < len(c) + 1 and i < len(c):
        t, mo, n, a, b, d = c[i:i + 6]
        (am, asd), (bm, bsd) = num(a), num(b)
        rows.append({'task': t, 'model': mo, 'n': n, 'nearest': a, 'faircast': b, 'delta': d,
                     'nm': am, 'nsd': asd, 'fm': bm, 'fsd': bsd, 'd': num(d)[0]})
        i += 6
    return rows


def table3():
    c = cells(I('table_S7_T3.txt'))
    head = c[c.index('Arm') + 1:c.index('Arm') + 5]
    rows, i = [], c.index('Arm') + 5
    while i + 4 < len(c) + 1 and i < len(c):
        rows.append({'arm': c[i], 'vals': [float(x) for x in c[i + 1:i + 5]]})
        i += 5
    return {'cols': head, 'rows': rows}


def pairs():
    out = []
    for line in I('table2_pairs.md').splitlines():
        p = [x.strip() for x in line.strip().strip('|').split('|')]
        if len(p) == 8 and re.match(r'[0-9.]+$', p[5]):
            out.append({'task': p[0], 'model': p[1].replace('Qwen3-', ''), 'seed': int(p[2]), 'opt': p[3], 'n_eval': int(p[4]),
                        'nearest': float(p[5]), 'faircast': float(p[6]), 'delta': float(p[7].replace('+', ''))})
    return out


T = {
    '_doc': 'Generated by mk_tables.py from inputs/; do not edit by hand.',
    'table2': table2(),
    'table3': table3(),
    'pairs': pairs(),
    'table1': {
        'at': 'S7.T1',
        'rows': ['Round-to-nearest export', 'Unbiased export (SR or EF)'],
        'cols': ['Trainer forward on fp32 master', 'Trainer forward on served copy'],
        'cells': [['Current default; hidden lag (§4)',
                   'Same policy as the default (0.6B: knights-and-knaves 0.889 against 0.865, GSM8K 0.705 against 0.742)'],
                  ['Collapse: EF 0.00 (4/4 runs); SR 0.6B GSM8K 0.13, MATH 0.002', 'Fair Cast (§7.2 to §7.3)']],
    },
    'cost': {'at': 'S7.SS7', 'params_b': 1.72, 'nearest_ms': 4.3, 'sr_ms': 21.7, 'ef_ms': 37.2, 'sr_naive_ms': 136.6,
             'ef_resid_gb': 6.9, 'step_s': [31, 130], 'kk_step_s': [56.2, 56.0]},
    'transfer': {'at': 'S7.SS6', 'rows': [['AIME24 (cosine pair)', 0.152, 0.204], ['AMC23 (cosine pair)', 0.495, 0.548],
                                          ['MATH-500 (cosine pair)', 0.754, 0.790], ['GSM8K (cosine pair)', 0.83, 0.83],
                                          ['AIME24 (level-5 pair)', 0.165, 0.163]]},
    'master_gap': {'at': 'S7.SS4', 'he_served': 59.8, 'he_master': 9.1, 'rtn_runs': 9, 'rtn_gap12_any': 5, 'rtn_gap12_final': 2,
                   'fc_runs': 12, 'fc_max_gap': 3},
    'zebra_fc_runs': {'at': 'S7.SS2', 'vals': [0.623, 0.625, 0.703, 0.34],
                      'note': 'three seeds from inputs/table2_pairs.md plus the repeat of seed 0, which "fell to 0.34" (§7.2)'},
    'list_functions': {'at': 'S7.SS5', 'nearest': 0.668, 'faircast': 0.523, 'ema005': [0.707, 0.709], 'ema001': 0.666},
}
assert len(T['pairs']) == 25 and len(T['table2']) == 13 and len(T['table3']['rows']) == 3, (len(T['pairs']), len(T['table2']))
json.dump(T, open(os.path.join(HERE, 'tables.json'), 'w'), indent=1, ensure_ascii=False)
print('tables.json: table2 %d rows, pairs %d, table3 %d rows' % (len(T['table2']), len(T['pairs']), len(T['table3']['rows'])))
