"""Write parts/30_js_data.js (window.API_DATA) from the real captures and runs in inputs/ and the two service files.
Run from src/: python3 gen_data.py   (stdlib only)
  inputs/exchanges.json     captured by service/capture.py (the chat API, 2026-10-04)
  inputs/service_runs.json  recorded by service/run_experiments.py (handler styles, trace, background work,
                            shutdown, settings; 2026-10-24)
"""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
ex = json.load(open(os.path.join(H, 'inputs', 'exchanges.json')))
sr = json.load(open(os.path.join(H, 'inputs', 'service_runs.json')))
src = open(os.path.join(H, 'service', 'app.py')).read()
src2 = open(os.path.join(H, 'service', 'exp_app.py')).read()

keys = ['health', 'create_noauth', 'create', 'create_invalid', 'create_invalid_default', 'create_badjson', 'get', 'get_missing',
        'list_p1', 'list_p2', 'list_badlimit', 'msg_nokey', 'msg_first', 'msg_retry', 'msg_mismatch', 'msg_concurrent_first',
        'msg_concurrent', 'stream', 'rate_ok', 'rate_limited']
styles = {k: {'workers': v['workers'], 'wall_ms': v['wall_ms'], 'p50_ms': v['p50_ms'], 'max_ms': v['max_ms'],
              'req': [[r['send_ms'], r['recv_ms'], r['worker']] for r in sorted(v['requests'], key=lambda r: r['i'])]}
          for k, v in sr['styles'].items()}
D = {
    'meta': ex['meta'], 'timing': ex['timing'],
    'ex': {k: {'req': ex[k]['request'], 'res': ex[k]['response'], 'ms': ex[k]['ms']} for k in keys},
    'stream_ms': ex['stream'].get('arrivals_ms'),
    'runs': {'meta': sr['meta'], 'styles': styles, 'trace': sr['trace'], 'bg': sr['bg'],
             'shutdown': sr['shutdown'], 'settings': sr['settings']},
    'src': src, 'src2': src2,
}
s = json.dumps(D, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
open(os.path.join(H, 'parts', '30_js_data.js'), 'w').write(
    '// generated by gen_data.py from inputs/exchanges.json, inputs/service_runs.json, service/app.py and service/exp_app.py\n'
    'window.API_DATA=' + s + ';\n')
print(len(s), 'bytes')
