"""Latency histogram of the measured no-slowdown baseline (inputs/baseline_attempts.txt, 2026-10-04, Apple M1 Pro)
-> parts/23b_js_lat_data.js (window.LAT). Percentiles use statistics.quantiles(method='inclusive'),
which reproduces the p50 27.5, p90 42.5, p99 62.3, p99.9 72.3 ms quoted on the page. Run: python3 gen_lat_js.py"""
import json, statistics
from pathlib import Path
here = Path(__file__).parent
rows = [l.split() for l in open(here / 'inputs/baseline_attempts.txt') if not l.startswith('#')]
lat = sorted(float(r[3]) - float(r[2]) for r in rows if r[4] == 'ok')
q = statistics.quantiles(lat, n=1000, method='inclusive')
lo, hi = 20, 80
bins = [0] * (hi - lo)
for x in lat:
    bins[min(hi - lo - 1, max(0, int(x) - lo))] += 1
out = {'n': len(lat), 'lo': lo, 'bins': bins, 'p50': round(q[499], 1), 'p90': round(q[899], 1),
       'p99': round(q[989], 1), 'p999': round(q[998], 1), 'max': round(lat[-1], 1)}
(here / 'parts/23b_js_lat_data.js').write_text('// generated by src/gen_lat_js.py from inputs/baseline_attempts.txt; do not edit\nwindow.LAT=' + json.dumps(out, separators=(',', ':')) + ';\n')
print({k: v for k, v in out.items() if k != 'bins'})
