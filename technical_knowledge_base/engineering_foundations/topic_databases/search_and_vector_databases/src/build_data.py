# ---- two prose summaries generated from the numbers ----
def fr(c):
    x = F[c]; pf, st, rl, pre = x['hnsw_post_filter'], x['hnsw_strict'], x['hnsw_relaxed'], x['btree_prefilter_exact']
    pct = f"{100 * x['share_of_rows']:.0f}%"
    return (f"With a {pct} filter and iterative scans off, the HNSW scan returned {pf['rows_mean']:.2f} rows on average instead of 10 "
            f"({100 * pf['zero_rows_share']:.0f}% of queries returned nothing; recall {pf['recall10']:.2f}). strict_order returned {st['rows_mean']:.2f} rows "
            f"at recall {st['recall10']:.3f} in {st['p50_ms']:.1f} ms; relaxed_order {rl['rows_mean']:.2f} rows at recall {rl['recall10']:.3f} in {rl['p50_ms']:.1f} ms; "
            f"the B-tree pre-filter with exact search was always right (recall {pre['recall10']:.3f}) in {pre['p50_ms']:.1f} ms.")
f['filt_text'] = fr('tenant') + ' ' + fr('tenant10') + (' Iterative scans fix the empty results; the price is latency and, at the 1% filter, the 20,000-tuple scan limit. '
    'Pre-filtering wins when the filter is selective, because exact search over about 5,230 rows is cheap; at 10% it must compute about 52,300 distances per query.')
def hy(name, sc):
    b, v, h = sc['bm25_pg']['ndcg10'], sc['vector']['ndcg10'], sc['rrf_bm25_vec']['ndcg10']
    lead = f'vectors beat BM25 (nDCG@10 {v:.3f} against {b:.3f})' if v > b else f'BM25 beat vectors (nDCG@10 {b:.3f} against {v:.3f})'
    res = 'fusion beat both' if h > max(b, v) else ('fusion landed between them' if h > min(b, v) else 'fusion was worst')
    return f"On {name}, {lead} and {res} ({h:.3f})."
w = m2['quora']['wins']
f['hyb_text'] = (hy('Quora', qs) + ' ' + hy('SciFact', ss) + f" Per question on Quora, BM25 was better on {w['bm25_better_than_vector']}, vectors on {w['vector_better_than_bm25']}, and they tied on {w['tie']}: "
    'the two retrievers fail on different questions, which is what fusion exploits when both are comparably strong (SciFact) and why an equal-weight fusion costs a little when one is much stronger (Quora). Requiring every word (fts_and) or ranking without idf (fts_or) costs the most; '
    'the HNSW index (ef_search 100) gave up little against exact vector search.')
json.dump(f, open(os.path.join(H, 'facts.json'), 'w'), indent=1)
print('facts', len(f), 'data bytes', os.path.getsize(os.path.join(H, 'parts/22_js_data.js')))
