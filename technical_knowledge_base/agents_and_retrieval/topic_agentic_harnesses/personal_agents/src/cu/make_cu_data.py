#!/usr/bin/env python3
"""cu/out/cu.json (written by capture.mjs) -> parts/22_js_cu_0data.js (window.HPCU), the Reading section 2 figure's data."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
c = json.load(open(os.path.join(H, "out", "cu.json")))
pick = lambda st: {e["name"]: [e["x"], e["y"], e["w"], e["h"]] for e in c[st] if e["w"]}
d = {"viewport": c["viewport"], "click": c["click"], "shift": c["shift"], "under": c["under"], "ax": c["ax"],
     "plain": pick("plain"), "banner": pick("banner"), "browser": c["browser"]}
open(os.path.join(H, "..", "parts", "22_js_cu_0data.js"), "w").write(
    "// generated by src/cu/make_cu_data.py from src/cu/out/cu.json: do not edit\nwindow.HPCU=" + json.dumps(d, separators=(",", ":")) + ";\n")
print("click", d["click"], "shift", d["shift"], "under", d["under"], "ax lines", len(d["ax"]))
