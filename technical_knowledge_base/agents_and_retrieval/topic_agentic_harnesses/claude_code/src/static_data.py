def tools():
    rows = []
    for line in open(os.path.join(HERE, "inputs", "tools_table_2.1.290.md")):
        m = re.match(r"\| `(\w+)` \| (.*) \| (Yes|No) \|\s*$", line)
        if not m:
            continue
        name, desc, perm = m.groups()
        desc = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", desc).replace("`", "")
        first = re.split(r"(?<=[a-z0-9)])\. ", desc)[0].rstrip(".")
        rows.append({"n": name, "d": first, "p": perm == "Yes", "c": CAT.get(name, "other"), "s": SEEN.get(name, "")})
    return rows

def hooks():
    ev = json.load(open(os.path.join(HERE, "inputs", "hook_events_2.1.290.json")))
    out = []
    for r in ev:
        b = r["b"]
        can = b.startswith("Yes") or r["e"] == "PermissionRequest"
        out.append({"e": r["e"], "w": r["w"], "m": r["m"], "b": b, "d": r["d"], "can": can})
    return out

if __name__ == "__main__":
    t, h = tools(), hooks()
    js = "// Generated by src/static_data.py from inputs/ (Claude Code 2.1.290 docs, read 6 Oct 2026). Do not edit by hand.\nwindow.HCC_STATIC=" + json.dumps({"tools": t, "hooks": h}, ensure_ascii=False, separators=(",", ":")) + ";\n"
    assert chr(0x2014) not in js
    open(OUT, "w").write(js.replace("</", "<\\/"))
    print(len(t), "tools,", len(h), "hook events,", sum(x["can"] for x in h), "can block,", len(js), "bytes")
