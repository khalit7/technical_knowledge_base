#!/usr/bin/env python3
"""Classify every recorded model call by what came of it, for the Reading figure "How each run ended"
(section 2). Reads recordings/*.json (already redacted) and writes parts/19_js_data_ends.js (window.HR_ENDS).

One letter per call, decided by the call itself and by the next message the harness sent back:
  A  acted, and the harness returned a real result
  E  acted, and the harness returned an error or refused the reply
  S  acted (a sed or edit command), exit 0 and empty output: a silent no-op
  P  a reply with no action: prose or an empty message
  X  a side call: session title, commit message, history summary
  U  a call made by a subagent
Text-protocol runs (Aider, mini-SWE-agent text mode) carry their action in the reply text, so every main
call of theirs counts as acting. The end reasons are written by hand from the recordings (exit status,
last reply) and checked below against what the data shows."""
import json, re
from pathlib import Path

S = Path(__file__).resolve().parent
order = json.loads((S / "recordings" / "order.json").read_text())
ERR = re.compile(r"^\s*(`justification` requires|\[An error occurred|Error validating|Tool call error|Format error)")
SILENT = re.compile(r'^\s*(\{\s*"returncode": 0,\s*"output": ""\s*\}|<returncode>0</returncode>\s*<output>\s*</output>)\s*$')
# the stored extract cuts long replies at 720 characters; this call's sed command falls after the cut
# (the text says it is about to fix top_words, and the next observation is empty output with exit 0)
SED_CUT = {("mswe_local_text", 3)}
TEXT = {"aider_diff_1", "aider_whole_1", "aider_haiku_diff", "mswe_local_text", "mswe_haiku_free", "mswe_haiku_cut"}
END = {
    "codex_1": "prose hit the 2,048-token cap; no tool call ends the turn",
    "gemini_1": "an empty reply ends the loop",
    "opencode_1": "prose describing the fix, no edit call: loop ends",
    "aider_diff_1": "tests pass",
    "aider_whole_1": "tests pass",
    "aider_haiku_diff": "tests pass",
    "ohs_1": "our 30-iteration cap",
    "mswe_local_tool": "three replies in a row with no tool call",
    "mswe_local_text": "submitted after a check that passes with the bug",
    "mswe_haiku_free": "submitted; no file changed",
    "mswe_haiku_cut": "submitted; no file changed",
}
out = {}
for rid in order:
    r = json.loads((S / "recordings" / f"{rid}.json").read_text())
    cs = r["calls"]
    cats = ""
    for i, c in enumerate(cs):
        nxt = cs[i + 1]["obs"] if i + 1 < len(cs) else ""
        if c["kind"] in ("title", "commit message", "history summary", "compaction"):
            cats += "X"
        elif c["kind"] == "subagent":
            cats += "U"
        elif c.get("acts") or rid in TEXT:
            act = " ".join(a["args"] for a in c.get("acts") or []) + (c.get("full_text") or c.get("text") or "")
            if nxt and ERR.match(nxt):
                cats += "E"
            elif nxt and SILENT.match(nxt) and (re.search(r"sed -i|str_replace", act) or (rid, i) in SED_CUT):
                cats += "S"
            else:
                cats += "A"
        else:
            cats += "P"
    out[rid] = {"cats": cats, "end": END[rid]}
# checks against facts the page states in prose
o = out
assert o["codex_1"]["cats"] == "EEEEP", o["codex_1"]
assert o["gemini_1"]["cats"].endswith("P") and o["gemini_1"]["cats"].count("P") == 1
assert o["opencode_1"]["cats"].startswith("X") and o["opencode_1"]["cats"].endswith("P") and o["opencode_1"]["cats"].count("U") == 6
assert o["ohs_1"]["cats"].count("E") == 7, o["ohs_1"]  # 5 refused str_replace, 1 bad path, 1 misspelt field
assert o["mswe_local_tool"]["cats"].count("S") == 6 and o["mswe_local_tool"]["cats"].endswith("PPP"), o["mswe_local_tool"]
assert o["mswe_local_text"]["cats"].count("S") == 1
assert o["mswe_haiku_free"]["cats"].count("E") == 5
for k, v in out.items():
    print(f"{k:18} {v['cats']}")
s = json.dumps(out, separators=(",", ":"), ensure_ascii=False)
(S / "parts" / "19_js_data_ends.js").write_text("// generated by src/derive_ends.py, do not edit\nwindow.HR_ENDS=" + s + ";\n")
