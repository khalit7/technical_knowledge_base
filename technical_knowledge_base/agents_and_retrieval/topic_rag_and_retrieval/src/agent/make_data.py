"""Build ../parts/33_js_agt_0data.js (window.AGTD) from out/*.json plus the replay trajectories (real runs of a few test
questions under the pipeline, the agent loop and decomposition). Deterministic; run after summarize.py.
usage: python -I -B make_data.py"""
import os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import json

from common import OUT, HERE, data, jl_read, work, save

PART = os.path.join(HERE, "..", "parts", "33_js_agt_0data.js")
MODES = ("single_k5", "react", "decomp")


def events(strategy, row):
    ev = []
    if strategy == "single_k5":
        for s in row["steps"]:
            if s["kind"] == "search":
                ev += [{"k": "search", "q": s["query"], "c": None}, {"k": "obs", "p": s["pids"], "c": None}]
            elif s["kind"] == "answer":
                ev.append({"k": "answer", "t": row["answer"], "c": 0})
    elif strategy == "react":
        for i, s in enumerate(row["steps"]):
            if s.get("thought"):
                ev.append({"k": "think", "t": s["thought"], "c": i})
            if s["kind"] == "search":
                ev += [{"k": "search", "q": s["query"], "c": i}, {"k": "obs", "p": s["pids"], "c": None}]
            elif s["kind"] == "finish":
                ev.append({"k": "answer", "t": s["answer"], "c": i})
            elif s["kind"] == "noaction":
                ev.append({"k": "noaction", "t": s["text"], "c": i})
    elif strategy == "decomp":
        j = 0
        for s in row["steps"]:
            if s["kind"] == "decompose":
                ev.append({"k": "decomp", "subs": s["subs"], "c": 0})
            elif s["kind"] == "search":
                j += 1
                ev += [{"k": "search", "q": s["query"], "c": None}, {"k": "obs", "p": s["pids"], "c": None},
                       {"k": "sub", "t": s["sub_answer"], "c": j}]
            elif s["kind"] == "answer":
                ev.append({"k": "answer", "t": row["answer"], "c": len(row["calls"]) - 1})
    return ev


def replay(models, picks):
    qs, _, by = data()
    Q = {q["qid"]: q for q in qs}
    runs = {m: {s: {r["qid"]: r for r in jl_read(work("runs", "test_%s_%s.jsonl" % (m, s)))} for s in MODES} for m in models}
    items, pids = [], set()
    for qid, label in picks:
        q = Q[qid]
        it = {"qid": qid, "label": label, "question": q["question"], "gold": q["answer"], "type": q["type"], "gold_pids": q["gold_pids"], "runs": {}}
        for m in models:
            it["runs"][m] = {}
            for s in MODES:
                r = runs[m][s].get(qid)
                if not r:
                    continue
                it["runs"][m][s] = {"events": events(s, r), "answer": r["answer"], "em": r["em"], "f1": r["f1"],
                                    "calls": [{k: c[k] for k in ("n_in", "n_in_new", "n_out", "seconds")} for c in r["calls"]]}
                pids |= set(r["seen"])
        pids |= set(q["gold_pids"])
        items.append(it)
    return {"models": models, "items": items, "titles": {p: by[p]["title"] for p in sorted(pids)},
            "snip": {p: (by[p]["text"][:110].rsplit(" ", 1)[0] + "...") for p in sorted(pids)}}


def main():
    D = {}
    for name in ("hops", "strategies", "steps", "position", "tune", "router", "graphrag"):
        p = os.path.join(OUT, name + ".json")
        if os.path.exists(p):
            D[name] = json.load(open(p))
    picks = json.load(open(os.path.join(OUT, "replay_picks.json"))) if os.path.exists(os.path.join(OUT, "replay_picks.json")) else None
    if picks:
        D["replay"] = replay(picks["models"], picks["items"])
    js = ("// generated by src/agent/make_data.py from src/agent/out/*.json and the recorded runs: do not edit by hand\nwindow.AGTD=" +
          json.dumps(D, separators=(",", ":"), ensure_ascii=False).replace("\u2014", ": ") + ";\n")
    open(PART, "w").write(js)
    print("wrote", PART, len(js.encode()), "bytes")


if __name__ == "__main__":
    main()
