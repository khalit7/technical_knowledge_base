"""Build ../parts/31_js_pip_0data.js (window.PIPD) from the measured results in out/*.json plus the real examples
the page shows (the funnel query, the RRF calculator's lists, the chunking explorer's paper, the per-query arrays
behind the K and k slider). Deterministic; run after every measuring script.
usage: python -I -B make_data.py"""
import os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import json
from common import L, OUT, HERE, work, r3
import fusion as F

PART = os.path.join(HERE, "..", "parts", "31_js_pip_0data.js")
D = {}
for name in ("fusion", "fusion_tuned", "filter", "chunking", "rerank", "qtrans", "e2e", "latency", "funnel", "chunk_explorer"):
    p = os.path.join(OUT, name + ".json")
    if os.path.exists(p):
        D[name] = json.load(open(p))

# ---- RRF calculator: real top-30 lists of a few SciFact claims
corpus, queries, qrels = L.beir("scifact")
bm = L.run("scifact", "bm25"); de = L.run("scifact", "qwen3-emb-0.6b")
RRFQ = ["70", "294", "659", "1368", "452"]
docs = {}
calc = []
for q in RRFQ:
    b, d = list(bm[q])[:30], list(de[q])[:30]
    for x in b + d:
        docs[x] = corpus[x]["title"][:110]
    calc.append({"qid": q, "claim": queries[q], "rel": sorted(qrels["test"][q]), "bm25": b, "dense": d,
                 "bm25_s": [round(bm[q][x], 2) for x in b], "dense_s": [round(de[q][x], 4) for x in d]})
D["rrf_calc"] = {"queries": calc, "titles": docs}
qg = work("qtrans_gen.json")
if os.path.exists(qg):
    G = json.load(open(qg))
    D["qtrans_conv"] = [{k: c[k] for k in ("qid", "turn1", "turn2", "rewrite")} for c in G["conv"]]
    D["qtrans_cost"] = G["cost"]
    D["qtrans_example"] = {"qid": "70", "claim": queries["70"], "hyde": G["hyde"]["70"], "mq": G["mq"]["70"]}

# titles and texts are quoted from the datasets; the page style has no em dashes, so they become colons
js = "// generated by src/pipe/make_data.py from src/pipe/out/*.json: do not edit by hand\nwindow.PIPD=" + json.dumps(D, separators=(",", ":"), ensure_ascii=False).replace("\u2014", ": ") + ";\n"
open(PART, "w").write(js)
print("wrote", PART, len(js.encode()), "bytes")
