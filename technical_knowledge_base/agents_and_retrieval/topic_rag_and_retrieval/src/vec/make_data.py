"""Turn out/*.json into ../parts/32_js_vec_0data.js (window.VECD), keeping only what the tab draws.
Run after the analysis scripts; then sh ../build.sh."""
import json
import os

H = os.path.dirname(os.path.abspath(__file__))
o = lambda n: json.load(open(os.path.join(H, "out", n)))

proj = o("proj.json")
for p in proj["points"]:
    p["t"] = p["t"][:72]
    if p["s"] != "c":
        p.pop("id")
mq = o("mrl_quant.json")
tr = o("two_recalls.json")
for r in tr["rows"]:
    r.pop("params", None)
D = dict(
    proj=proj,
    models=o("models.json"),
    mq=mq,
    tr=dict(rows=tr["rows"], n=tr["n"], d=tr["d"], queries=tr["queries"], faiss=tr["faiss"]),
    lists=o("lists.json"),
    con=o("contrastive.json"),
    front=o("frontier.json"),
)
if os.path.exists(os.path.join(H, "out", "metric.json")):
    D["metric"] = o("metric.json")
def clean(x):
    """No em-dashes anywhere on the page (house rule): titles quoted from the corpora get a comma instead."""
    if isinstance(x, str):
        return x.replace(" \u2014 ", ", ").replace("\u2014", ", ")
    if isinstance(x, list):
        return [clean(v) for v in x]
    if isinstance(x, dict):
        return {k: clean(v) for k, v in x.items()}
    return x


D = clean(D)
s = "// generated by src/vec/make_data.py from src/vec/out/*.json: do not edit\nwindow.VECD=" + json.dumps(D, separators=(",", ":"), ensure_ascii=False) + ";\n"
p = os.path.join(H, "..", "parts", "32_js_vec_0data.js")
open(p, "w").write(s)
print("wrote", p, len(s.encode()), "bytes")
