"""Assemble everything the page embeds into parts/22_ing_data.js (window.ING) (check_data.py reads it back). Inputs are the small result files in data/ (copied from the scratch runs by
scripts/collect.py) and the page images in data/img/.
usage: python3 build_data.py"""
import base64, json, os

H = os.path.dirname(os.path.abspath(__file__))
DD = os.path.join(H, "data")


def j(name):
    return json.load(open(os.path.join(DD, name)))


def img(name):
    p = os.path.join(DD, "img", name)
    return "data:image/jpeg;base64," + base64.b64encode(open(p, "rb").read()).decode()


ING = {}
have = lambda n: os.path.exists(os.path.join(DD, n))
if have("anatomy.json"):
    ING["anat"] = j("anatomy.json"); ING["anatImg"] = img(ING["anat"]["img"])
if have("view.json"):
    ING["view"] = j("view.json")
    for p in ING["view"]["pages"]:
        p["img"] = img(p["img"])
if have("table_auto.json"):
    ING["table"] = j("table_auto.json")
    if have("table_text.json"):
        ING["table"].update(j("table_text.json"))
    if ING["table"].get("img"):
        ING["table"]["img"] = img(ING["table"]["img"])
if have("cd.json"):
    ING["cd"] = j("cd.json")
if have("mm_auto.json"):
    ING["mm"] = j("mm_auto.json")
    if have("mm_text.json"):
        ING["mm"].update(j("mm_text.json"))
    ING["mm"]["thumbs"] = {k: img(v) for k, v in ING["mm"]["thumbs"].items()}
if have("results_auto.json"):
    ING["res"] = j("results_auto.json")
    for extra in ("results_pub.json", "results_text.json"):
        if have(extra):
            ING["res"].update(j(extra))
if have("record.json"):
    ING["rec"] = j("record.json")
    if os.path.exists(os.path.join(DD, "img", "rec_1909.00175_p3.jpg")):
        ING["recImg"] = img("rec_1909.00175_p3.jpg")  # page 3 of arXiv 1909.00175 v1, rendered by pdftoppm (grey, 400 px wide)
s = json.dumps(ING, ensure_ascii=False, separators=(",", ":"))
# house style: no em dashes anywhere on the page, including inside parser outputs shown verbatim (shown as en dashes)
s = s.replace("\u2014", "\u2013")
open(os.path.join(H, "parts", "22_ing_data.js"), "w").write("// ---- generated by src/build_data.py: every number and output the page shows ----\nwindow.ING=" + s + ";\n")
print("22_ing_data.js", len(s), "bytes")
