"""Write parts/22_js_hs.js (window.HS) from inputs/tb2_same_model_agents_2026-10-05.json:
every agent listed on the Terminal-Bench 2.0 public board for four models, with the board's mean and 95% half-width.
usage (from src/): python3 mk_harness.py"""
import json, re
d = json.load(open('inputs/tb2_same_model_agents_2026-10-05.json'))
ORDER = ['Claude Opus 4.6', 'GPT-5.3-Codex', 'Gemini 3.1 Pro', 'GPT-5']
OWN = {'Claude Opus 4.6': 'Claude Code', 'GPT-5.3-Codex': 'Simple Codex', 'Gemini 3.1 Pro': 'Gemini CLI', 'GPT-5': 'Codex CLI'}
models = []
for m in ORDER:
    rows = [r for r in d['rows'] if r['model'] == m]
    ag = []
    for r in rows:
        ci = float(re.match(r'\+/- ([\d.]+)', r['ci']).group(1))
        org = re.search(r'agent org ([^;]+);', r['note'] or '')
        ver = 'verified True' in (r['note'] or '')
        kind = 'own' if r['harness'] == OWN[m] else 'neutral' if r['harness'] == 'Terminus 2' else 'third'
        ag.append({'h': r['harness'], 'v': r['value'], 'ci': ci, 'org': org.group(1) if org else '', 'ver': ver, 'k': kind})
    ag.sort(key=lambda a: a['v'])
    models.append({'m': m, 'date': rows[0]['date'], 'a': ag, 'lo': ag[0]['v'], 'hi': ag[-1]['v']})
out = {'src': 'https://www.tbench.ai/?version=2.0', 'read': '2026-10-05', 'models': models}
open('parts/22_js_hs.js', 'w').write('// ---- generated by src/mk_harness.py from inputs/tb2_same_model_agents_2026-10-05.json (do not edit by hand) ----\nwindow.HS=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
for m in models:
    print(m['m'], len(m['a']), 'agents', m['lo'], 'to', m['hi'], 'spread', round(m['hi'] - m['lo'], 1))
