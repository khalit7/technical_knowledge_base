// ---- Scene: Fig. 1 (stg-life), the life of a benchmark, then every family (renderer v2, 25_js_s3.js) ----
// Time runs left to right, score up a glass plate (one plate per benchmark, 0 to 100%), the seven families are lanes in depth, each named by its child page.
// Steps 1 to 4 follow MMLU from launch to saturation (the points of the old stepper, read/recompute.py); step 5 its successors in the same lane
// (GPQA Diamond and HLE, best score so far in Epoch AI's runs from data/saturation.json); step 6 the Agentic lane (Terminal-Bench versions and
// Terminal-Bench-Science 0.1); step 7 every benchmark in the Benchmark atlas as a tile at its launch year, coloured by status (data/atlas.json).
// Data: window.LIFE3D (26_js_sc_life_data.js, generated by read/make_life3d.py).
(function(){
  if(!document.getElementById('stg-life')||!window.S3||!window.LIFE3D)return;
  const {mix,cl,lerp}=S3,D=window.LIFE3D;
  const win=(e,a,b)=>cl((e-a)/(b-a),0,1);
  const yf=s=>{const y=+s.slice(0,4),d=Date.UTC(y,+s.slice(5,7)-1,+s.slice(8,10))-Date.UTC(y,0,1);return y+d/864e5/365.25};
  const X=t=>(t-2022.4)*1.25,YS=2.0/100,Y=v=>v*YS,HT=2.0;
  const ZL=i=>3.6-i*1.2,ZK=ZL(0),ZA=ZL(3);
  const asOf=yf(D.as_of);
  const MM=D.R.then,TS=D.R.now;
  const Z={mmlu:ZK+.38,gpqa:ZK,hle:ZK-.38,tb2:ZA+.36,tb3:ZA+.12,tb4:ZA-.12,tbs:ZA-.36};
  // MMLU's plate grows with the story: its right edge is the date each step has reached
  const mEnd=[yf(MM[0].date)+.55,yf(MM[2].date)+.35,2024.05,yf(MM[3].date)+.3,asOf,asOf,asOf];
  // a label is drawn only once the camera has arrived, so labels never cross while the view moves
  let moving=false;
  function lab(R,p,t,o){if(moving)return;const q=R.p(p);if(q[2]<=0)return;R.label(p,t,o)}
  function plate(R,x0,x1,z,c,a,nv){if(a<=.01||x1-x0<.005)return;R.glass([x0,0,z],[x1-x0,0,0],[0,HT,0],{c,a,nu:Math.max(1,Math.round((x1-x0)/.62)),nv:nv||4,th:.02})}
  // a frontier as dots joined by a line, up to time tmax; flow: dots stream up it while it is the subject
  function curve(R,pts,z,c,a,tmax,flow){const q=pts.filter(p=>yf(p[0])<=tmax+1e-6).map(p=>[X(yf(p[0])),Y(p[1]),z+.03]);if(!q.length||a<=.01)return q;
    if(q.length>1)R.line(q,{c,w:2.2,a});q.forEach(p=>R.ball(p,.055,{c,a}));if(flow&&q.length>1)R.flow(q,{c,r:.05,n:Math.max(4,q.length*3),speed:.9,a:a*.9});return q}
  const pm=r=>[r.date,r.score,r.model];
  function draw(R,k,e,st){const P=R.P,late=win(e,.55,1),pk=st&&st.pk!=null?st.pk:k;moving=e<.55&&k!==pk;
    R.grid(-6.2,6.2,-4.4,4.6,.5);
    const end=lerp(mEnd[pk===k?Math.max(0,k-1):pk],mEnd[k],k===0?1:e);
    // ---- the MMLU plate (Knowledge and reasoning lane) ----
    const mA=k<=3?1:k===4?lerp(1,.32,e):k===5?.6:lerp(.6,.14,e);
    const mC=k>=4?mix(P.c1,P.mute,k===4?e*.6:.6):P.c1;
    plate(R,X(yf(MM[0].date)),X(end),Z.mmlu,mC,(k===0?e:1)*mA);
    const mPts=MM.map(pm);
    if(k<=3){
      // chance, then the error band of the answer key
      lab(R,[X(yf(MM[0].date)),HT,Z.mmlu],'MMLU · 57 subjects',{fs:13,b:1,c:P.c1,al:'left',dy:-12,a:late});
      R.line([[X(yf(MM[0].date)),Y(25),Z.mmlu+.03],[X(end),Y(25),Z.mmlu+.03]],{c:P.mute,w:1.2,dash:[4,4],a:(k===0?e:1)*.9});
      if(k===0)lab(R,[X(end),Y(25),Z.mmlu],'chance 25%',{fs:12,mono:1,c:P.mute,al:'left',dx:8,a:late});
      lab(R,[X(yf(MM[0].date)),HT,Z.mmlu],'100%',{fs:12,mono:1,c:P.mute,al:'right',dx:-8,a:late,wide:1});
      lab(R,[X(yf(MM[0].date)),0,Z.mmlu],'0%',{fs:12,mono:1,c:P.mute,al:'right',dx:-8,dy:-4,a:late,wide:1});
    }
    const shown=k===0?1:k===1?3:k===2?3:4;
    const mq=curve(R,mPts.slice(0,shown),Z.mmlu,mC,(k===0?e:1)*(k<=3?1:k===5?.9:mA),end,k===1||k===5);
    if(k<=1){const rs=k===0?[0]:[1,2];rs.forEach(i=>{const p=mq[i];if(!p)return;const r=MM[i];
      lab(R,p,r.model+' '+r.score.toFixed(1)+'%'+(i===2?' · day '+r.days:''),{fs:12.5,b:1,c:P.ink,al:i===2?'right':'left',dx:i===2?-10:10,dy:i===2?-12:i===1?14:0,a:late})});
      if(k===0)R.glow(mq[0],.35,{c:P.c1,a:.5*e})}
    // ---- step 3: contamination: items leak into a training crawl and come back as memory ----
    const crawl=[X(2022.2),0,ZK+1.45];
    const cA=k===2?e:k===3?lerp(1,.28,e):0;
    if(cA>.01){R.box(crawl,[1.5,.5,.7],{fill:mix(P.paper,P.c5,.35),a:cA});
      R.flowArc([X(2021.3),Y(60),Z.mmlu],[crawl[0]-.35,.5,crawl[2]],.45,{c:P.c5,a:cA,r:.06,n:10,speed:1.1});
      R.flowArc([crawl[0]+.35,.5,crawl[2]],[mq[2]?mq[2][0]:X(2023),Y(84),Z.mmlu],.45,{c:P.bad,a:cA*.9,r:.06,n:9,speed:1.1});
      if(k===2){lab(R,[crawl[0],0,crawl[2]+.35],'web crawl → training data',{fs:12.5,b:1,c:P.c5,dy:14,a:late});
        lab(R,[X(2021.3),Y(60),Z.mmlu],'test items copied to the web',{fs:12,c:P.mute,al:'right',dx:-10,a:late,wide:1});
        lab(R,[mq[2]?mq[2][0]:X(2023),Y(86.4),Z.mmlu],'GPT-4 restores a masked option 57% of the time',{fs:12,c:P.bad,al:'right',dx:-12,dy:-14,a:late})}}
    // ---- step 4: saturation: the top of the plate is the answer key's error ----
    const bA=k===3?e:k===4?lerp(1,.4,e):k>=5?(k===5?.4:lerp(.4,0,e)):0;
    if(bA>.01){const x0=X(yf(MM[0].date));R.glass([x0,Y(93.5),Z.mmlu+.005],[X(end)-x0,0,0],[0,Y(6.5),0],{c:P.bad,a:bA,nu:6,nv:1,th:.02})}
    if(k===3){const p=mq[3];if(p){R.glow(p,.32,{c:P.bad,a:.5*e});lab(R,p,'o1 92.3%',{fs:12.5,b:1,c:P.ink,al:'right',dx:-10,dy:8,a:late})}
      lab(R,[X(end),Y(96.7),Z.mmlu],'≈6.5% of questions flawed (MMLU-Redux)',{fs:12,b:1,c:P.bad,al:'right',dx:-6,dy:-22,a:late})}
    // ---- step 5: the successors in the same lane ----
    const sA=k<4?0:k===4?e:k===5?.35:lerp(.35,.12,e);
    if(sA>.01){const g=D.gpqa,h=D.hle,t=k===4?lerp(yf(g.launch),asOf,e):asOf;
      plate(R,X(yf(g.launch)),X(Math.max(yf(g.launch),t)),Z.gpqa,P.c4,sA);curve(R,g.pts,Z.gpqa,P.c4,sA,t,k===4);
      const th=Math.max(yf(h.launch),t);if(t>=yf(h.launch)){plate(R,X(yf(h.launch)),X(th),Z.hle,P.c6,sA);curve(R,h.pts,Z.hle,P.c6,sA,th,k===4)}
      if(k===4){R.flowArc([X(2024.4),HT,Z.mmlu],[X(2024.9),HT,Z.gpqa],.35,{c:P.c4,a:late*.8,r:.05,n:5});R.flowArc([X(2025.6),HT,Z.gpqa],[X(2025.9),HT,Z.hle],.35,{c:P.c6,a:late*.8,r:.05,n:5});
        const gl=g.pts[g.pts.length-1],hl=h.pts[h.pts.length-1];
        lab(R,[X(yf(gl[0])),Y(gl[1]),Z.gpqa],'GPQA Diamond '+gl[1].toFixed(1)+'%',{fs:12.5,b:1,c:P.c4,al:'right',dx:-14,dy:-16,a:late});
        lab(R,[X(yf(hl[0])),Y(hl[1]),Z.hle],'HLE '+hl[1].toFixed(1)+'%',{fs:12.5,b:1,c:P.c6,al:'right',dx:-14,dy:14,a:late});
        lab(R,[X(yf(MM[3].date)),Y(92.3),Z.mmlu],'MMLU: replaced',{fs:12,c:P.mute,al:'right',dx:-10,dy:-8,a:late,wide:1})}}
    // ---- step 6: the Agentic lane, where a benchmark now lasts weeks ----
    const aA=k<5?0:k===5?win(e,.45,1):lerp(1,.14,e);
    if(aA>.01){D.tb.forEach(([n,d0,d1],i)=>{const z=[Z.tb2,Z.tb3,Z.tb4][i];plate(R,X(yf(d0)),X(d1?yf(d1):asOf),z,P.c2,aA*.45,4)});
      const tb0=yf(TS[0].date);plate(R,X(tb0),X(asOf),Z.tbs,P.c2,aA);
      const tq=curve(R,TS.map(pm),Z.tbs,P.c2,aA,asOf,k===5);
      if(k===5){tq.forEach((p,i)=>R.ball(p,.075,{c:P.c2,a:e}));R.glow(tq[2],.4,{c:P.c2,a:.45*e});
        const r=TS[2],m=MM[2];
        lab(R,tq[2],'Terminal-Bench-Science 0.1: +'+r.gain.toFixed(1)+' in '+r.days+' days',{fs:12.5,b:1,c:P.c2,al:'right',dx:-12,dy:-14,a:late});
        lab(R,mq[2]||[X(2023.2),Y(86.4),Z.mmlu],'MMLU: +'+m.gain.toFixed(1)+' in '+m.days+' days',{fs:12.5,b:1,c:P.c1,al:'right',dx:-12,dy:-10,a:late});}}
    // ---- step 7: every family: each atlas benchmark a tile at its launch year, by status ----
    if(k===6){const a=e;
      const COL={r:mix(P.paper,P.mute,.28),s:mix(P.paper,P.c5,.62),a:mix(P.paper,P.good,.62)},ORD={r:0,s:1,a:2};
      D.lanes.forEach((L,i)=>{const z=ZL(i),by={};L.b.forEach(b=>(by[b[0]]=by[b[0]]||[]).push(b));
        Object.keys(by).forEach(yr=>{const bs=by[yr].sort((u,v)=>ORD[u[1]]-ORD[v[1]]);bs.forEach((b,j)=>{const tj=win(a,.05+.5*(i/7),.45+.5*(i/7));
          R.box([X(+yr+.5),j*.15,z],[.95,.13,.62],{fill:COL[b[1]],a:tj,shadow:j===0,lw:.6})})});
        const c=D.counts[L.k];
        lab(R,[X(2017.95),0,z],L.n,{fs:12,b:1,c:P.ink,al:'right',dx:-4,a:late,grp:'lane'});
        lab(R,[X(2027.1),0,z],c.a+' of '+c.n,{fs:12.5,mono:1,b:1,c:P.good,al:'left',dx:4,a:late,grp:R.W<520?undefined:'cnt'});   // a phone keeps the counts (the step text names the lanes)
        // the family keeps replacing its benchmarks: a slow stream along the lane, from the oldest tile to the newest
        const ys=L.b.map(b=>b[0]);R.flow([[X(Math.min(...ys)+.5),.06,z+.36],[X(Math.max(...ys)+.5),.06,z+.36]],{c:P.good,a:late*.55,r:.045,n:5,speed:.7})});
      lab(R,[X(2027.1),0,ZL(6)-.9],'still discriminating',{fs:12,c:P.good,al:'left',dx:-10,a:late,wide:1});
      [2018,2020,2022,2024,2026].forEach(y=>lab(R,[X(y+.5),0,ZL(0)+.7],String(y),{fs:12,mono:1,c:P.mute,dy:6,a:late}))}
    else if(k>=4)[2020,2022,2024,2026].forEach(y=>lab(R,[X(y+.5),0,ZK+.9],String(y),{fs:12,mono:1,c:P.mute,dy:6,a:late,wide:1}));
  }
  const full={cam:[.08,.86],bounds:[[-5.45,0,-3.9],[5.65,1.5,4.35]]};
  const V=[
    {cam:[.3,.36],bounds:[[X(2020.4),0,ZK-.4],[X(2022.1),HT+.15,ZK+.6]]},
    {cam:[.28,.36],bounds:[[X(2020.4),0,ZK-.4],[X(2023.9),HT+.15,ZK+.6]]},
    {cam:[.26,.42],bounds:[[X(2020.4),0,ZK-.4],[X(2024.4),HT+.15,ZK+2.0]]},
    {cam:[.26,.4],bounds:[[X(2020.4),0,ZK-.4],[X(2025.3),HT+.15,ZK+2.0]]},
    {cam:[.22,.42],bounds:[[X(2020.4),0,ZK-.8],[X(2027.6),HT+.1,ZK+.9]]},
    {cam:[.2,.5],bounds:[[X(2020.4),0,ZA-.8],[X(2027.4),HT,ZK+.9]]},
    full];
  // the last step needs room for the lane names (left) and counts (right); the close views do not: the margin glides with the camera
  let api=null;const M0=[30,40,30,60],M6=[22,78,22,172],P0=[22,10,22,10],P6=[22,62,22,10];
  const marg=w=>{const s=api&&api.st;if(w<520){if(!s)return P6;const t=S3.RM?1:S3.ease(s.e),f=s.k===6?(s.pk===6?1:t):s.pk===6?1-t:0;return P0.map((v,i)=>lerp(v,P6[i],f))}if(!s)return M6;const t=S3.RM?1:S3.ease(s.e),f=s.k===6?(s.pk===6?1:t):s.pk===6?1-t:0;return M0.map((v,i)=>lerp(v,M6[i],f))};
  api=S3.stage({id:'stg-life',list:'sx-life',fig:'Fig. 1 · the life of a benchmark, then every family',cam:full.cam,bounds:full.bounds,aspect:.56,dur:2200,hold:5600,draw,
    margin:marg,view:k=>V[k]});
})();
