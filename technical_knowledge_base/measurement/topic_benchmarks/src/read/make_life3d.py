"""Data for Fig. 1 (stage stg-life, parts/27_js_sc_life.js): the life of a benchmark, then every family.
Reads only this page's own data: the life points of the old Reading stepper (the same as read/recompute.py),
data/saturation.json (GPQA Diamond and HLE frontier points, Terminal-Bench version dates) and data/atlas.json
(every benchmark's launch year, status and owning child page). Writes parts/26_js_sc_life_data.js.
Run from src/: python3 read/make_life3d.py"""
import json, datetime as dt
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent
D = lambda s: dt.date.fromisoformat(s)
sat = json.loads((SRC / "data/saturation.json").read_text())
atl = json.loads((SRC / "data/atlas.json").read_text())
B = {b["id"]: b for b in sat["benchmarks"]}

# the life points (sources on the page, in the step list): MMLU then, Terminal-Bench-Science 0.1 now
then = [("2020-09-07", 43.9, "GPT-3 175B"), ("2022-03-29", 67.5, "Chinchilla"), ("2023-03-14", 86.4, "GPT-4"), ("2024-09-12", 92.3, "o1")]
now = [("2026-08-27", 30.0, "Claude Opus 5"), ("2026-09-01", 52.6, "Claude Fable 5.1"), ("2026-09-22", 64.6, "GPT-6 Astra")]


def rows(pts):
    t0 = D(pts[0][0]); out = []
    for d, s, m in pts:
        days = (D(d) - t0).days; gain = round(s - pts[0][1], 1)
        out.append(dict(date=d, days=days, score=s, model=m, headroom=round(100 - s, 1), gain=gain,
                        per30=round((s - pts[0][1]) / days * 30, 2) if days else None))
    return out


R = {"then": rows(then), "now": rows(now)}
pace = round(R["now"][2]["per30"] / R["then"][2]["per30"], 1)


def frontier(bid, series=None):
    """Best score so far over the listed series (every series if None); upper bounds never count;
    a model public before the launch is placed at the launch (the Saturation timeline's rule)."""
    b = B[bid]; L = D(b["launch"]["d"]); pts = []
    for s in b["series"]:
        if series and s["id"] not in series:
            continue
        for p in s["pts"]:
            if p.get("ub"):
                continue
            pts.append((max(L, D(p["d"])), p["v"], p["m"]))
    pts.sort(); best = -1; out = []
    for d, v, m in pts:
        if v > best:
            best = v
            if out and out[-1][0] == d.isoformat():
                out.pop()   # two models public at the launch: keep the better
            out.append([d.isoformat(), v, m])
    return {"name": b["name"], "launch": b["launch"]["d"], "pts": out}


gpqa = frontier("gpqa", ["gp1"])   # Epoch AI's runs
hle = frontier("hle", ["hl1"])     # external results compiled by Epoch AI
tb = [[B[i]["name"], B[i]["launch"]["d"], (B[i].get("retired") or {}).get("d")] for i in ("terminal_bench_2", "terminal_bench_3", "terminal_bench_4")]
tb_days = (D(tb[2][1]) - D(tb[0][1])).days

# the seven lanes: every atlas row with its owning child page (rows owned by this root only are left out)
LANES = [("kr", "Knowledge and reasoning"), ("math", "Math"), ("code", "Coding"), ("ag", "Agentic"),
         ("lcm", "Long context and multimodal"), ("pref", "Human preference"), ("safe", "Safety and honesty")]
ST = {"active": "a", "saturating": "s", "saturated": "r", "retired": "r"}
lanes = []
for k, nm in LANES:
    rs = sorted((r for r in atl["rows"] if r.get("own") == k), key=lambda r: (r["yr"], r["n"]))
    lanes.append({"k": k, "n": nm, "b": [[r["yr"], ST[r["st"]], r["n"]] for r in rs]})
left_out = [r["n"] for r in atl["rows"] if r.get("own") not in dict(LANES)]

out = {"as_of": sat["as_of"], "atlas_read": atl["read_date"], "R": R, "pace": pace, "gpqa": gpqa, "hle": hle, "tb": tb, "tb_days": tb_days,
       "lanes": lanes, "left_out": left_out,
       "counts": {l["k"]: {"n": len(l["b"]), "a": sum(1 for b in l["b"] if b[1] == "a"), "s": sum(1 for b in l["b"] if b[1] == "s"), "r": sum(1 for b in l["b"] if b[1] == "r")} for l in lanes}}
js = ("// ---- Fig. 1 data (generated by src/read/make_life3d.py from this page's data/saturation.json and data/atlas.json; do not edit) ----\n"
      "window.LIFE3D=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
      "// the life numbers the old stepper exposed, kept for read/check_read.mjs\nwindow.RD_LIFE={R:LIFE3D.R,pace:LIFE3D.pace};\n")
(SRC / "parts/26_js_sc_life_data.js").write_text(js)
print(json.dumps({k: out[k] for k in ("pace", "tb_days", "counts", "left_out")}, indent=1))
print("gpqa", gpqa["pts"][-1], len(gpqa["pts"]), "hle", hle["pts"][-1], len(hle["pts"]), "tb", tb)
