"""Write parts/11_js_data.js (window.KR): the real data behind every visual, from inputs/ and tables.py.
Run after recompute.py: python3 recompute.py && python3 mk_data.py"""
import json
from tables import REDUX_T2, REDUX_T2_SUBJECTS, HLEV_T2, HLEV_SPLIT, SQA_T3, MMLUPRO_T3, HLE_TOOLS, HLED

rx = json.load(open('inputs/redux_all.json'))
sizes = json.load(open('inputs/mmlu_test_sizes.json'))['test_n']
rc = json.load(open('inputs/recompute.json'))['values']
items = json.load(open('inputs/items.json'))
arc = json.load(open('inputs/arc_tasks.json'))
CODE = {'ok': 'o', 'wrong_groundtruth': 'w', 'bad_question_clarity': 'q', 'bad_options_clarity': 'p',
        'no_correct_answer': 'n', 'multiple_correct_answers': 'm', 'expert': 'e'}
CACHE = None  # per-item order comes from the cached rows if present (fetch_redux.py), else from redux_seq.json
import os, sys
cache = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('REDUX_CACHE', '')

subjects = []
for k in sorted(rx['subjects']):
    s = rx['subjects'][k]
    subjects.append({'k': k, 'n': s['n'], 't': sizes[k], 'c': {CODE[t]: v for t, v in s.items() if t in CODE and t != 'ok'}})

# per-item error codes, in dataset order, for the five Table 2 subjects (kept in inputs/redux_seq.json so the build
# does not need the raw cache)
SEQ_SUBJ = ['virology', 'logical_fallacies', 'college_chemistry', 'professional_law', 'human_sexuality']
seq_path = 'inputs/redux_seq.json'
if cache and os.path.isdir(cache):
    seq = {k: ''.join(CODE[r['error_type']] for r in json.load(open(os.path.join(cache, 'redux_%s.json' % k)))) for k in SEQ_SUBJ}
    picks = {}
    for k, i in [('virology', 88), ('virology', 96), ('elementary_mathematics', None), ('computer_security', None)]:
        rows = json.load(open(os.path.join(cache, 'redux_%s.json' % k)))
        if i is None:
            key = {'elementary_mathematics': 'Solve the equation −47 = g + 24.', 'computer_security': 'You are given a message (m) and its OTP'}[k]
            i = next(j for j, r in enumerate(rows) if r['question'].startswith(key))
        r = rows[i]
        picks['%s_%d' % (k, i)] = {'subject': k, 'row': i, 'q': r['question'], 'o': r['choices'], 'a': r['answer'],
                                  'type': r['error_type'], 'fix': r['correct_answer'], 'why': r['potential_reason'], 'source': r['source']}
    json.dump({'seq': seq, 'picks': picks}, open(seq_path, 'w'), indent=1, ensure_ascii=False)
sp = json.load(open(seq_path))

KR = {
    'redux': {'n': rx['n'], 'types': rx['types'], 'subjects': subjects, 'seq': sp['seq'], 'seqSubj': SEQ_SUBJ,
              't2subj': REDUX_T2_SUBJECTS, 't2': REDUX_T2, 'strat': rc['redux_strat_pct'], 'wrongPct': rc['redux_wrong_gt_pct']},
    'hlev': {'t2': HLEV_T2, 'split': HLEV_SPLIT},
    'picks': sp['picks'],
    'items': items,
    'arc': [{'v': t['v'], 'id': t['id'], 'url': t['url'], 'train': t['train'], 'test': t['test']} for t in arc],
    'arc3': rc['arc3_effort'],
    'tools': [{'m': m, 'a': a, 'b': b, 'set': s, 'who': w, 'k': k, 's': src} for m, a, b, s, w, k, src in HLE_TOOLS],
    'hled': HLED,
    'sqa': SQA_T3,
    'mmlupro': MMLUPRO_T3,
    'rc': {k: rc[k] for k in ['gpqa_ci95_at_90', 'gpqa_ci95_at_96', 'gpqa_gap95_at_90', 'sqa_guess_threshold_gpt4o', 'hlev_share_range',
                              'hlev_full_gain_range', 'hlev_sub_gain_range', 'redux_strat_pct', 'redux_wrong_gt_pct']},
}
js = '// generated by src/mk_data.py from src/inputs/ and src/tables.py; do not edit by hand\nwindow.KR=' + json.dumps(KR, ensure_ascii=False, separators=(',', ':')) + ';\n'
open('parts/11_js_data.js', 'w').write(js)
print('11_js_data.js', len(js), 'bytes')
