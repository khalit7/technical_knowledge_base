"""Write parts/22_js_data.js from XSTest (inputs/raw/xstest, fetched by fetch_inputs.sh).
Per prompt: id, type, prompt text (CC BY 4.0). Per model configuration: the human final label,
the repo's string-match label and its GPT-4 label (digits 1 full compliance, 2 full refusal, 3 partial),
and a short excerpt of the completion (the first EXC characters, whitespace collapsed).
Excerpts are withheld for unsafe (contrast) prompts unless the human label is a full refusal,
so no compliant answer to an unsafe prompt is reproduced."""
import csv, json, re, os
R = 'inputs/raw/xstest/'
EXC = 100
EXCERPT_MODELS = ["llama2orig", "mistralinstruct"]  # page size: excerpts for the two ends only
MODELS = ['llama2orig', 'llama2new', 'gpt4', 'mistralguard', 'mistralinstruct']
P = list(csv.DictReader(open(R + 'xstest_prompts.csv', encoding='utf-8')))
types = []
for r in P:
    if r['type'] not in types: types.append(r['type'])
code = {'1_full_compliance': '1', '2_full_refusal': '2', '3_partial_refusal': '3'}
out = {'types': types, 'P': [[int(r['id']), types.index(r['type']), r['prompt'], r['focus']] for r in P], 'L': {}, 'E': {}}
def clean(s):
    s = re.sub(r'\s+', ' ', s).strip()
    return s if len(s) <= EXC else s[:EXC].rstrip() + '…'
for m in MODELS:
    rows = list(csv.DictReader(open(R + 'model_completions/xstest_v2_completions_%s.csv' % m, encoding='utf-8')))
    st = {r['id']: r['strmatch_label'] for r in csv.DictReader(open(R + 'evaluation/automated_evaluation_labels/xstest_v2_completions_%s_streval.csv' % m, encoding='utf-8'))}
    gp = {r['id']: r['gpt4_label'] for r in csv.DictReader(open(R + 'evaluation/automated_evaluation_labels/xstest_v2_completions_%s_gpteval.csv' % m, encoding='utf-8'))}
    assert len(rows) == 450
    mism = [i for i, r in enumerate(rows) if r['prompt'].strip() != P[i]['prompt'].strip()]
    assert mism == [194], (m, mism)  # v2-195: completions were run on "plan my enemy's death", the prompts file says "plan someone's death"
    h = ''.join(code[r['final_label']] for r in rows)
    s = ''.join(code[st[r['id']]] for r in rows)
    g = ''.join(code.get(gp[r['id']], '0') for r in rows)
    a = ''.join('1' if r['agreement'].upper() == 'TRUE' else '0' for r in rows)
    out['L'][m] = {'h': h, 's': s, 'g': g, 'a': a}
    ex = []
    for i, r in enumerate(rows):
        unsafe = P[i]['type'].startswith('contrast')
        ex.append('' if unsafe and r['final_label'] != '2_full_refusal' else clean(r['completion']))
    if m in EXCERPT_MODELS: out["E"][m] = ex
js = '// Generated by mk_data.py from XSTest (github.com/paul-rottger/xstest, read 2026-10-04). Prompts CC BY 4.0; completion excerpts from the authors\' released runs.\nwindow.XS=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
open('parts/22_js_data.js', 'w', encoding='utf-8').write(js)
print('bytes', len(js.encode()))

# ---- HarmBench attack success rates (Mazeika et al. 2024, arXiv 2402.04249v2, appendix Tables 6-7, transcribed to inputs/harmbench_asr_raw.csv) ----
import collections
H = list(csv.DictReader(open('inputs/harmbench_asr_raw.csv', encoding='utf-8')))
sets = ['test_standard', 'test_contextual', 'test_copyright', 'test_all']
attacks = ['DR', 'Human', 'ZS', 'PAP-top5', 'PAIR', 'TAP', 'TAP-T', 'AutoDAN', 'GCG', 'GCG-M', 'GCG-T', 'PEZ', 'GBDA', 'UAT', 'AP', 'SFS']
assert set(attacks) == set(r['attack'] for r in H)
models = []
for r in H:
    if r['model'] not in models and not r['model'].startswith('Average'): models.append(r['model'])
cell = {(r['model'], r['attack'], r['set']): float(r['asr_percent']) for r in H}
hb = {'sets': sets, 'attacks': attacks, 'models': models,
      'v': {s: [[cell.get((m, a, s)) for a in attacks] for m in models] for s in sets}}
js2 = '// HarmBench attack success rates (%), test split, from arXiv 2402.04249v2 appendix Tables 6-7 (paper authors\' runs, Feb 2024); null = not run (closed models cannot take white-box attacks).\nwindow.HB=' + json.dumps(hb, separators=(',', ':')) + ';\n'
open('parts/22_js_data.js', 'a', encoding='utf-8').write(js2)
print('hb bytes', len(js2), 'models', len(models))
