"""Section 5 figure: share of each Inspect prompt (characters) taken by the identical 10-shot system message,
and whether the system messages are identical, from data/runs.json (full message texts). Writes parts/22_js_scale.js."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
r = json.load(open(os.path.join(H, "data", "runs.json")))
sys0 = [m["content"] for m in r["items"][0]["in"]["messages"] if m["role"] == "system"][0]
out = {"same_system": all([m["content"] for m in x["in"]["messages"] if m["role"] == "system"][0] == sys0 for x in r["items"]), "share": []}
for x in r["items"]:
    ms = x["in"]["messages"]
    s = sum(len(m["content"]) for m in ms if m["role"] == "system"); u = sum(len(m["content"]) for m in ms if m["role"] == "user")
    out["share"].append(round(s / (s + u), 4))
lm_first = [x["lm"]["context"][:60] for x in r["items"]]
out["lm_distinct_starts"] = len(set(lm_first))
open(os.path.join(H, "parts", "22_js_scale.js"), "w").write("/* generated by src/mk_scale.py; do not edit */\nwindow.HX_SCALE=" + json.dumps(out) + ";\n")
print(out)
