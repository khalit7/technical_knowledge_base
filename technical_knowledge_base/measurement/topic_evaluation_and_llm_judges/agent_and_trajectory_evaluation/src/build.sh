#!/bin/sh
R=$(git -C "$(dirname "$0")" rev-parse --show-toplevel 2>/dev/null) && [ -x "$R/.venv/bin/python3" ] && PATH="$R/.venv/bin:$PATH"; export LC_ALL=en_US.UTF-8   # pin repo Python (3.12) and locale (glob order): page hashes depend on both
# Assemble ../index.html from parts/.
# HTML: 01_head + 02_css (styles), 10_header (title and tab bar), 20_read_a..e (Reading tab; the path-matcher grid is inside it since 2026-10-24),
# 30_tab_grade (Three graders, 400 trials), 39_tab_more (Further reading).
# JS: every *.js in parts/ in file-name order, each in its own <script>, 99_js_tabs.js (the tab wiring) last.
# Data: parts/21_js_data.js is generated by mk_data.py from inputs/ (run mk_inputs.py, then mk_data.py, when those change).
# Links may be written {{text|url}} (url may be n:<notion id>, or #t-<tab> / #rd-<section> for a link inside the page).
cd "$(dirname "$0")"
{ cat parts/01_head.html parts/02_css.html parts/10_header.html parts/20_read_a.html parts/20_read_b.html parts/20_read_c.html parts/20_read_d.html parts/20_read_e.html parts/30_tab_grade.html parts/39_tab_more.html
  echo '<div id="jsErr" hidden style="margin:12px 0;padding:10px 12px;border:1px solid #c2703a;border-radius:8px;font:13px/1.5 ui-monospace,Menlo,monospace;white-space:pre-wrap"></div>'
  cat parts/05z_errbox.js.html
  for f in parts/*.js; do [ "$(basename $f)" = 99_js_tabs.js ] && continue; echo "<script>/* $(basename $f) */"; cat "$f"; echo '</script>'; done
  echo "<script>/* 99_js_tabs.js */"; cat parts/99_js_tabs.js; echo '</script>'
  echo '</div></body></html>'; } | perl -CSD -pe '
s/\{\{([^|{}]+)\|([^{}]+)\}\}/my($t,$u)=($1,$2);if($u=~m{^#(t-[\w-]+)$}){"<a href=\"#\" data-tab=\"$1\">$t<\/a>"}elsif($u=~m{^#(rd-[\w-]+)$}){"<a href=\"#$1\">$t<\/a>"}else{$u=~s{^n:}{https:\/\/app.notion.com\/p\/};"<a href=\"$u\" target=\"_blank\" rel=\"noopener noreferrer\">$t<\/a>"}/ge;
' > ../index.html
if grep -q '{{[^{}]*|[^{}]*}}' ../index.html; then echo "unexpanded link"; grep -o '{{[^{}]*|[^{}]*}}' ../index.html | head; fi
ED=$(printf '\342\200\224'); if grep -q "$ED" ../index.html; then echo "EM DASH FOUND"; fi
# Static estimate of reading time (script-drawn text excluded). The header states the rendered measure from html_utils/audit_pages.mjs (230 words a minute); update it by hand after a change.
python3 - <<'PY'
import re
s=open('../index.html').read()
a=s.index('id="t-read"');b=s.index('id="t-grade"')
r=re.sub(r'<script.*?</script>|<style.*?</style>|<svg.*?</svg>|<nav.*?</nav>|<button.*?</button>','',s[a:b],flags=re.S)
det=' '.join(re.findall(r'<details.*?</details>',r,flags=re.S));det=re.sub(r'<summary.*?</summary>','',det,flags=re.S)
core=re.sub(r'<details.*?</details>','',r,flags=re.S)+' '.join(re.findall(r'<summary.*?</summary>',r,flags=re.S))
wc=lambda x:len(re.sub(r'<[^>]+>',' ',x).split())
cw,dw=wc(core),wc(det)
s=s.replace('RT_MIN',str(round(cw/230))).replace('RT_DET',str(round(dw/230)))
open('../index.html','w').write(s)
print('reading words core',cw,'details',dw,'minutes',round(cw/230),round(dw/230))
PY
wc -c ../index.html
