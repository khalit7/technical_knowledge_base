# Writes parts/21_js_data.js (window.ATJ) from inputs/. Run after mk_inputs.py.
import json, os
H = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(H, 'inputs', 'tau2_airline_trials.json')))
C = json.load(open(os.path.join(H, 'inputs', 'tau2_cases.json')))
s = json.dumps({'meta': T['meta'], 'rows': T['rows'], 'cases': C}, ensure_ascii=False, separators=(',', ':'))
s = s.replace('</', '<\\/').replace(chr(0x2014), '-')
open(os.path.join(H, 'parts', '21_js_data.js'), 'w').write('// generated by mk_data.py from inputs/ (tau2-bench airline trials, MIT)\nwindow.ATJ=' + s + ';\n')
print(len(s))
