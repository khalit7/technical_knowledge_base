"""Check the page's port of v2's replay score (parts/14_js_simcore.js: SIM.front, SIM.Vhv) against the released code.

  python3 check_score.py --released <clone of google-research/dream-rsi>
      runs the released code (CPU, a few seconds) and stores its outputs in inputs/score_released.json
  python3 check_score.py
      (build.sh) recomputes everything with the page's JS and compares it with inputs/score_released.json;
      writes inputs/check_score.json, which the page reads, and fails on any difference above 1e-12

Three comparisons, all on the page's own default history (illustrative worlds, seeds 1 to 3, 10 x 11 cells):
  1. the score function alone: for every one of the 505 candidate policies, the page's replays at the five budget
     preferences are fed to the released _pareto_summary (eval.py) and to the page's port;
  2. end to end: the worlds are written as released raw_scores.json traces, ten candidates (the released
     parallel-refine incumbent and nine toy policies written as released OptimalPolicy files) are replayed by the
     released TraceEnv through the released eval.py CLI with --beta-sweep, and its beta_sweep.json is compared with
     the page's replays (calls, rounds and best per trace and budget preference) and scores;
  3. hand-computed cases for the frontier and the area (dominated points, ties, zero calls, the exhaustive point).
"""
import json, math, os, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / 'inputs' / 'score_released.json'
SEEDS = [1, 2, 3]
SUBSET = [0, 1, 50, 117, 200, 251, 333, 404, 480]  # indices into SIM.pool(); 0 is the fixed starting policy
HAND = [  # (points (calls, attainment), exhaustive budget, expected area by hand)
    ([(1, 0.5), (2, 1.0), (4, 1.0)], 4, (0.5 * 3 + 0.5 * 2) / 4),        # 0.625; the (4, 1.0) point is dominated
    ([(110, 1.0)] * 5, 110, 0.0),                                       # the exhaustive policy: no area at all
    ([(10, 0.6), (10, 0.9), (30, 0.8), (50, 1.0)], 110, (0.9 * 100 + 0.1 * 60) / 110),  # same budget keeps the higher; (30, 0.8) dominated
    ([(0, 0.0), (20, 0.5), (20, 0.5)], 100, 0.5 * 80 / 100),            # a zero-call replay adds nothing; ties count once
    ([(5, 0.2), (40, 0.95), (60, 0.95), (90, 1.0)], 100, (0.2 * 95 + 0.75 * 60 + 0.05 * 10) / 100),
]

JS = r'''
const SIM=require(process.argv[1]+'/parts/14_js_simcore.js');
const worlds=%s.map(s=>SIM.world(s));const pool=SIM.pool();const lam=0.05,W=10;
const out={worlds:worlds.map(w=>({seed:w.seed,s:w.s,best:w.best})),pool:pool.map(p=>({w:p.w,p:p.p===Infinity?null:p.p,k:p.k,refill:p.refill,blind:!!p.blind})),cands:[]};
pool.forEach((pol,i)=>{const per=worlds.map(wd=>{const s=SIM.Vhv(wd,pol,lam,W);return{V:s.V,hv:s.hv,pen:s.pen,pts:s.pts.map(p=>({rho:p.rho,N:p.N,k:p.k,best:p.best}))}});
  const m=worlds.length;out.cands.push({V:per.reduce((a,x)=>a+x.V,0)/m,hv:per.reduce((a,x)=>a+x.hv,0)/m,pen:per.reduce((a,x)=>a+x.pen,0)/m,per})});
const res=SIM.dream(worlds,{v:2,lam},W);out.dreamV=res.map(r=>r.V);const win=SIM.pick(res);out.win=res.indexOf(win);
out.hand=%s.map(([pts,B])=>SIM.front(pts.map(([N,a])=>({N,a})),B).hv);
console.log(JSON.stringify(out));
'''


def page_js():
    code = JS % (json.dumps(SEEDS), json.dumps([[list(map(list, p)), b] for p, b, _ in HAND]))
    r = subprocess.run(['node', '-e', code, str(HERE)], capture_output=True, text=True, check=True)
    return json.loads(r.stdout)


POLICY = '''# A toy policy of the Dream-RSI page, written against the released policy API (generated by check_score.py).
from dream_rsi.policy.api import LLMDesignedMethod, SimResult, finalize_result
P = %s
def sched(p, rho):  # parts/14_js_simcore.js SIM.sched, same arithmetic
    if p['blind']: return p
    return {'w': max(1, int((p['w'] * (0.4 + 0.6 * rho) + 0.5) // 1)),
            'p': None if p['p'] is None else max(1, int((p['p'] * (0.5 + 0.5 * rho) + 0.5) // 1)),
            'k': min(0.99, p['k'] + 0.1 * (1 - rho)) if p['k'] > 0 else 0, 'refill': p['refill']}
class OptimalPolicy(LLMDesignedMethod):
    NAME = "OptimalPolicy"
    def solve(self, q, budget=None):
        q.reset(); res = SimResult()
        pol = sched(P, float(self.config.get("beta", 1.0)))
        W = q.max_parallelism
        roots = q.legal_roots(); nb = len(roots)
        w = min(pol['w'], W, nb); pmax = float('inf') if pol['p'] is None else pol['p']
        opened, closed, nxt, bb, stale, nv = [], set(), {}, {}, {}, {}
        best, k = 0.0, 0
        while True:
            batch = []
            for b in opened:
                if b in closed: continue
                cand = [a for a in q.legal_actions() if q.meta(a).branch == b]
                if cand: batch.append(min(cand, key=lambda a: q.meta(a).attempt))
            want = w if k == 0 else (w if pol['refill'] else 0)
            a = len(batch); roots = q.legal_roots()
            while a < want and roots and len(batch) < W:
                r = roots.pop(0); opened.append(q.meta(r).branch); batch.append(r); a += 1
            if not batch: break
            for o in q.probe_batch(batch):
                b = o.branch; bb.setdefault(b, -1.0); stale.setdefault(b, 0); nv.setdefault(b, 0)
                if o.valid:
                    nv[b] += 1
                    if o.score > bb[b] + 1e-12: bb[b] = o.score; stale[b] = 0
                    else: stale[b] += 1
                    best = max(best, o.score)
                else: stale[b] += 1
            for cid in batch:
                b = q.meta(cid).branch
                if b in closed: continue
                if stale[b] >= pmax or (pol['k'] > 0 and nv[b] >= 2 and bb[b] < pol['k'] * best): closed.add(b)
            k += 1
        return finalize_result(q, res)
'''


def raw_trace(wd):
    nodes = []
    for b, row in enumerate(wd['s']):
        for j, v in enumerate(row):
            nid = 'b%d_a%d' % (b, j)
            ok = v is not None
            nodes.append({'id': nid, 'branch': b, 'attempt': j, 'parent_id': None if j == 0 else 'b%d_a%d' % (b, j - 1),
                          'intent': 'explore' if j == 0 else 'refine', 'tags': [], 'path': 'toy/' + nid,
                          'created_at': '2026-10-26T00:%02d:%02d+00:00' % (j, b), 'status': 'done',
                          'raw': {'evaluated': True, 'combined_score': v if ok else None, 'n_valid': 1 if ok else 0, 'n_total': 1,
                                  'sol_times_ms': [None], 'valids': [ok], 'max_gaps': [None], 'error': None if ok else 'failed attempt'}})
    return {'version': 1, 'workspace': 'toy-%d' % wd['seed'], 'exported_at': '2026-10-26T00:00:00+00:00', 'n_problems': 1,
            'baseline': {'evaluated': True, 'combined_score': 0.0, 'n_valid': 1, 'n_total': 1}, 'nodes': nodes}


def released(clone):
    clone = Path(clone).resolve()
    commit = subprocess.run(['git', '-C', str(clone), 'rev-parse', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()
    date = subprocess.run(['git', '-C', str(clone), 'log', '-1', '--format=%cs'], capture_output=True, text=True, check=True).stdout.strip()
    sys.path.insert(0, str(clone))
    for k in ('DRSI_REPLAY_PARALLELISM_PENALTY', 'DRSI_REPLAY_MAX_WORKERS', 'DRSI_REPLAY_BETA_GRID'): os.environ.pop(k, None)
    from dream_rsi.learning.heuristic_search import eval as E
    from dream_rsi.learning.heuristic_search.workflow import baseline_incumbent_source
    d = page_js()
    names = ['iter%03d' % i for i in range(len(d['worlds']))]
    # 1. the score function alone, on the page's replays
    part1 = []
    for c in d['cands']:
        grid = []
        for ri, rho in enumerate([0, 0.25, 0.5, 0.75, 1]):
            grid.append({'status': 'ok', 'beta': rho, 'per_trace': [
                {'name': names[i], 'run_best': d['worlds'][i]['best'], 'n_evaluated': 110, 'total_budget': per['pts'][ri]['N'],
                 'best': per['pts'][ri]['best'], 'effective_sequential_rounds': per['pts'][ri]['k']} for i, per in enumerate(c['per'])]})
        s = E._pareto_summary(grid)
        part1.append([s['reward'], s['auc'], s['parallel_penalty']])
    # 2. end to end through the released replay environment and eval.py
    part2 = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp); pool = tmp / 'trace_pool'
        for i, wd in enumerate(d['worlds']):
            (pool / names[i]).mkdir(parents=True)
            (pool / names[i] / 'raw_scores.json').write_text(json.dumps(raw_trace(wd)))
        runs = [('released parallel-refine incumbent', baseline_incumbent_source(), 0)] + [('toy candidate %d' % i, POLICY % repr(d['pool'][i]), i) for i in SUBSET[1:]] + [('toy candidate %d (the v2 winner)' % d['win'], POLICY % repr(d['pool'][d['win']]), d['win'])]
        for name, src, idx in runs:
            mf = tmp / ('m%d.py' % idx); mf.write_text(src); rd = tmp / ('r%d' % idx)
            r = subprocess.run([sys.executable, str(clone / 'dream_rsi/learning/heuristic_search/eval.py'), str(mf), '--trace-pool', str(pool), '--result-dir', str(rd), '--beta-sweep'], capture_output=True, text=True, cwd=str(tmp))
            sw = json.loads((rd / 'beta_sweep.json').read_text())
            pts = [[[g['beta'], t['total_budget'], t['effective_sequential_rounds'], t['best']] for t in g['per_trace']] for g in sw['grid']]
            part2.append({'name': name, 'index': idx, 'rc': r.returncode, 'reward': sw['pareto']['reward'], 'auc': sw['pareto']['auc'],
                          'parallel_penalty': sw['pareto']['parallel_penalty'], 'weight': sw['pareto']['parallelism_weight'], 'points': pts})
    hand = [E._trace_auc([(n, a, 0.0) for n, a in pts], float(b))[0] for pts, b, _ in HAND]
    out = {'released': 'google-research/dream-rsi', 'commit': commit, 'commit_date': date, 'file': 'dream_rsi/learning/heuristic_search/eval.py',
           'defaults': {'lambda': E.DEFAULT_PARALLELISM_PENALTY, 'W': E.DEFAULT_REPLAY_MAX_WORKERS, 'beta_grid': E._parse_beta_grid()},
           'seeds': SEEDS, 'part1': part1, 'part2': part2, 'hand': hand}
    OUT.write_text(json.dumps(out, indent=1) + '\n')
    print('stored released outputs from', commit[:12], 'in', OUT.name)


def check():
    R = json.loads(OUT.read_text()); d = page_js()
    assert R['seeds'] == SEEDS and len(R['part1']) == len(d['cands'])
    m1 = max(max(abs(a - b) for a, b in zip(R['part1'][i], (c['V'], c['hv'], c['pen']))) for i, c in enumerate(d['cands']))
    m1d = max(abs(R['part1'][i][0] - v) for i, v in enumerate(d['dreamV']))
    m2, pts_bad = 0.0, 0
    for r in R['part2']:
        c = d['cands'][r['index']]
        m2 = max(m2, abs(r['reward'] - c['V']), abs(r['auc'] - c['hv']), abs(r['parallel_penalty'] - c['pen']))
        for ri, g in enumerate(r['points']):
            for ti, (beta, N, k, best) in enumerate(g):
                p = c['per'][ti]['pts'][ri]
                if (N, k) != (p['N'], p['k']) or abs(best - p['best']) > 1e-12 or abs(beta - p['rho']) > 1e-12: pts_bad += 1
    exp = [e for _, _, e in HAND]
    mh = max(max(abs(a - b) for a, b in zip(R['hand'], exp)), max(abs(a - b) for a, b in zip(d['hand'], exp)))
    inc = R['part2'][0]
    out = {'commit': R['commit'], 'commit_date': R['commit_date'], 'defaults': R['defaults'],
           'n_candidates': len(d['cands']), 'max_diff_score_fn': m1, 'max_diff_dream': m1d, 'n_end_to_end': len(R['part2']),
           'max_diff_end_to_end': m2, 'replay_point_mismatches': pts_bad, 'n_points_end_to_end': sum(len(g) for r in R['part2'] for g in r['points']),
           'n_hand': len(HAND), 'max_diff_hand': mh, 'incumbent': {'reward': inc['reward'], 'auc': inc['auc'], 'penalty': inc['parallel_penalty']},
           'winner': d['win'], 'winner_V': d['cands'][d['win']]['V']}
    ok = m1 < 1e-12 and m1d < 1e-12 and m2 < 1e-12 and pts_bad == 0 and mh < 1e-12 and all(r['rc'] == 0 for r in R['part2'])
    out['pass'] = ok
    (HERE / 'inputs' / 'check_score.json').write_text(json.dumps(out, indent=1) + '\n')
    print(out)
    assert ok, 'the page port and the released score differ'
    print('PASS')


if __name__ == '__main__':
    if len(sys.argv) > 2 and sys.argv[1] == '--released':
        released(sys.argv[2])
    check()
