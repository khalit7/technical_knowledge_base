"""Turn the toy sweep (model/*.json, written by train.py) into the page's data and fits.

  python3 mk_results.py        (build.sh runs it; plain Python, no numpy)

Writes parts/_gen_runs.js (window.RUNS: every run's checkpoints, plus the frontier analysis) and
inputs/results.json (the numbers quoted in the page and README).

Analyses:
  L(N): pure power law in log-log space on the final losses of the full-length (K) runs (the page refits it live).
  Overtaking: at the compute where each size's full run ends, is the next bigger size already better? Its loss
  there is read from its long run's checkpoint (the paper's way) and from its matched runs (Chinchilla's way).
  If the bigger size never wins inside the sweep, the compute-optimal size cannot be located and no allocation
  exponent is fitted.
"""
import glob, json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
runs = {}
for f in sorted(glob.glob(os.path.join(HERE, 'model', '*.json'))):
    r = json.load(open(f))
    if 'log' in r: runs[r['name']] = r
V, CTX = 96, 64

def linfit(xs, ys):
    n = len(xs); mx = sum(xs) / n; my = sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs); sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    b = sxy / sxx; return b, my - b * mx

def interp(pts, x):
    """pts sorted by x (log space): linear interpolation, None outside."""
    if x < pts[0][0] - 1e-12 or x > pts[-1][0] + 1e-12: return None
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        if x0 <= x <= x1: return y0 + (y1 - y0) * (x - x0) / (x1 - x0) if x1 > x0 else y0
    return pts[-1][1]

K = sorted([r for n, r in runs.items() if n.startswith('K_')], key=lambda r: r['N_eq21'])

def overtake():
    """At the compute where each size's full run ends (C = 6 N FULL), is the next bigger size already better?
    The bigger size's loss at that compute is read two ways: from its long run's checkpoint (the paper's way)
    and from its matched runs (K, M4, M16 ends, linear in log tokens between them)."""
    out = []
    for r0, r1 in zip(K, K[1:]):
        C = 6 * r0['N_eq21'] * r0['budget']; T1 = C / (6 * r1['N_eq21'])
        ck = math.exp(interp([(math.log(c['tokens']), math.log(c['test'])) for c in r1['log']], math.log(T1)))
        ends = sorted((math.log(x['budget']), math.log(x['log'][-1]['test'])) for x in runs.values()
                      if (x['nl'], x['d']) == (r1['nl'], r1['d']) and x.get('seed', 1) == 1 and 'lrx' not in x)
        m = interp(ends, math.log(T1)) if len(ends) >= 2 else None
        out.append(dict(small=r0['name'], big=r1['name'], N0=r0['N_eq21'], N1=r1['N_eq21'], C=C, tpp0=r0['budget'] / r0['N_eq21'],
                        L0=r0['log'][-1]['test'], L1ck=ck, L1m=math.exp(m) if m is not None else None))
    return out

R = dict(overtake=overtake())
# L(N) fit on final K losses (pure power law, like Eq. 1.1)
xs = [math.log(r['N_eq21']) for r in K]; ys = [math.log(r['log'][-1]['test']) for r in K]
b, a = linfit(xs, ys)
R['LN_pure_all'] = dict(alpha=-b, Nc=math.exp(-a / b) if b else None)
# seed noise: |test(seed 2) - test(seed 1)| at the end
R['seed'] = []
for n, r in runs.items():
    if n.startswith('S2_'):
        k = runs.get('K_%d_%d' % (r['nl'], r['d']))
        if k: R['seed'].append(dict(nl=r['nl'], d=r['d'], N=r['N_eq21'], s1=k['log'][-1]['test'], s2=r['log'][-1]['test'], diff=r['log'][-1]['test'] - k['log'][-1]['test']))
R['cpu_seconds'] = round(sum(r['seconds'] for r in runs.values()), 1)
R['nruns'] = len(runs)
json.dump(R, open(os.path.join(HERE, 'inputs', 'results.json'), 'w'), indent=1)

# compact data for the page
J = dict(runs=[dict(n=r['name'], nl=r['nl'], d=r['d'], N=r['N_eq21'], Nx=r['N_nonemb'], head=r['N_head'], emb=r['N_emb'], tot=r['N_total'],
                    budget=r['budget'], seed=r.get('seed', 1), lr=round(r['lr'], 6), warm=r['warmup'], steps=r['steps'], sec=r['seconds'],
                    t=[c['tokens'] for c in r['log']], L=[c['test'] for c in r['log']], Ltr=[c['train'] for c in r['log']]) for r in sorted(runs.values(), key=lambda r: (r['name'][0], r['N_eq21'], r['budget']))],
         ov=R['overtake'],
         seed=R['seed'], cpu=R['cpu_seconds'], V=V, CTX=CTX)
open(os.path.join(HERE, 'parts', '_gen_runs.js'), 'w').write('// Generated by mk_results.py from model/*.json (the toy sweep of train.py).\nwindow.RUNS=' + json.dumps(J, separators=(',', ':')) + ';\n')
for o in R['overtake']: print('%-8s %-8s tpp %.0f  L0 %.3f  L1ck %.3f  L1m %s' % (o['small'], o['big'], o['tpp0'], o['L0'], o['L1ck'], o['L1m'] and '%.3f' % o['L1m']))
print('L(N) pure', R['LN_pure_all'], 'seed', R['seed'], 'cpu s', R['cpu_seconds'], 'runs', R['nruns'])
