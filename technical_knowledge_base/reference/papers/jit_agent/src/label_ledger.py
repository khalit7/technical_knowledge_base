"""Labels src/ledger.json (drafted by html_utils/ledger.py init on 2026-10-25 from the page as committed before the light pass;
adapted from the Qwen3 labeller). For every unit not overridden below, the key is the first run of 8 (then 6, then 4) consecutive
words of its text that appears verbatim in the rebuilt page, and the label is depth when that key sits inside a closed <details>
block, core otherwise. Rerun after a rebuild; it prints any unit it cannot place."""
import json, re, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[4] / 'html_utils'))
import ledger  # visible() and norm(), so keys match what ledger.py check reads
PAGE = 'reference/papers/jit_agent'
H = 'agents_and_retrieval/topic_agentic_harnesses'
FAT = {1: 'old reading-time line, replaced by the measured subtitle', 39: 'old autoplay note, replaced by "never plays by itself"', 156: 'a bare link label; the noise table is linked from the margins block'}
VOLATILE = {}
OWNED = {}
KEYS = {}
NEW = [
 ('core', '', 'Core sentence: train a 27B model to write a four-module harness per task just in time; about +8 on the nine-benchmark average for two backbones; 14.9 to 54.1% cheaper than fixed harnesses on three benchmarks.', 'the idea in one sentence: instead of tuning one agent harness'),
 ('core', '', "Hero: the paper's Figure 1 (CC BY 4.0), different tasks get different harnesses from one trained writer.", 'different tasks get different harnesses from one trained writer'),
 ('core', '', 'Hero results: Table 2 averages and Table 3 cost per case against the cheapest fixed harness in six settings (generated by mk_hero.py; the caption carries the key).', 'cost bars share one scale ($0 to $0.20 per case)'),
 ('core', '', 'New terms: AOT against JIT, (M, P, A, F) under protocol, seed bank, incumbent, Evo-GDPO.', 'the bar a new candidate must beat'),
 ('core', '', "The paper's Figure C.3 (Turnstile) beside the illustrative animation: final_answer locked in F until is_complete().", 'the gate is in f, not in the prompt'),
 ('owned:' + H, '', 'What a harness is and its parts are taught on Topic: agentic-harnesses; the Problem keeps the paper\'s own list and links it.', 'harness is everything except the model'),
 ('owned:models_and_training/topic_rl/rl_for_llms', '', "GRPO's group-relative advantage is taught on RL for LLMs; Stage III keeps GDPO's change (separate normalisation per channel) and links it.", 'group relative policy optimization is ppo minus the value model'),
 ('owned:models_and_training/topic_llm_training_and_post_training/alignment_sft_rlhf_dpo_rlvr', '', 'DPO itself is taught on the Alignment page; Stage I keeps the weighted pair rule and links it.', 'dpo family directly on pairs'),
 ('owned:measurement/topic_evaluation_and_llm_judges/eval_statistics', '', 'Binomial standard errors and paired comparisons in general are on Eval statistics; this page keeps its own z values and links it.', 'p(1 − p)/n), or s/√n for any score'),
 ('volatile', '', 'As of 25 October 2026 the repository is still at ababa06 (27 August) and arXiv still at v2: dated closed block "Later, as of 25 October 2026".', 'the repository\'s last commit is still ababa06'),
]
F = HERE / 'ledger.json'
u = json.loads(F.read_text())
raw = (HERE.parent / 'index.html').read_text()
vis = ledger.norm(ledger.visible(PAGE))
body = re.sub(r'<script.*?</script>|<style.*?</style>', ' ', raw, flags=re.S)
det = ' '.join(ledger.norm(d) for d in re.findall(r'<details.*?</details>', body, flags=re.S))
def find_key(text):
    w = ledger.norm(text).split(' ')
    for n in (8, 6, 4):
        for i in range(0, max(1, len(w) - n + 1)):
            k = ' '.join(w[i:i + n])
            if len(k) >= 18 and k in vis and not re.fullmatch(r'[\W\d ]+', k):
                return k
    return ''
bad = 0
for x in u:
    if x.get('added'):
        continue
    x.pop('note', None)
    if x['id'] in FAT:
        x['label'], x['key'], x['note'] = 'fat', '', FAT[x['id']]; continue
    if x['id'] in VOLATILE:
        x['label'], x['key'] = 'volatile', VOLATILE[x['id']]; x['note'] = 'dated closed block'; continue
    if x['id'] in OWNED:
        o, k = OWNED[x['id']]; x['label'], x['key'] = 'owned:' + o, k; continue
    k = KEYS.get(x['id']) or find_key(x['text'])
    if not k:
        print('UNPLACED', x['id'], x['tab'], x['text'][:110]); bad += 1; x['label'], x['key'] = '', ''; continue
    x['key'] = k; x['label'] = 'depth' if k in det else 'core'
have = {x['text'] for x in u if x.get('added')}
n = max(x['id'] for x in u)
for lab, where, text, key in NEW:
    if text in have:
        continue
    n += 1; u.append({'id': n, 'tab': 't-read', 'section': 'light pass 2026-10-25', 'text': text, 'label': lab, 'key': key, 'where': where, 'added': True})
F.write_text(json.dumps(u, indent=1, ensure_ascii=False) + '\n')
c = {}
for x in u: c[x['label'].split(':')[0]] = c.get(x['label'].split(':')[0], 0) + 1
print('units', len(u), c, 'unplaced', bad)
