"""Collect the toy model's measured results into parts/_gen_results.js (window.RES) for the page.
Reads model/finetune.json, model/report.json, model/check_forward.json, model/overlap.json and the logs in
model/{bert,nonsp,ltr}.pt (via the small JSON copy model/logs.json written by train.py export).
  python3 mk_results.py   (build.sh runs it)"""
import json, os, statistics as st
HERE = os.path.dirname(os.path.abspath(__file__)); M = os.path.join(HERE, 'model')
F = json.load(open(os.path.join(M, 'finetune.json'))); REP = json.load(open(os.path.join(M, 'report.json')))
CK = json.load(open(os.path.join(M, 'check_forward.json'))); OV = json.load(open(os.path.join(M, 'overlap.json')))
LG = json.load(open(os.path.join(M, 'logs.json')))
out = {'sizes': F['sizes'], 'cfg': LG['cfg']}
for task in ('tok', 'sent'):
    mean, sd = {}, {}
    for r in F['runs']:
        if r['task'] != task: continue
        mean.setdefault(r['variant'], {}).setdefault(r['n'], []).append(r['test'])
    for v, by in mean.items():
        for n, runs in by.items():
            keys = runs[0].keys()
            sd.setdefault(v, {})[n] = {k: round(st.pstdev([x[k] for x in runs]), 4) for k in keys}
            by[n] = {k: round(st.mean([x[k] for x in runs]), 4) for k in keys}
    out[task] = {'mean': mean, 'sd': sd}
steps = sorted({r['step'] for r in F['fig5']})
out['fig5'] = {'steps': steps, **{v: [next(r['test']['all'] for r in F['fig5'] if r['variant'] == v and r['step'] == s) for s in steps] for v in ('bert', 'ltr')}}
out['pre'] = {'bert': REP['bert']['float'], 'bert_q': REP['bert']['quantised'], 'ltr': REP['ltr']['float'], 'ltr_q': REP['ltr']['quantised'], 'nonsp': LG['nonsp_eval']}
out['logs'] = {k: LG[k] for k in ('bert', 'nonsp', 'ltr')}
out['tagq'] = {k: {'float': REP[k]['float']['all'], 'q': REP[k]['quantised']['all']} for k in ('bert_tag', 'ltr_tag')}
models = ('bert', 'ltr', 'bert_tag', 'ltr_tag')
out['check'] = {'agree': ', '.join(CK[m]['same_argmax_everywhere'] for m in models), 'logit': max(CK[m]['max_abs_logit_diff'] for m in models),
                'att': max(CK[m]['max_abs_attention_diff'] for m in models), 'nsp': CK['bert']['max_abs_nsp_prob_diff'], 'grammar': CK['grammar_truth_match']}
out['overlap'] = OV
out['seconds'] = {'finetune': F['seconds'], **LG['seconds']}
S2 = os.path.join(M, 'seed2.json')
if os.path.exists(S2):  # the NSP ablation repeated with pretraining seed 8 (train.py seed2)
    J = json.load(open(S2)); s2 = {}
    for r in J['runs']:
        s2.setdefault(r['task'], {}).setdefault(r['variant'][:-3], {}).setdefault(r['n'], []).append(r['test']['all'])
    out['seed2'] = {t: {v: {n: round(st.mean(x), 4) for n, x in by.items()} for v, by in d.items()} for t, d in s2.items()}
    out['seed2_eval'] = {v: J[v + '_eval'] for v in ('bert_s2', 'nonsp_s2')}
open(os.path.join(HERE, 'parts', '_gen_results.js'), 'w').write('// Generated by mk_results.py from model/*.json.\nwindow.RES=' + json.dumps(out, separators=(',', ':')) + ';\n')
print('mk_results: written')
