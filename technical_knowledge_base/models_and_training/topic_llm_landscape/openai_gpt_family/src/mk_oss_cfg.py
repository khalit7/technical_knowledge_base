# Write parts/42a_js_oss_cfg.js from the two published configuration files in inputs/ (gpt-oss-120b and gpt-oss-20b, Hugging Face config.json):
# the fields the gpt-oss stage (Fig. 6) and the one-card stage (Fig. 7) draw. Run: python3 mk_oss_cfg.py (in src/).
import json
out={}
for m in ('120b','20b'):
    c=json.load(open(f'inputs/cfg_gpt-oss-{m}.json'))
    out[m]=dict(L=c['num_hidden_layers'],E=c['num_local_experts'],k=c['num_experts_per_tok'],d=c['hidden_size'],ff=c['intermediate_size'],
                H=c['num_attention_heads'],KV=c['num_key_value_heads'],hd=c['head_dim'],win=c['sliding_window'],ctx=c['max_position_embeddings'],
                types=''.join('F' if t=='full_attention' else 'S' for t in c['layer_types']))
js='// Generated by src/mk_oss_cfg.py from inputs/cfg_gpt-oss-120b.json and cfg_gpt-oss-20b.json (types: S sliding_attention, F full_attention, in layer order).\nwindow.OSSCFG='+json.dumps(out,separators=(',',':'))+';\n'
open('parts/42a_js_oss_cfg.js','w').write(js);print(js)
