#!/usr/bin/env python3
"""Write parts/26z_js_lfx_data.js (window.LFX) for the loss-family push animation (moved from the DPO paper page, 2026-10-26).

The toy outcomes shown in the animation's counters are the DPO paper page's long runs (4,000 steps on its
enumerable toy, deterministic labels): read here from reference/papers/dpo/src/parts/_gen_toy.js, which that page's
engine writes and checks (check_engine.mjs, check_engine.py). Rerun this after the DPO page regenerates its toy.
Run from src/: python3 mk_lfx_data.py
"""
import json, os, re
H = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(H, "..", "..", "..", "..", "reference", "papers", "dpo", "src", "parts", "_gen_toy.js")
T = json.loads(re.search(r"window\.TOYRES=(\{.*?\});\n", open(SRC, encoding="utf-8").read(), re.S).group(1))
RUNS = ["Unlikelihood α = 1", "DPO β = 0.1", "Hinge (SLiC) β = 0.5", "IPO τ = 0.1", "cDPO β = 0.1, ε = 0.1", "SimPO β = 2, γ = 1"]
out = {}
for r in T["long"]:
    if r["name"] not in RUNS: continue
    z = r["trace"][-1]; at = {t["s"]: t for t in r["trace"]}
    out[r["name"]] = {"steps": z["s"], "kl": z["kl"], "r": z["r"], "g": z["g"], "u": z["u"], "top": r["top"][0]["t"], "kl1200": at[1200]["kl"]}
assert set(out) == set(RUNS), set(RUNS) - set(out)
with open(os.path.join(H, "parts", "26z_js_lfx_data.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by src/mk_lfx_data.py from the DPO paper page's toy long runs (reference/papers/dpo/src/parts/_gen_toy.js). Do not edit.\n")
    f.write("window.LFX=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
for k, v in out.items(): print(k, v)
