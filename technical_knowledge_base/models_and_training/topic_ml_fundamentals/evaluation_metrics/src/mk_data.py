# Pack the small inputs into parts/30_js_data.js (window.EM), the page's only data.
# Run from src/: python3 mk_data.py
import json, random
s = json.load(open('inputs/sst2_scores.json'))
g = json.load(open('inputs/glass_cm.json'))
pp = json.load(open('inputs/ppl_tokens.json'))
tx = json.load(open('inputs/text_presets.json'))

def cut(t, n=90):
    return t if len(t) <= n else t[:n - 1].rstrip() + '…'
import math
def lg(p):  # log-odds x 1000 (probabilities as small as 1e-15 kept), so ranks and extreme values survive
    p = min(max(p, 1e-15), 1 - 1e-15)
    return int(round(1000 * math.log(p / (1 - p))))
rng = random.Random(0)
perm = list(range(len(s['y']))); rng.shuffle(perm)
EM = {
  'sst2': {'y': ''.join(str(v) for v in s['y']), 'logit': {k: [lg(v) for v in s['p'][k]] for k in ['lr', 'nb', 'nbc']},
           'text': [cut(t) for t in s['text']], 'perm': perm},
  'glass': {'classes': g['classes'], 'cm': g['cm']},
  'ppl': {'texts': pp['texts'], 'models': {k: {'repo': m['repo'], 'vocab': m['vocab'], 'params': m['params'], 'start': m['start_token'],
          'scores': {t: {'tokens': v['tokens'], 'nb': v['nb'], 'lp': v['lp']} for t, v in m['scores'].items()}} for k, m in pp['models'].items()}},
  'text': {'ref': tx['ref'], 'cands': [{'key': c['key'], 'label': c['label'], 'text': c['text'],
            'lib': {'bleu': round(c['bleu'], 2), 'chrf': round(c['chrf'], 2), 'r1': round(c['rouge']['rouge1']['f'], 4), 'r2': round(c['rouge']['rouge2']['f'], 4),
                    'rl': round(c['rouge']['rougeL']['f'], 4), 'met': round(c['meteor_stem'], 4), 'metwn': round(c['meteor_wordnet'], 4)},
            'bs': {'P': round(c['bertscore']['P'], 4), 'R': round(c['bertscore']['R'], 4), 'F': round(c['bertscore']['F'], 4),
                   'Fr': round(c['bertscore']['F_rescaled'], 4), 'tokens': c['bertscore']['tokens'], 'sim': c['bertscore']['sim']}} for c in tx['cands']],
           'ref_tokens': tx['bertscore']['ref_tokens'], 'baseline': tx['bertscore']['baseline']},
}
js = '// ---- Data (generated by src/mk_data.py from src/inputs/; do not edit) ----\nwindow.EM=' + json.dumps(EM, ensure_ascii=False, separators=(',', ':')) + ';\n'
open('parts/30_js_data.js', 'w').write(js)
print('parts/30_js_data.js', len(js.encode()), 'bytes')
