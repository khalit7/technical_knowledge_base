"""Write parts/45_js_ns_0data.js from inputs/root_gradient_sv.json and print the numbers the Muon stepper's
static captions quote. Newton-Schulz acts on each singular value separately: X <- aX + b(XX^T)X + c(XX^T)^2 X
maps sigma to a*sigma + b*sigma^3 + c*sigma^5 (Jordan's coefficients), so five scalar iterations are exact.
Also prints the decoupled-decay figure's ratios and the critical-batch curve's anchor (McCandlish et al. eq. 2.11)."""
import json, math
from pathlib import Path
H = Path(__file__).resolve().parent
sv = json.loads((H / "inputs/root_gradient_sv.json").read_text())["singular_values"]
a, b, c = 3.4445, -4.7750, 2.0315
its = [sv]
for _ in range(5):
    its.append([a * s + b * s ** 3 + c * s ** 5 for s in its[-1]])
for k, x in enumerate(its):
    print(f"iteration {k}: min {min(x):.2f}  max {max(x):.2f}  ratio {max(x) / min(x):.2f}")
(H / "parts/45_js_ns_0data.js").write_text(
    "// generated by ns_data.py from inputs/root_gradient_sv.json: 32 singular values of one real gradient (root toy, 64 x 176), Frobenius norm 1\n"
    "window.NS_SV=" + json.dumps([round(v, 6) for v in sv]) + ";\n")
# decoupled decay: per-step shrink of a weight theta = 1 under L2-in-Adam against AdamW, steady state, eta 1e-3, lambda 0.1
eta, lam = 1e-3, 0.1
for s in [0.001, 0.01, 0.1, 1, 10]:
    l2 = eta * lam / math.sqrt(s * s + lam * lam)
    print(f"gradient RMS {s}: L2-in-Adam shrink {l2:.3g}, AdamW {eta * lam:.3g}, ratio {l2 / (eta * lam):.3g}")
# critical batch: S = Smin (1 + Bcrit/B), E = Emin (1 + B/Bcrit)
for r in [0.125, 1, 8]:
    print(f"B/Bcrit {r}: steps x{1 + 1 / r:.3g}, examples x{1 + r:.3g}")
