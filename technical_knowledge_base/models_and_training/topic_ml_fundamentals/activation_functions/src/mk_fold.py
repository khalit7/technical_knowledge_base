"""Data for Fig. 1 (why a nonlinearity): XOR-shaped points, the best linear model, and a two-unit ReLU layer that separates them.

Four clusters of 15 points around the corners of the unit square (Gaussian, sd 0.12, numpy seed 0): class A at (0, 0) and (1, 1),
class B at (0, 1) and (1, 0). Three models, each scored by thresholding its output at 0.5 (B above):
- the least-squares linear model y = a x1 + b x2 + c (the best any stack of linear layers can do, since a stack of linear maps is one);
- the ReLU layer with weights set by hand: h1 = ReLU(x1 + x2), h2 = ReLU(x1 + x2 - 1), y = h1 - 2 h2 (one crease each);
- the same weights with no activation: y = (x1 + x2) - 2 (x1 + x2 - 1) = 2 - x1 - x2, a plane.
Writes inputs/fold.json and parts/20_js_fold.js. Run: python3 src/mk_fold.py (well under a second).
"""
import json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
rng = np.random.default_rng(0)
C = [((0, 0), 0), ((1, 1), 0), ((0, 1), 1), ((1, 0), 1)]
P = []
for (cx, cy), lab in C:
    for _ in range(15):
        x1, x2 = rng.normal(cx, 0.12), rng.normal(cy, 0.12)
        P.append((round(float(x1), 3), round(float(x2), 3), lab))
X = np.array([[p[0], p[1]] for p in P]); y = np.array([p[2] for p in P], float)
A = np.c_[X, np.ones(len(X))]
coef, *_ = np.linalg.lstsq(A, y, rcond=None)
lin = A @ coef
relu = lambda v: np.maximum(v, 0)
s = X.sum(1)
h1, h2 = relu(s), relu(s - 1)
fold = h1 - 2 * h2
nolin = s - 2 * (s - 1)
acc = lambda out: float(((out > 0.5) == (y > 0.5)).mean())
res = dict(points=P, lin=[round(float(c), 10) for c in coef], acc_lin=acc(lin), acc_fold=acc(fold), acc_nolin=acc(nolin),
           lin_range=[round(float(lin.min()), 3), round(float(lin.max()), 3)],
           fold_A_max=round(float(fold[y == 0].max()), 3), fold_B_min=round(float(fold[y == 1].min()), 3), n=len(P))
json.dump(res, open(os.path.join(HERE, "inputs", "fold.json"), "w"), indent=1)
open(os.path.join(HERE, "parts", "20_js_fold.js"), "w").write("// generated by src/mk_fold.py\nwindow.FOLD=" + json.dumps(res, separators=(",", ":")) + ";\n")
print({k: v for k, v in res.items() if k != "points"})
