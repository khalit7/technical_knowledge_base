"""Answer checkers on the Tulu 3 RLVR set: do different ways of extracting and comparing an answer agree?

Two kinds of response are checked against each row's ground_truth:
  ref    the reference solution of the same problem (GSM8K train "...#### 72"; MATH train "...\\boxed{...}"), joined to
         the RLVR row by question text. A correct checker should accept every one of them.
  model  answers generated by a local Qwen3 model (pt_generate.py): the case RL training actually sees.

Extractors (math rows; each returns the extracted answer and whether it matches ground_truth):
  last_number  Tulu 3's GSM8K verifier: the last number in the response, string-equal to the label
               (open-instruct ground_truth_utils.py:216-220 @ 72f46040)
  tulu_math    Tulu 3's MATH verifier: \\boxed{}, then Minerva "Final Answer: The final answer is X", then the last
               $...$; equal if sympy says the difference simplifies to 0 or the Hendrycks string normalisation matches
               (ground_truth_utils.py:243-278, math_utils.py)
  minerva      the strict variant: only the Minerva sentence (ground_truth_utils.py:297-307)
  boxed_exact  naive: the content of the last \\boxed{} equals the label as a string
  answer_is    the "The answer is X" sentence the GSM8K few-shot examples use, numbers compared after removing commas
  math_verify  Hugging Face math-verify 0.8.0: parse(gold) and parse(response), verify()
IF rows: Tulu 3's checker (if_functions.py via IFEvalVerifierOld, ground_truth_utils.py:376-391) in strict mode, and
a loose mode in the manner of Google's IFEval (also accept the response with its first line, its last line or both
removed, or with markdown asterisks removed).

usage: DC_SCRATCH=... PYTHONPATH=$DC_SCRATCH/post/pylib:$DC_SCRATCH/src/open-instruct python -I -B pt_checkers.py
       [model_jsonl ...]     (needs PYTHONPATH, so run without -I: see run_checkers.sh)
"""
import gzip
import json
import os
import re
import sys
from collections import Counter
from multiprocessing import get_context

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pt_common as P  # noqa: E402

MATH_EX = ["last_number", "tulu_math", "minerva", "boxed_exact", "answer_is", "math_verify"]
DL = {"gsm8k": "openai/gsm8k main/train-00000-of-00001.parquet @ 740312ad",
      "MATH": "DigitalLearningGmbH/MATH-lighteval data/train-00000-of-00001.parquet @ 0530c786"}


def _ws(t):
    return re.sub(r"\s+", " ", t or "").strip()


def references():
    """{rlvr row index: reference solution} for GSM8K and MATH rows, joined on whitespace-normalised question."""
    import pandas as pd
    hf = os.path.join(P.L.scratch(), "hf", "hub")
    g = pd.read_parquet(_find(hf, "datasets--openai--gsm8k", "train-00000-of-00001.parquet"))
    m = pd.read_parquet(_find(hf, "datasets--DigitalLearningGmbH--MATH-lighteval", "train-00000-of-00001.parquet"))
    gq = {_ws(q): a for q, a in zip(g.question, g.answer)}
    mq = {_ws(q): (s, lv, ty) for q, s, lv, ty in zip(m.problem, m.solution, m.level, m.type)}
    out = {}
    for r in P.records("rlvr"):
        q = _ws(r["question"])
        if r["dataset"] == "gsm8k" and q in gq:
            out[r["i"]] = {"ref": gq[q]}
        elif r["dataset"] == "MATH":
            hit = mq.get(q) or mq.get(_ws(re.sub(r"\}\s*$", "", r["question"])))
            if hit:
                out[r["i"]] = {"ref": hit[0], "level": hit[1], "type": hit[2]}
    return out


def _find(root, repo, name):
    for dp, _, fs in os.walk(os.path.join(root, repo)):
        if name in fs:
            return os.path.join(dp, name)
    raise FileNotFoundError(repo)


# ------------------------------------------------------------------ extractors
def ex_last_number(resp, gt):
    response = re.sub(r"(\d),(\d)", r"\1\2", resp)
    numbers = re.findall(r"[-+]?(?:\d*\.\d+|\d+)", response)
    extracted = numbers[-1] if numbers else response
    return extracted[:80], str(extracted).lower() == str(gt).lower()


def ex_tulu_math(resp, gt):
    from open_instruct.math_utils import (get_unnormalized_answer, hendrycks_is_equiv, is_equiv,
                                          last_boxed_only_string, normalize_final_answer, remove_boxed)
    all_answers = []
    b = last_boxed_only_string(resp)
    if b is not None:
        try:
            b = remove_boxed(b)
        except AssertionError:
            b = None
    if b is not None:
        all_answers.append(b)
    mv = normalize_final_answer(get_unnormalized_answer(resp))
    if mv is not None and mv != "[invalidanswer]":
        all_answers.append(mv)
    if not all_answers:
        d = [x.start() for x in re.finditer(r"\$", resp)]
        if len(d) > 1:
            all_answers.append(normalize_final_answer(resp[d[-2] + 1:d[-1]]))
    if not all_answers:
        all_answers.append(normalize_final_answer(resp))
        all_answers.append(resp)
    for a in all_answers:
        if is_equiv(a, gt) or hendrycks_is_equiv(a, gt):
            return str(a)[:80], True
    return str(all_answers[0])[:80], False


def ex_minerva(resp, gt):
    from open_instruct.math_utils import get_unnormalized_answer, hendrycks_is_equiv, is_equiv, normalize_final_answer
    a = normalize_final_answer(get_unnormalized_answer(resp))
    if a is None or a == "[invalidanswer]":
        a = normalize_final_answer(resp)
        shown = "[no Minerva sentence]"
    else:
        shown = a
    return str(shown)[:80], bool(is_equiv(a, gt) or hendrycks_is_equiv(a, gt))


def ex_boxed_exact(resp, gt):
    from open_instruct.math_utils import last_boxed_only_string, remove_boxed
    b = last_boxed_only_string(resp)
    if b is None:
        return "[no \\boxed{}]", False
    try:
        b = remove_boxed(b)
    except AssertionError:
        return "[malformed \\boxed]", False
    return b[:80], b.strip() == gt.strip()


ANS = re.compile(r"[Tt]he (?:final )?answer is[:\s]*\$?\\?(?:boxed\{)?\s*(-?[0-9][0-9,]*(?:\.[0-9]+)?)")


def ex_answer_is(resp, gt):
    m = ANS.findall(resp)
    if not m:
        return "[no 'The answer is']", False
    a = m[-1].replace(",", "").rstrip(".")
    try:
        return a, float(a) == float(gt.replace(",", ""))
    except ValueError:
        return a, a == gt


def ex_math_verify(resp, gt):
    from math_verify import parse, verify
    try:
        g = parse("$" + gt + "$")
        p = parse(resp)
        return (str(p[1]) if len(p) > 1 else str(p[0]) if p else "[nothing parsed]")[:80], bool(verify(g, p))
    except Exception as e:  # noqa: BLE001
        return f"[error {type(e).__name__}]", False


EX = {"last_number": ex_last_number, "tulu_math": ex_tulu_math, "minerva": ex_minerva, "boxed_exact": ex_boxed_exact,
      "answer_is": ex_answer_is, "math_verify": ex_math_verify}


def check_math(job):
    i, ds, resp, gt = job
    out = {"i": i}
    for k, f in EX.items():
        try:
            out[k] = f(resp, gt)
        except Exception as e:  # noqa: BLE001
            out[k] = (f"[error {type(e).__name__}]", False)
    return out


# ------------------------------------------------------------------ IF
def if_check(resp, gt, loose=False):
    from open_instruct.if_functions import IF_FUNCTIONS_MAP
    c = json.loads(gt)
    fn = IF_FUNCTIONS_MAP[c.pop("func_name")]
    args = {k: v for k, v in c.items() if v is not None}
    ans = resp.split("</think>")[-1].strip()
    cands = [ans]
    if loose:
        lines = ans.split("\n")
        cands += ["\n".join(lines[1:]).strip(), "\n".join(lines[:-1]).strip(), "\n".join(lines[1:-1]).strip()]
        cands += [x.replace("*", "") for x in list(cands)]
    for a in cands:
        try:
            if a and fn(a, **args):
                return True
        except Exception:  # noqa: BLE001
            pass
    return False


def summarise(results, rows, kind):
    s = {"n": len(results)}
    for ds in ("gsm8k", "MATH"):
        rs = [r for r in results if rows[r["i"]]["dataset"] == ds]
        if not rs:
            continue
        o = {"n": len(rs), "ok": {k: sum(r[k][1] for r in rs) for k in MATH_EX}}
        # pairwise agreement on the verdict
        o["agree"] = {a: {b: sum(r[a][1] == r[b][1] for r in rs) for b in MATH_EX} for a in MATH_EX}
        tulu = "last_number" if ds == "gsm8k" else "tulu_math"
        o["tulu"] = tulu
        o["tulu_ok"] = o["ok"][tulu]
        o["any_ok"] = sum(any(r[k][1] for k in MATH_EX) for r in rs)
        o["all_ok"] = sum(all(r[k][1] for k in MATH_EX) for r in rs)
        o["tulu_vs_mv"] = dict(Counter(f"{int(r[tulu][1])}{int(r['math_verify'][1])}" for r in rs))
        s[ds] = o
    return s


def main():
    rows = {r["i"]: r for r in P.records("rlvr")}
    refs = references()
    res = {"sources": DL, "joined": {d: sum(rows[i]["dataset"] == d for i in refs) for d in ("gsm8k", "MATH")},
           "rows": {d: sum(r["dataset"] == d for r in rows.values()) for d in ("gsm8k", "MATH", "ifeval")}}
    jobs = [(i, rows[i]["dataset"], v["ref"], rows[i]["ground_truth"]) for i, v in sorted(refs.items())]
    with get_context("spawn").Pool(4) as pool:
        ref_res = pool.map(check_math, jobs, chunksize=50)
    res["ref"] = summarise(ref_res, rows, "ref")
    ex = []
    for r in ref_res:
        bad = [k for k in MATH_EX if not r[k][1]]
        if bad:
            ex.append(dict(r, dataset=rows[r["i"]]["dataset"], gt=rows[r["i"]]["ground_truth"], fail=bad))
    with gzip.open(os.path.join(P.scratch(), "checkers_ref.jsonl.gz"), "wt") as f:
        for r in ref_res:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    res["ref_examples"] = pick_examples(ex, rows, refs)
    # model outputs
    res["model"] = {}
    for fn in sys.argv[1:]:
        if not os.path.exists(fn):
            continue
        gen = [json.loads(x) for x in open(fn)]
        label = gen[0]["model"] if gen else os.path.basename(fn)
        mj = [(g["i"], g["dataset"], g["response"], rows[g["i"]]["ground_truth"]) for g in gen if g["dataset"] != "ifeval"]
        with get_context("spawn").Pool(4) as pool:
            mres = pool.map(check_math, mj, chunksize=4)
        o = summarise(mres, rows, "model")
        ifr = [g for g in gen if g["dataset"] == "ifeval"]
        st = [if_check(g["response"], rows[g["i"]]["ground_truth"]) for g in ifr]
        lo = [if_check(g["response"], rows[g["i"]]["ground_truth"], loose=True) for g in ifr]
        o["ifeval"] = {"n": len(ifr), "strict": sum(st), "loose": sum(lo),
                       "by_type": {}}
        for g, a, b in zip(ifr, st, lo):
            t = rows[g["i"]]["constraint_type"]
            d = o["ifeval"]["by_type"].setdefault(t, [0, 0, 0])
            d[0] += 1
            d[1] += a
            d[2] += b
        o["finish"] = dict(Counter(g.get("finish") for g in gen))
        o["examples"] = model_examples(mres, gen, rows, ifr, st, lo)
        res["model"][label] = o
    P.save_out("checkers.json", res)
    print(json.dumps({k: res[k] for k in ("joined", "rows")}), json.dumps(res["ref"])[:1500])
    for k, v in res["model"].items():
        print(k, json.dumps({d: v.get(d, {}).get("ok") for d in ("gsm8k", "MATH")}), v["ifeval"]["strict"],
              v["ifeval"]["loose"], v["ifeval"]["n"])


def pick_examples(ex, rows, refs, per=3):
    """A few reference solutions that some extractor rejects, per failing extractor (short excerpts)."""
    out, seen = [], Counter()
    for r in ex:
        key = (r["dataset"], tuple(sorted(r["fail"])))
        if seen[key] >= 1 or len(out) >= 14:
            continue
        seen[key] += 1
        ref = refs[r["i"]]["ref"]
        out.append({"i": r["i"], "dataset": r["dataset"], "gt": r["gt"], "tail": ref[-220:],
                    "q": rows[r["i"]]["question"][:220], "res": {k: r[k] for k in MATH_EX}})
    return out


def model_examples(mres, gen, rows, ifr, st, lo):
    by = {g["i"]: g for g in gen}
    out = []
    for r in mres:
        verdicts = {k: r[k][1] for k in MATH_EX}
        if len(set(verdicts.values())) > 1:
            g = by[r["i"]]
            out.append({"i": r["i"], "dataset": g["dataset"], "gt": rows[r["i"]]["ground_truth"],
                        "q": rows[r["i"]]["question"][:240], "resp": g["response"][-500:],
                        "res": {k: r[k] for k in MATH_EX}})
    for g, a, b in zip(ifr, st, lo):
        if a != b:
            out.append({"i": g["i"], "dataset": "ifeval", "gt": rows[g["i"]]["ground_truth"],
                        "q": rows[g["i"]]["question"][:300], "resp": g["response"][:500],
                        "res": {"strict": a, "loose": b}, "type": rows[g["i"]]["constraint_type"]})
    return out


if __name__ == "__main__":
    main()
