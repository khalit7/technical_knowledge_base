"""Writes ../parts/22_js_rd_page.js: the measured inputs the Reading tab embeds from the lab tabs.
Run from this folder: python3 -B make_read_data.py   (standard library only)
Inputs (all committed): ../pipe/out/page_data.json and for_reading.json (Pipeline lab), ../qual/out/q_summary.json
(Quality lab), ../dedup/out/*.json (Dedup lab). The two quality scores of the page come from
`../qual/q_page_score.py http://www.protectnmwater.org/` run on 2026-10-15 (printed values copied below) and
agree with FineWeb-Edu's stored score for this page (2.765625)."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
J = lambda *p: json.load(open(os.path.join(H, '..', *p)))
pd = J('pipe', 'out', 'page_data.json')
page = [p for p in pd['pages'] if p['host'] == 'www.protectnmwater.org'][0]
fr = J('pipe', 'out', 'for_reading.json')
q = J('qual', 'out', 'q_summary.json')
out = {
    'page': {
        'host': page['host'], 'crawl': 'CC-MAIN-2024-30', 'warc': '00000',
        'html_chars': page['html_chars'], 'html_tags': page['html_tags'],
        'html_excerpt': fr['todo2_real_page']['HTML_excerpt'],
        'wet': page['wet']['text'], 'wet_lines': page['wet_lines'], 'traf': page['traf']['text'], 'res': page['res']['text'],
        'keep_traf': page['keep']['traf'], 'keep_res': page['keep']['res'],
        'lid': {'traf': page['traf']['en'], 'res': page['res']['en'], 'wet': page['wet']['en']},
        'verdict': {'traf': page['traf']['out'], 'res': page['res']['out'], 'wet': page['wet']['out']},
        'punct_lines': {k: page[k]['punct_lines'] for k in ('wet', 'traf', 'res')},
        # q_page_score.py output, 2026-10-15
        'edu_score': 2.765, 'edu_int': 3, 'dclm_p': 0.00164, 'dclm_cut': q['dclm_cut'],
        'in_fineweb': True, 'in_fineweb_edu': True, 'fineweb_edu_stored_score': 2.765625,
    },
    'funnel': fr['todo4_measured_funnel'],
    'chardup': fr['todo5_char_dup'],
}
s = json.dumps(out, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c').replace('>', '\\u003e')
open(os.path.join(H, '..', 'parts', '22_js_rd_page.js'), 'w').write(
    '// ---- Reading tab: measured inputs from the lab tabs (generated by src/read/make_read_data.py; do not edit) ----\n'
    'window.RDP=' + s + ';\n')
print('wrote 22_js_rd_page.js', len(s), 'chars')
