"""Build the page's embedded data (parts/22_pc_data.js) and the prose facts (data/facts.json) from the committed
inputs in src/inputs and src/data. Run by build.sh before assembling the page. Pure stdlib.
Every number the prose quotes as @@key@@ comes from facts.json, so prose and data cannot drift apart.
"""
import csv, json, os, math

H = os.path.dirname(os.path.abspath(__file__))
IN = os.path.join(H, 'inputs')
DA = os.path.join(H, 'data')
facts = {}
PC = {}


def fmt_int(n):
    return f'{n:,}'


def fmt_bn(n, d=1):
    return f'{n / 1e9:.{d}f} billion'


# ---- Common Crawl crawl statistics ----
rows = list(csv.DictReader(open(os.path.join(IN, 'cc', 'monthly.csv'))))
crawls = []
for r in rows:
    crawls.append({'id': r['crawl'], 'page': int(r['page']), 'url': int(r['url']), 'digest': int(r['digest estim.'])})
info = {c['id']: c for c in json.load(open(os.path.join(IN, 'cc', 'collinfo.json')))}
for c in crawls:
    i = info.get(c['id'])
    if i:
        c['from'] = i['from'][:10]
        c['to'] = i['to'][:10]
PC['crawls'] = crawls
cum = list(csv.DictReader(open(os.path.join(IN, 'cc', 'cumulative.csv'))))[-1]
tot_pages, tot_urls = int(cum['page']), int(cum['url estim.'])
assert tot_pages == sum(c['page'] for c in crawls), 'cumulative.csv last row should equal the sum of monthly pages'
facts['cc_n_crawls'] = str(len(crawls))
facts['cc_total_pages'] = f'{tot_pages / 1e9:.1f} billion'
facts['cc_total_urls'] = f'{tot_urls / 1e9:.1f} billion'
facts['cc_caps_per_url'] = f'{tot_pages / tot_urls:.1f}'
# files of the latest crawl, compressed TiB as printed on its index page (checked 2026-10-14)
PC['ccfiles'] = {'crawl': 'CC-MAIN-2026-39', 'rows': [
    ['WARC (raw responses)', 82.79], ['WAT (metadata, links)', 14.16], ['WET (extracted text)', 5.89],
    ['Non-200 responses', 2.70], ['robots.txt captures', 0.15], ['URL index (CDX)', 0.23], ['Columnar index (Parquet)', 0.20]]}
PC['recout'] = open(os.path.join(IN, 'cc', 'python_org_demo_output.txt')).read()

# ---- robots.txt opt-outs (measured here) ----
rb_p = os.path.join(DA, 'robots_optout.json')
if os.path.exists(rb_p):
    rb = json.load(open(rb_p))
    PC['robots'] = rb
    hosts = sum(v['robots_200_parsed'] for v in rb['crawls'].values())
    facts['rb_hosts_total'] = fmt_int(hosts)
    facts['rb_files'] = str(rb['files_per_crawl'])
    n_min = min(v['robots_200_parsed'] for v in rb['crawls'].values())
    facts['rb_se'] = f'{100 * math.sqrt(0.25 / n_min):.1f}'  # worst-case binomial standard error at p = 0.5
    for c, v in rb['crawls'].items():
        k = c.replace('CC-MAIN-', '').replace('-', '_')
        for a in ('CCBot', 'GPTBot', 'ClaudeBot', 'Google-Extended', '* (all crawlers)'):
            facts[f'rb_{k}_{a.split()[0].replace("-", "").replace("*", "all").lower()}'] = f"{100 * v['full_block_share_of_parsed'][a]:.1f}%"

for extra in sorted(os.listdir(DA)):
    if extra.endswith('.json') and extra not in ('facts.json', 'robots_optout.json', 'samples_manifest.json', 'tokenizers_manifest.json'):
        key = extra[:-5]
        PC[key] = json.load(open(os.path.join(DA, extra)))
        f = PC[key].get('facts') if isinstance(PC[key], dict) else None
        if f:
            facts.update(f)

json.dump(facts, open(os.path.join(DA, 'facts.json'), 'w'), indent=1, sort_keys=True)
with open(os.path.join(H, 'parts', '22_pc_data.js'), 'w') as o:
    o.write('// generated by build_data.py from src/inputs and src/data; do not edit\n')
    o.write('window.PC=' + json.dumps(PC, separators=(',', ':'), ensure_ascii=False) + ';\n')
print('facts', len(facts), 'data bytes', os.path.getsize(os.path.join(H, 'parts', '22_pc_data.js')))
