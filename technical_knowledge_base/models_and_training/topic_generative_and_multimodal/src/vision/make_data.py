"""Assemble the Vision lab's page data: parts/34_js_vs_0data.js (window.VS_DATA) from out/*.json and the images.

Run with the shared venv (Pillow): python -I make_data.py   (needs GM_SCRATCH for the full-size test images)
Every number the page shows comes from out/analyse_<model>.json, out/zeroshot.json, out/embed_fmnist_<model>.json;
check_data.py confirms the page embeds exactly these.
"""
import base64, io, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from vs_env import *
import numpy as np
from PIL import Image

PARTS = os.path.join(HERE, "..", "parts")
IMG = os.path.join(HERE, "img")
uri = lambda b, t: f"data:image/{t};base64," + base64.b64encode(b).decode()


def webp(im, size, q=72):
    bio = io.BytesIO(); im.resize((size, size), Image.BICUBIC).save(bio, "WEBP", quality=q); return bio.getvalue()


def b64(a):
    return base64.b64encode(np.asarray(a, dtype=np.int8).tobytes()).decode()


def r4(x):
    return np.round(np.asarray(x, dtype=float), 4).tolist()


A = {w: json.load(open(os.path.join(OUT, f"analyse_{w}.json"))) for w in ("clip", "siglip")}
Z = json.load(open(os.path.join(OUT, "zeroshot.json")))
E = {w: json.load(open(os.path.join(OUT, f"embed_fmnist_{w}.json"))) for w in ("clip", "siglip")}
P = json.load(open(os.path.join(HERE, "probes.json")))
keys = A["clip"]["keys"]; assert keys == A["siglip"]["keys"]

D = {"keys": keys, "captions": A["clip"]["captions"], "classes": Z["classes"], "date": A["clip"]["date"],
     "machine": A["clip"]["machine"], "prompt_sets": A["clip"]["prompt_sets"], "probes": P, "models": {}}
# images: 16 test images at 96 px, the 5 patch-view images at 224 px (committed copies in img/), probes at 112 px, 40 query digits
ti = {k: im for k, im, _ in pretrained.test_images()}
D["thumbs"] = {k: uri(webp(ti[k], 96), "webp") for k in keys}
xt, yt = load_split("test")
pimgs = []
for k in A["clip"]["patch_images"]:
    im = ti[k] if k in ti else Image.fromarray(xt[0]).convert("RGB")
    p = os.path.join(IMG, f"patch_{k.split('_')[0] if k.startswith('fmnist') else k}.webp")
    b = webp(im, 224, 75); open(p, "wb").write(b); pimgs.append(uri(b, "webp"))
D["patch_images"] = A["clip"]["patch_images"]; D["patch_uris"] = pimgs
D["probe_uris"] = {k: uri(open(os.path.join(IMG, k + ".webp"), "rb").read(), "webp")
                   for p in P.values() for k in p["images"]}
q = Z["query_idx"]
def png(a):
    bio = io.BytesIO(); Image.fromarray(a).save(bio, "PNG", optimize=True); return uri(bio.getvalue(), "png")
D["fmclf"] = json.load(open(os.path.join(HERE, "..", "data", "smoke", "train_results.json")))["classifier"]["test_acc"]
D["query"] = {"idx": q, "labels": [int(yt[i]) for i in q], "uris": [png(xt[i]) for i in q]}

for w, a in A.items():
    z = Z[w]; g = a["grid"]
    tok = np.asarray(a["tokens24"])[:, :, :16]; ts = float(np.abs(tok).max()) / 127
    att = np.asarray(a["pool_att"]); attq = np.round(att / att.max(1, keepdims=True) * 127)
    D["models"][w] = {
        "repo": a["model"][0], "rev": a["model"][1][:12], "params": a["params"], "params_vision": a["params_vision"],
        "params_text": a["params_text"], "scale": a["logit_scale"], "bias": a.get("logit_bias"),
        "input": a["input_shape"][1:], "ps": a["patch_size"], "grid": g, "check": a["patch_check"],
        "pos_shape": a["pos_shape"], "pos": b64(a["pos_cos"]), "tok": b64(np.round(tok / ts)), "tok_scale": round(ts, 6),
        "pool": a["pool"], "pool_keys": a["pool_keys"], "pool_att": b64(attq),
        "pool_max": r4(att.max(1)),
        "sim16": r4(a["sim16"]), "sim16_cased": r4(a["sim16_cased"]) if "sim16_cased" in a else None,
        "case": json.load(open(os.path.join(OUT, f"diag_case_{w}.json")))["acc"],
        "lp_unscaled": z["linear_probe_unscaled_500"], "probe_settings": z["probe_settings"], "probes": {k: r4(v) for k, v in a["probes"].items()},
        "embed16": [a["embed16_img_seconds"], a["embed16_txt_seconds"]],
        "fmnist_ips": E[w]["images_per_second"], "fmnist_seconds": round(E[w]["val_seconds"] + E[w]["test_seconds"], 1),
        "acc": z["acc"], "per_class": z["per_class"], "best": z["best"], "confusion": z["confusion"],
        "query_cos": {k: base64.b64encode(np.round(np.asarray(v) * 10000).astype("<i2").tobytes()).decode()
                      for k, v in z["query_cos"].items()},   # int16, cosine x 10,000, 40 images x 10 classes
        "lp": z["linear_probe"]}
js = "// generated by src/vision/make_data.py: do not edit by hand\nwindow.VS_DATA=" + json.dumps(D, separators=(",", ":")) + ";\n"
open(os.path.join(PARTS, "34_js_vs_0data.js"), "w").write(js)
print("34_js_vs_0data.js", len(js), "bytes")
