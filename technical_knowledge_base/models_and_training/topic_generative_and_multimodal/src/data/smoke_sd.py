"""Smoke test of the latent-diffusion model on MPS, and the six generated test images g01..g06.

Run under the bench lock: GM_SCRATCH=... nice -n 15 python -I smoke_sd.py
Records load time, per-image and per-step time, peak memory, and one SD-VAE round trip (latent shape,
latent std with and without the 0.18215 scaling factor, PSNR) in smoke/sd.json.
"""
import json, os, sys, time

import numpy as np
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from common import cap_threads, device, scratch, sha256, PeakMem, sync, empty_cache, MACHINE
from grids import thumb
from pretrained import load_sd, PROMPTS, GEN, SD

cap_threads(4)
dev = device("mps")
res = {"model": SD[0], "revision": SD[1], "dtype": "float16", "gen": GEN, "machine": MACHINE, "date": time.strftime("%Y-%m-%d")}
with PeakMem() as pm:
    t = time.time(); pipe = load_sd(dev); sync(dev); res["load_seconds"] = round(time.time() - t, 1)
    res["scaling_factor"] = pipe.vae.config.scaling_factor
    res["unet_params"] = sum(p.numel() for p in pipe.unet.parameters())
    res["vae_params"] = sum(p.numel() for p in pipe.vae.parameters())
    res["text_encoder_params"] = sum(p.numel() for p in pipe.text_encoder.parameters())
    times = {}
    meta = json.load(open(os.path.join(HERE, "test_images.json")))
    items = [i for i in meta["items"] if not i["key"].startswith("g")]
    for k, key in enumerate(["g01", "g02", "g03", "g04", "g05", "g06"]):
        seed = k
        g = torch.Generator("cpu").manual_seed(seed)
        sync(dev); t = time.time()
        img = pipe(PROMPTS[key], num_inference_steps=GEN["steps"], guidance_scale=GEN["guidance_scale"],
                   generator=g, height=512, width=512).images[0]
        sync(dev); times[key] = round(time.time() - t, 2)
        print(key, times[key], "s", flush=True)
        name = f"{key}_{['bicycle', 'oranges', 'lighthouse', 'puppy', 'stopsign', 'astronaut'][k]}"
        p = scratch("test_images", name + ".png"); img.save(p)
        tb = thumb(img, os.path.join(HERE, "test_images", name + ".webp"), 256, 80)
        items.append({"key": name, "kind": "generated", "licence": "generated by Stable Diffusion v1.5 (CreativeML OpenRAIL-M: outputs belong to the user, use-based restrictions apply)",
                      "caption": f"generated from the prompt: {PROMPTS[key]}", "prompt": PROMPTS[key], "seed": seed,
                      "truth": {"prompt": PROMPTS[key], "note": "ground truth is the prompt; check by eye what was actually drawn"},
                      "full_png_sha256": sha256(p), "thumb_bytes": tb})
    res["seconds_per_image"] = times
    first, rest = times["g01"], [v for k, v in times.items() if k != "g01"]
    res["first_image_seconds_incl_warmup"] = first
    res["median_seconds_per_image"] = float(np.median(rest))
    res["median_seconds_per_step_incl_cfg"] = round(float(np.median(rest)) / GEN["steps"], 3)

    # one VAE round trip on the cat photo
    from PIL import Image
    im = Image.open(scratch("test_images", "p01_cat.png")).convert("RGB")
    x = torch.from_numpy(np.asarray(im)).permute(2, 0, 1)[None].float().div(127.5).sub(1).to(dev, torch.float16)
    with torch.no_grad():
        lat = pipe.vae.encode(x).latent_dist.mean
        rec = pipe.vae.decode(lat).sample.float().clamp(-1, 1)
    mse = float(((rec.cpu() - x.float().cpu()) ** 2).mean())
    res["vae_roundtrip_p01"] = {"input": list(x.shape), "latent": list(lat.shape),
                                "latent_std_raw": round(float(lat.float().std()), 4),
                                "latent_std_scaled": round(float(lat.float().std()) * res["scaling_factor"], 4),
                                "psnr_db": round(10 * np.log10(4.0 / mse), 2), "dtype": "float16"}
    sync(dev)
res["peak_mps_mb"], res["max_rss_mb"] = pm.peak_mb, pm.rss_mb
meta["items"] = items
json.dump(meta, open(os.path.join(HERE, "test_images.json"), "w"), indent=1)
json.dump(res, open(os.path.join(HERE, "smoke", "sd.json"), "w"), indent=1)
print(json.dumps(res), flush=True)
