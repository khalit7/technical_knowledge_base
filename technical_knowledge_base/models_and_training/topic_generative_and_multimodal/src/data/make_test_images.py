"""The fixed colour test images for the pretrained models (CLIP/SigLIP, the SD VAE, the VLM).

16 images, 512x512 RGB, each with ground truth in test_images.json:
  p01..p04  four photographs bundled with scikit-image 0.26.0 (CC0 or public domain, see the licence field)
  s01..s06  six synthetic scenes drawn here with Pillow (counting, colour, left/right, OCR, a chart, a
            typographic attack), so questions about them have exact answers
  g01..g06  six images generated by the pretrained latent-diffusion model (smoke_sd.py writes them)
This script writes p* and s*; smoke_sd.py writes g* and completes test_images.json.
Full-size images go to GM_SCRATCH/test_images/ (PNG); 256-pixel WebP thumbnails are committed in
src/data/test_images/. Run: GM_SCRATCH=... python -I make_test_images.py
"""
import json, math, os, sys

import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from common import scratch, sha256
from grids import thumb

FULL = scratch("test_images"); os.makedirs(FULL, exist_ok=True)
THUMB = os.path.join(HERE, "test_images"); os.makedirs(THUMB, exist_ok=True)
N = 512


def square(a):
    """Centre-crop a numpy image to a square and resize to 512x512."""
    h, w = a.shape[:2]; s = min(h, w)
    a = a[(h - s) // 2:(h - s) // 2 + s, (w - s) // 2:(w - s) // 2 + s]
    return Image.fromarray(a).convert("RGB").resize((N, N), Image.LANCZOS)


def font(size):
    return ImageFont.load_default(size=size)


items = []


def add(key, img, kind, licence, truth, caption):
    p = os.path.join(FULL, f"{key}.png"); img.save(p)
    tb = thumb(img, os.path.join(THUMB, f"{key}.webp"), 256, 80)
    items.append({"key": key, "kind": kind, "licence": licence, "caption": caption, "truth": truth,
                  "full_png_sha256": sha256(p), "thumb_bytes": tb})


# ---- photographs (scikit-image 0.26.0, skimage/data/_fetchers.py docstrings give the licences)
from skimage import data
add("p01_cat", square(data.chelsea()), "photo", "CC0 (photographer Stefan van der Walt), scikit-image data.chelsea",
    {"objects": ["cat"], "count_cats": 1}, "a close-up of a tabby cat's face")
add("p02_coffee", square(data.coffee()), "photo", "CC0 (photographer Rachel Michetti), scikit-image data.coffee",
    {"objects": ["cup", "saucer", "spoon"], "count_cups": 1}, "an espresso cup on a red saucer with a spoon, on a wooden table")
add("p03_rocket", square(data.rocket()), "photo", "public domain (SpaceX launch photo of DSCOVR), scikit-image data.rocket",
    {"objects": ["rocket", "launch pad", "towers"]}, "a Falcon 9 rocket standing on its launch pad at dusk, with towers and lights")
add("p04_hubble", square(data.hubble_deep_field()), "photo", "public domain (NASA Hubble eXtreme Deep Field), scikit-image data.hubble_deep_field",
    {"objects": ["galaxies"]}, "the Hubble eXtreme Deep Field: many small galaxies on black")

SYN = "synthetic, drawn by make_test_images.py (this topic's own; no third-party rights)"

# ---- s01: counting and colour
im = Image.new("RGB", (N, N), "white"); d = ImageDraw.Draw(im)
for cx, cy in ((110, 130), (260, 100), (400, 170)):
    d.ellipse((cx - 50, cy - 50, cx + 50, cy + 50), fill=(220, 30, 30))
for x0, y0 in ((120, 320), (320, 330)):
    d.rectangle((x0, y0, x0 + 100, y0 + 100), fill=(30, 70, 220))
add("s01_shapes", im, "synthetic", SYN,
    {"red_circles": 3, "blue_squares": 2, "total_shapes": 5, "absent": ["green shapes", "triangles"]},
    "three red circles and two blue squares on a white background")

# ---- s02: left / right relation
im = Image.new("RGB", (N, N), (235, 235, 235)); d = ImageDraw.Draw(im)
d.polygon([(70, 360), (200, 360), (135, 160)], fill=(30, 160, 60))
d.ellipse((310, 190, 460, 340), fill=(250, 150, 20))
add("s02_left_right", im, "synthetic", SYN,
    {"left": "green triangle", "right": "orange circle", "count_shapes": 2},
    "a green triangle on the left and an orange circle on the right, grey background")

# ---- s03: OCR
im = Image.new("RGB", (N, N), (40, 90, 140)); d = ImageDraw.Draw(im)
d.rounded_rectangle((60, 170, 452, 342), 18, fill="white")
d.text((N // 2, N // 2), "LATENT 42", font=font(64), fill="black", anchor="mm")
add("s03_text", im, "synthetic", SYN, {"text": "LATENT 42"},
    "a white card with the text LATENT 42 in black capital letters on a blue background")

# ---- s04: typographic attack (the cat photo with a written label "DOG")
im = square(data.chelsea()); d = ImageDraw.Draw(im)
d.rectangle((150, 360, 362, 450), fill="white", outline="black", width=3)
d.text((256, 405), "DOG", font=font(64), fill="black", anchor="mm")
add("s04_typographic", im, "synthetic (edited photo: p01 plus a drawn label)", "CC0 base photo (data.chelsea) plus our label",
    {"objects": ["cat"], "written_word": "DOG", "true_animal": "cat"},
    "the cat photo with a white sticker reading DOG")

# ---- s05: bar chart
im = Image.new("RGB", (N, N), "white"); d = ImageDraw.Draw(im)
vals, names, cols = [3, 7, 5, 2], ["A", "B", "C", "D"], [(70, 110, 200), (220, 120, 40), (60, 160, 90), (170, 60, 160)]
d.line((60, 440, 470, 440), fill="black", width=3); d.line((60, 440, 60, 60), fill="black", width=3)
for i, (v, nm, c) in enumerate(zip(vals, names, cols)):
    x = 95 + i * 95
    d.rectangle((x, 440 - v * 50, x + 60, 440), fill=c)
    d.text((x + 30, 465), nm, font=font(32), fill="black", anchor="mm")
    d.text((x + 30, 440 - v * 50 - 20), str(v), font=font(26), fill="black", anchor="mm")
add("s05_chart", im, "synthetic", SYN,
    {"bars": dict(zip(names, vals)), "tallest": "B", "shortest": "D", "sum": sum(vals)},
    "a bar chart with bars A=3, B=7, C=5, D=2")

# ---- s06: analog clock at 3:00
im = Image.new("RGB", (N, N), (250, 248, 240)); d = ImageDraw.Draw(im)
c, r = N // 2, 200
d.ellipse((c - r, c - r, c + r, c + r), outline="black", width=8, fill="white")
for h in range(12):
    a = math.radians(h * 30)
    d.line((c + 170 * math.sin(a), c - 170 * math.cos(a), c + 190 * math.sin(a), c - 190 * math.cos(a)), fill="black", width=6)
d.line((c, c, c + 110, c), fill="black", width=12)           # hour hand at 3
d.line((c, c, c, c - 165), fill="black", width=7)            # minute hand at 12
d.ellipse((c - 10, c - 10, c + 10, c + 10), fill="black")
add("s06_clock", im, "synthetic", SYN, {"time": "3:00"}, "an analog clock with no numerals showing three o'clock")

json.dump({"size": N, "items": items}, open(os.path.join(HERE, "test_images.json"), "w"), indent=1)
print(len(items), "images;", sum(i["thumb_bytes"] for i in items), "thumbnail bytes")
