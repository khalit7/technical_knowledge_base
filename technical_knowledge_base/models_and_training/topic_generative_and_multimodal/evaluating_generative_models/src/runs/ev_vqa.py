"""VQA-based alignment on the 64 Stable Diffusion images: SmolVLM-500M (bf16, MPS) answers yes/no questions.

    python -I ev_vqa.py           # under the bench lock (run_gpu.sh)
Two scores per image (both in [0, 1]):
  vqa_whole   P(yes) for 'Does this figure show "<prompt>"? Please answer yes or no.' (the VQAScore idea, Lin et al.
              2024, with SmolVLM-500M instead of the paper's CLIP-FlanT5 model)
  tifa_lite   the share of the prompt's three element questions (inputs/vqa_questions.json) answered yes (TIFA's idea,
              Hu et al. 2023, with questions written by hand instead of generated by a language model)
P(yes) = softmax mass of the first answer token on yes-tokens / (yes + no tokens), read from the logits after the
chat template's "Assistant:". Image budget: 2x2 tiles + global view = 320 image tokens (size longest_edge 1024; the
VLM lab measured 26 of 30 questions right at 320 tokens, the same as at 1,088). Greedy 4-token answers are kept too.
Writes out/vqa.json.
"""
import json, os, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ev_env import ev_scratch, dump, HERE
import torch
from PIL import Image
from common import cap_threads, device, sync, MACHINE, touch_bench, PeakMem
import pretrained

cap_threads(4)
torch.set_grad_enabled(False)
dev = device(os.environ.get("EV_DEV", "mps"))
Q = json.load(open(os.path.join(HERE, "..", "inputs", "vqa_questions.json")))
gen = json.load(open(os.path.join(HERE, "..", "out", "sd_gen.json")))
model, proc = pretrained.load_vlm(dev, torch.bfloat16)
tok = proc.tokenizer
YES = sorted({tok.encode(w, add_special_tokens=False)[0] for w in ("Yes", " Yes", "yes", " yes")})
NO = sorted({tok.encode(w, add_special_tokens=False)[0] for w in ("No", " No", "no", " no")})


def chat(q):
    return proc.apply_chat_template([{"role": "user", "content": [{"type": "image"}, {"type": "text", "text": q}]}],
                                    add_generation_prompt=True)


def ask(im, q):
    inp = proc(text=chat(q), images=[im], return_tensors="pt", size={"longest_edge": 1024}).to(dev)
    lg = model(**inp).logits[0, -1].float()
    p = torch.softmax(lg, -1)
    py, pn = float(p[YES].sum()), float(p[NO].sum())
    out = model.generate(**inp, do_sample=False, max_new_tokens=4)
    ans = proc.decode(out[0, inp["input_ids"].shape[1]:], skip_special_tokens=True).strip()
    return {"p_yes": round(py / (py + pn), 4), "mass_yes_no": round(py + pn, 4), "answer": ans,
            "image_tokens": int((inp["input_ids"] == model.config.image_token_id).sum())}


res = {"model": list(pretrained.VLM), "dtype": "bfloat16", "machine": MACHINE, "date": time.strftime("%Y-%m-%d"),
       "yes_ids": YES, "no_ids": NO, "images": {}}
LIMIT = int(os.environ.get("EV_LIMIT", "0"))
t0 = time.time()
with PeakMem() as pm:
    for i, r in enumerate(gen["images"]):
        if LIMIT and i >= LIMIT:
            break
        im = Image.open(ev_scratch("sd", r["name"] + ".png")).convert("RGB")
        prompt = gen["prompts"][r["key"]]
        whole = ask(im, Q["whole_prompt_template"].format(prompt=prompt))
        els = [dict(q=q, **ask(im, Q["element_template"].format(question=q))) for q in Q["questions"][r["key"]]]
        res["images"][r["name"]] = {"whole": whole, "elements": els,
                                    "tifa_lite": round(sum(e["p_yes"] > 0.5 for e in els) / len(els), 4)}
        print(r["name"], whole["p_yes"], [e["p_yes"] for e in els], [e["answer"] for e in els], f"{time.time() - t0:.0f} s", flush=True)
        touch_bench("ev")
res["peak_mps_mb"] = round(pm.peak_mb, 1); res["seconds"] = round(time.time() - t0, 1)
dump("vqa.json" if not LIMIT else "vqa_smoke.json", res)
