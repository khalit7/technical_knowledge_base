# Build parts/22_js_va_0data.js (window.VA) from the recorded outputs in this folder.
# (The Model timeline tab and its rows from the root's Model map were removed on 2026-10-24.)
# usage: python3 -I make_data.py
import json, os
H = os.path.dirname(os.path.abspath(__file__)); J = lambda *p: json.load(open(os.path.join(H, *p)))
codecs = J('codec', 'out', 'codecs.json'); assets = J('codec', 'out', 'assets.json'); mist = J('codec', 'out', 'mistakes.json')
meta_in = J('codec', 'out', 'inputs_meta.json'); vae = J('vae', 'out', 'wan_vae.json'); cnt = J('calc', 'out', 'meta.json')
vm = J('inputs', 'video_models.json'); src = J('inputs', 'source_lines.json')
for m in vm['models']:
    if m['cfg']:
        m['params'] = cnt['params'][m['cfg']]; m['pcount'] = 'counted from config (meta device)'
    else:
        m['pcount'] = 'stated in the paper'
spk = codecs['clips']['speech']['codecs']
# the EnCodec block of run_codecs.py (shown on the page) and the lines the script printed (same format as its print calls)
rc = open(os.path.join(H, 'codec', 'run_codecs.py')).read().split('\n')
i0 = [i for i, l in enumerate(rc) if l.startswith('    # EnCodec 24 kHz')][0]; i1 = [i for i, l in enumerate(rc) if i > i0 and l.strip() == 'del m'][0]
runcode = '\n'.join(l[4:] for l in rc[i0:i1])
outl = []
for c, R in codecs['clips'].items():
    C = R['codecs']; e, d_, mi = C['encodec']['rows'], C['dac']['rows'], C['mimi']['rows']
    outl += [f"{c} encodec {e[0]} {e[7]} {e[-1]}", f"{c} dac {d_[0]} {d_[-1]}", f"{c} mimi {mi[0]} {mi[7]} {mi[-1]}"]
VA = dict(
  codecs={c: {k: v for k, v in R['codecs'].items()} for c, R in codecs['clips'].items()},
  clipsec={c: R['seconds'] for c, R in codecs['clips'].items()}, inmeta=meta_in, revisions=codecs['revisions'],
  spec=assets['spec'], audio=assets['audio'], env=assets['env'], mist=mist,
  vae={k: v for k, v in vae.items()}, models=vm['models'], reproduce=vm['reproduce'], flopcheck=cnt['flop_check'],
  src=src, runcode=runcode, runout='\n'.join(outl))
s = '// generated by make_data.py from codec/out, vae/out, calc/out, inputs; do not edit\nwindow.VA=' + json.dumps(VA, separators=(',', ':')) + ';\n'
open(os.path.join(H, 'parts', '22_js_va_0data.js'), 'w').write(s)
print('bytes', len(s))
