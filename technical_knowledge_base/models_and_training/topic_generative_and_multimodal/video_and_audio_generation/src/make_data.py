# Build parts/22_js_va_0data.js (window.VA) from the recorded outputs in this folder and the root's Model map rows.
# usage: python3 -I make_data.py
import json, os
H = os.path.dirname(os.path.abspath(__file__)); J = lambda *p: json.load(open(os.path.join(H, *p)))
codecs = J('codec', 'out', 'codecs.json'); assets = J('codec', 'out', 'assets.json'); mist = J('codec', 'out', 'mistakes.json')
meta_in = J('codec', 'out', 'inputs_meta.json'); vae = J('vae', 'out', 'wan_vae.json'); cnt = J('calc', 'out', 'meta.json')
vm = J('inputs', 'video_models.json'); src = J('inputs', 'source_lines.json'); ax = J('inputs', 'arxiv_extra.json')
mm = json.load(open(os.path.join(H, '..', '..', 'src', 'map', 'out', 'mm_data.json')))
for m in vm['models']:
    if m['cfg']:
        m['params'] = cnt['params'][m['cfg']]; m['pcount'] = 'counted from config (meta device)'
    else:
        m['pcount'] = 'stated in the paper'
# timeline: the Model map's video and audio rows (dates, statuses), plus method papers (arXiv v1 dates)
rows = [dict(id=r['id'], n=r['n'], c=r['c'], o=r['o'], fam=r['fam'], d=r['d'], dk=r['dk'], st=r['st'], acc=r['acc'], size=r['size'], obj=r['obj'], what=r['what'], ev=r['ev'])
        for r in mm['rows'] if r['c'] in ('video', 'audio') and r['d']]
A = lambda k: ax[[x for x in ax if x.startswith(k)][0]]['published']
methods = [
 ('vdm', 'Video Diffusion Models', 'video', '2204.03458', 'Factorised space-time U-Net: spatial attention per frame, then temporal attention per position.'),
 ('latte', 'Latte', 'video', '2401.03048', 'A video DiT that compares four ways of splitting spatial and temporal attention.'),
 ('dforce', 'Diffusion Forcing', 'video', '2407.01392', 'Each frame gets its own noise level: rollouts past the training length.'),
 ('causvid', 'CausVid', 'video', '2412.07772', 'A causal, few-step student distilled from a bidirectional video model: streaming generation.'),
 ('framepack', 'FramePack', 'video', '2504.12626', 'Compresses older frames into fewer tokens so context stays bounded; anti-drift sampling.'),
 ('selfforce', 'Self Forcing', 'video', '2506.08009', 'Trains on its own autoregressive rollouts to close the train-test gap.'),
 ('fvd', 'FVD', 'video', '1812.01717', 'Frechet distance on I3D video features: the first standard video metric.'),
 ('vbench', 'VBench', 'video', '2311.17982', '16 dimensions, each scored by its own model.'),
 ('encodec', 'EnCodec', 'audio', '2210.13438', 'Neural codec: 24 kHz, 75 frames a second, up to 32 RVQ codebooks (measured on this page).'),
 ('dac', 'DAC', 'audio', '2306.06546', 'Improved RVQGAN: 44.1 kHz, 9 codebooks, factorised L2-normalised codes (measured on this page).'),
 ('fad', 'FAD', 'audio', '1812.08466', 'Frechet distance on VGGish audio features.'),
]
for k, n, c, a, w in methods:
    rows.append(dict(id=k, n=n, c=c, o='', fam='method', d=A(a), dk='arXiv v1', st='method', acc='paper', size='', obj='', what=w, ev='primary', ax=a))
rows.sort(key=lambda r: r['d'])
spk = codecs['clips']['speech']['codecs']
# the EnCodec block of run_codecs.py (shown on the page) and the lines the script printed (same format as its print calls)
rc = open(os.path.join(H, 'codec', 'run_codecs.py')).read().split('\n')
i0 = [i for i, l in enumerate(rc) if l.startswith('    # EnCodec 24 kHz')][0]; i1 = [i for i, l in enumerate(rc) if i > i0 and l.strip() == 'del m'][0]
runcode = '\n'.join(l[4:] for l in rc[i0:i1])
outl = []
for c, R in codecs['clips'].items():
    C = R['codecs']; e, d_, mi = C['encodec']['rows'], C['dac']['rows'], C['mimi']['rows']
    outl += [f"{c} encodec {e[0]} {e[7]} {e[-1]}", f"{c} dac {d_[0]} {d_[-1]}", f"{c} mimi {mi[0]} {mi[7]} {mi[-1]}"]
VA = dict(
  codecs={c: {k: v for k, v in R['codecs'].items()} for c, R in codecs['clips'].items()},
  clipsec={c: R['seconds'] for c, R in codecs['clips'].items()}, inmeta=meta_in, revisions=codecs['revisions'],
  spec=assets['spec'], audio=assets['audio'], env=assets['env'], mist=mist,
  vae={k: v for k, v in vae.items()}, models=vm['models'], reproduce=vm['reproduce'], flopcheck=cnt['flop_check'],
  src=src, timeline=rows, runcode=runcode, runout='\n'.join(outl), mapchecked=mm.get('checked'))
s = '// generated by make_data.py from codec/out, vae/out, calc/out, inputs and the root\'s src/map/out/mm_data.json; do not edit\nwindow.VA=' + json.dumps(VA, separators=(',', ':')) + ';\n'
open(os.path.join(H, 'parts', '22_js_va_0data.js'), 'w').write(s)
print('bytes', len(s), 'timeline', len(rows))
