"""Derive the few numbers the 3D scenes and their step lists quote, from this page's own recorded data.

  python3 make_scene_data.py      (run by build.sh; seconds, CPU, no scratch needed)

Reads parts/22_js_nm_0data.js (window.NM, written by make_data.py from the recorded runs) and writes
parts/22_js_nm_1sc.js, which sets window.NM.sc. prefill.py writes the same values into the static step lists
(data-nm="sc.<name>"), so the scenes and the prose cannot disagree. Nothing here is a new measurement:
every value is a sum, count or product of recorded values.
- ar: the tiny autoregressive model writing one dress (class 3) at temperature 1 (smp.ar_record["1.0"]),
  the same recorded sample the token-by-token widget replays: the entropy (bits) of each of its 64 steps,
  summed per row of the 8 x 8 grid (the chosen codes' probabilities are recorded to 4 decimals, too coarse for -log2).
- mask: the masked model's 8-round decode of class 3 (smp.mask_record): how many positions each round fills.
- cost: sequential calls and FLOPs per image of the three samplers in section 4 (d.ar_sample_flops,
  8 x d.mask_pass_flops, 20 x tok.flops_unet_fwd_1), the counted networks of tokenize_data.py.
"""
import json, math, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "parts", "22_js_nm_0data.js"), encoding="utf8").read()
N = json.loads(re.search(r"window\.NM=(\{.*?\});\n", src, re.S).group(1))
C = 3  # dress, the class the widgets open on
rec = N["smp"]["ar_record"]["1.0"]
H, p = rec["H"][C], rec["p"][C]
rows = [round(sum(H[r * 8:(r + 1) * 8]), 1) for r in range(8)]
order = sorted(range(64), key=lambda j: -H[j])
mr = N["smp"]["mask_record"]["tokens_per_round"]
cum = [sum(1 for v in mr[r][C] if v != N["smp"]["mask_record"]["mask_id"]) for r in range(len(mr))]
per = [cum[0]] + [cum[i] - cum[i - 1] for i in range(1, len(cum))]
side = [j for j in range(64) if j % 8 in (0, 7)]
mid = [j for j in range(64) if j % 8 not in (0, 7)]
sc = {
    "cls": C,
    "ar": {"rowbits": rows, "Hsum": round(sum(H), 1),
           "Hmax": round(H[order[0]], 2), "Hmax_pos": order[0] + 1, "Hmax_row": order[0] // 8 + 1, "Hmax_col": order[0] % 8 + 1,
           "n_below_half": sum(1 for h in H if h < 0.5), "n_above_5": sum(1 for h in H if h > 5),
           "side_mean": round(sum(H[j] for j in side) / len(side), 2), "side_max": round(max(H[j] for j in side), 2),
           "mid_mean": round(sum(H[j] for j in mid) / len(mid), 2)},
    "mask": {"per_round": per, "cum": cum},
    "cost": {"ar_calls": 64, "mask_calls": len(mr), "ddim_calls": 20,
             "ar_flops": N["d"]["ar_sample_flops"], "mask_flops": len(mr) * N["d"]["mask_pass_flops"],
             "ddim_flops": 20 * N["tok"]["flops_unet_fwd_1"]},
}
sc["cost"]["ddim_over_ar"] = round(sc["cost"]["ddim_flops"] / sc["cost"]["ar_flops"], 1)
sc["cost"]["mask_over_ar"] = round(sc["cost"]["mask_flops"] / sc["cost"]["ar_flops"], 1)
for i, v in enumerate(rows):
    sc["ar"]["row%d" % (i + 1)] = v
for i, v in enumerate(per):
    sc["mask"]["r%d" % (i + 1)] = v
out = "// generated by make_scene_data.py from 22_js_nm_0data.js: the numbers the 3D scenes and their step lists quote\nwindow.NM.sc=" + json.dumps(sc, separators=(",", ":")) + ";\n"
open(os.path.join(HERE, "parts", "22_js_nm_1sc.js"), "w", encoding="utf8").write(out)
print("scene data:", json.dumps(sc)[:300])
