"""Write parts/22_js_av_3scene.js (window.AVSC): the per-image numbers the 3D stages draw that the page's other data parts
do not carry. CPU, under a second, read only: copied field by field from the topic root's committed Latent lab recording
(../../src/latent/out/tiny.json, written by the root's src/latent/eval_lt.py), nothing is recomputed.
  python3 make_scene_data.py
Fields, for the four hero test images (positions 0, 1, 7, 9 of the topic's 16 test images, the tiles the hero card shows):
  ae16 code16      the 16-number autoencoder's code of each image
  vae16 mu16/sigma16  the 16-number VAE's (beta = 1) posterior mean and standard deviation
  psnr16           per-image test PSNR of ae16, vae16_b1p0 and vq_restart
It asserts the run-level numbers equal the ones this page already embeds (parts/22_js_av_1lab.js), so the stages and the
prose read one recording.
"""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
TINY = os.path.join(HERE, "..", "..", "src", "latent", "out", "tiny.json")
PICK = [0, 1, 7, 9]


def main():
    t = json.load(open(TINY))
    r = t["runs"]
    s = open(os.path.join(HERE, "parts", "22_js_av_1lab.js")).read()
    L = json.loads(s[s.index("=") + 1:s.rindex(";")])
    for k in ("ae16", "vae16_b1p0", "vq_restart"):
        assert abs(r[k]["test_psnr_db"] - L["runs"][k]["test_psnr_db"]) < 1e-9, k
    assert r["vae16_b1p0"]["kl_per_dim"] == L["runs"]["vae16_b1p0"]["kl_per_dim"]
    out = {"pick": PICK, "test16_index": [t["test16_indices"][i] for i in PICK],
           "ae16_code": [r["ae16"]["code16"][i] for i in PICK],
           "vae_mu": [r["vae16_b1p0"]["mu16"][i] for i in PICK],
           "vae_sigma": [r["vae16_b1p0"]["sigma16"][i] for i in PICK],
           "psnr": {k: [r[k]["test16_psnr_db"][i] for i in PICK] for k in ("ae16", "vae16_b1p0", "vq_restart")}}
    # the hero stage's image (the first pick): ranges written in its step list
    a, mu, sg = out["ae16_code"][0], out["vae_mu"][0], out["vae_sigma"][0]
    out["hero"] = {"ae_min": min(a), "ae_max": max(a), "mu_min": min(mu), "mu_max": max(mu), "sig_min": min(sg), "sig_max": max(sg),
                   "psnr_ae16": out["psnr"]["ae16"][0], "psnr_vae": out["psnr"]["vae16_b1p0"][0], "psnr_vq": out["psnr"]["vq_restart"][0]}
    # the KL this image pays, per number and in total: 1/2 (mu^2 + sigma^2 - 1 - log sigma^2), nats (the closed form of section 3)
    kl = [0.5 * (m * m + v * v - 1 - math.log(v * v)) for m, v in zip(mu, sg)]
    out["hero"].update({"kl_img": round(sum(kl), 2), "kl_dim_max": round(max(kl), 2), "kl_dim_min": round(min(kl), 3)})
    kd = L["runs"]["vae16_b1p0"]["kl_per_dim"]
    out["col"] = {"vae_kl_min": min(kd), "vae_kl_max": max(kd)}
    js = ("// generated by src/make_scene_data.py from the topic root's Latent lab recording (src/latent/out/tiny.json, read only); do not edit\n"
          "window.AVSC=" + json.dumps(out, separators=(",", ":")) + ";\n")
    open(os.path.join(HERE, "parts", "22_js_av_3scene.js"), "w").write(js)
    print("22_js_av_3scene.js", len(js), "bytes")


if __name__ == "__main__":
    main()
