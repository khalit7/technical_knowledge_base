"""Write parts/22_js_av_1lab.js (window.AVL): the subset of the topic root's retired Latent lab that this page now teaches
(this page owns the autoencoder, the VAE, beta, VQ-VAE basics and the SD VAE's scaling factor since 2026-10-23).
Read only, CPU, seconds: the root's committed data part (src/retired/parts/31_js_lt_0data.js since the 2026-10-24 topic close, written by the root's
src/latent/make_data.py from its recorded runs) is copied field by field, nothing is recomputed.
  python3 absorb_lab.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT_PART = os.path.join(HERE, "..", "..", "src", "retired", "parts", "31_js_lt_0data.js")

RUN_FIELDS = ("params", "train_seconds", "test_nll_nats", "test_psnr_db", "test_kl_nats", "test_neg_elbo_nats_beta1",
              "active_units", "posterior_sigma_mean", "prior", "prior_std_normal", "prior_fitted_gaussian", "code_std",
              "grid", "codes_used_test", "perplexity", "bits_per_image", "kl_per_dim")
SPRITES = ["rec", "beta", "prior", "grid_ae2", "grid_vae2", "interp",
           "sd_p01_cat_orig", "sd_p01_cat_rec", "sd_p01_cat_blur", "sd_p04_hubble_orig", "sd_p04_hubble_rec",
           "sd_p04_hubble_blur", "sd_s03_text_orig", "sd_s03_text_rec", "sd_s03_text_blur",
           "sd_dec_right", "sd_dec_forgot_divide", "sd_dec_divided_raw",
           "sd_noise_scaled_0", "sd_noise_raw_0", "sd_noise_scaled_300", "sd_noise_raw_300",
           "sd_noise_scaled_600", "sd_noise_raw_600", "sd_noise_scaled_999", "sd_noise_raw_999",
           "sd_i2i_0p18215", "sd_i2i_0p13025", "sd_i2i_1p0", "sd_t2i_div_0p18215", "sd_t2i_div_1p0", "sd_t2i_div_0p13025"]


def main():
    s = open(ROOT_PART).read()
    d = json.loads(s[s.index("=") + 1:s.rindex(";")].strip())
    runs = {}
    for k, v in d["tiny"]["runs"].items():
        runs[k] = {f: v[f] for f in RUN_FIELDS if f in v}
    sd = d["sd_vae"]
    psnr = {k: v["fp32"]["psnr"] for k, v in sd["images"].items()}
    post = [v["posterior_std_mean"] for v in sd["images"].values()]
    lstd = [v["latent_std"] for v in sd["images"].values()]
    L = {"runs": runs, "floor": d["tiny"]["floor"], "pairs": d["tiny"]["pairs"], "scatter": d["scatter"],
         "sd": {"scaling_factor": sd["scaling_factor"], "all16": sd["all16"], "decode_mistakes": sd["decode_mistakes"],
                "noising": sd["noising"], "fp32": sd["fp32"], "fp16": sd["fp16"], "psnr": psnr,
                "post_std_min": min(post), "post_std_max": max(post), "latent_std_min": min(lstd), "latent_std_max": max(lstd),
                "fp16_max_gap": round(max(abs(v["fp16"]["psnr"] - v["fp32"]["psnr"]) for v in sd["images"].values()), 2)},
         "scale": d["sd_scale"], "perc": d["perc"],
         "img": {k: d["img"][k] for k in SPRITES}}
    # derived, with their formulas (shown on the page)
    vq = d["tiny"]["runs"]
    L["derived"] = {
        "snr_ratio": round((1 / sd["scaling_factor"]) ** 2, 1),          # latent 1/0.18215 = 5.49x too large -> SNR x 30.1
        "too_large": round(1 / sd["scaling_factor"], 2),
        "factor_gap_pct": round(100 * abs(sd["all16"]["implied_factor_1_over_std"] - sd["scaling_factor"]) / sd["scaling_factor"], 1),
        "vq_plain_alive200": vq["vq_plain"]["alive_log"][1][1],
        "vq_restart_full_step": vq["vq_restart"]["alive_log"][6][0],
        "ae16_bag": vq["ae16"]["prior_std_normal"]["class_share"][8],
        "ae16_std_min": min(vq["ae16"]["code_std"]), "ae16_std_max": max(vq["ae16"]["code_std"]),
    }
    js = ("// generated by src/absorb_lab.py from the topic root's retired Latent lab data part (src/retired/parts/31_js_lt_0data.js, read only); do not edit\n"
          "window.AVL=" + json.dumps(L, separators=(",", ":")) + ";\n")
    open(os.path.join(HERE, "parts", "22_js_av_1lab.js"), "w").write(js)
    print("22_js_av_1lab.js", len(js), "bytes")


if __name__ == "__main__":
    main()
