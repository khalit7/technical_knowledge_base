"""Writes parts/26_js_ns_scene.js (window.NSS): the few recorded arrays the 3D scenes need that window.NSD does not carry.
  smol: SmolLM2-135M's residual stream on the running text, per layer (embedding, then the 30 layers; the last entry is after
        the final norm), from the root's Inside lab (../../src/inside/out/smol.json, measured on Apple M1 Pro, reused, not rerun):
        largest |entry| with its token and channel, median |entry|, attention weight on token 0 per layer (30 entries, layers 1 to 30), the four largest
        channels at the layer where the massive activation appears.
  tiny: the root's reference tiny GPT (pre-norm, trained) after the embedding and each sub-layer, from this page's
        out/inspect/ref_baseline_s1500.json (analysis/inspect_runs.py): largest |entry|, its token and channel, median |entry|.
Deterministic; check_data.py regenerates it and compares.  python3 make_scene_data.py"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
smol = json.load(open(os.path.join(HERE, "..", "..", "src", "inside", "out", "smol.json")))
ref = json.load(open(os.path.join(HERE, "out", "inspect", "ref_baseline_s1500.json")))
r = smol["resid"]
out = {
    "smol": {"L": smol["L"], "d": smol["d"], "T": smol["T"], "max_abs": r["max_abs"], "max_tok": r["max_tok"], "max_dim": r["max_dim"],
             "median_abs": r["median_abs"], "big_layer": r["big_layer"], "big_dims": r["big_dims"], "sink": smol["sink_layer"],
             "tok": {str(i): smol["tokens"][i] for i in sorted(set(r["max_tok"]))}},
    "tiny": {"points": ref["points"], "max_abs": ref["max_abs"], "max_tok": ref["max_abs_tok"], "max_dim": ref["max_abs_dim"], "median_abs": ref["median_abs"]},
}
s = "// generated by src/make_scene_data.py from the Inside lab's smol.json and out/inspect/ref_baseline_s1500.json; do not edit\nwindow.NSS=" + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n"
open(os.path.join(HERE, "parts", "26_js_ns_scene.js"), "w", encoding="utf-8").write(s)
print("26_js_ns_scene.js", len(s), "bytes")
